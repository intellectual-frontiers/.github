CREATE TABLE IF NOT EXISTS s.person (
  id INTEGER PRIMARY KEY,
  name VARCHAR(100) NOT NULL DEFAULT 'x',
  email TEXT UNIQUE CHECK (email LIKE '%@%'),
  born DATE REFERENCES s.country (code) ON DELETE CASCADE ON UPDATE NO ACTION,
  seen TIMESTAMP WITH TIME ZONE,
  score DECIMAL(5, 2) CONSTRAINT score_ok CHECK (score >= 0),
  CONSTRAINT person_pk PRIMARY KEY (id),
  UNIQUE (email, name),
  FOREIGN KEY (born) REFERENCES country (code) ON DELETE SET NULL,
  CHECK (id > 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS person_name ON person (name DESC, lower(email)) WHERE name IS NOT NULL;
