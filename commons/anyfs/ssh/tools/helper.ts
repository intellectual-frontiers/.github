// Spec: 0002-anyfs-ssh-helper FR-001
/**
 * Makes `src/helper/posix.ts` from the script `src/helper/posix.sh`: the script as the text the library carries, and its SHA-256, which is the one hash the store trusts. The script is the source; the
 * module is made from it, never edited.
 *
 * ```sh
 * bun tools/helper.ts           write src/helper/posix.ts
 * bun tools/helper.ts --check   exit 1 where the module is not what the script makes
 * ```
 *
 * @module
 */
import process from "node:process";
import { sha256 } from "@intellectual-frontiers/crypto/sha256";
import { fs, path } from "@intellectual-frontiers/system";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..");
const SCRIPT = path.join(ROOT, "src/helper/posix.sh");
const MODULE = path.join(ROOT, "src/helper/posix.ts");

/** The module that the script makes. */
export async function moduleOf(script: string): Promise<string> {
  return [
    "// Spec: 0002-anyfs-ssh-helper FR-001",
    "// AUTO-GENERATED by bun tools/helper.ts from src/helper/posix.sh: edit the script, never this file.",
    "/**",
    " * The helper of the posix dialect: the script that runs on the host, and its SHA-256 as the library knows it.",
    " *",
    " * @module",
    " */",
    "",
    "/** The text of the helper script. */",
    `export const POSIX_HELPER: string = ${JSON.stringify(script)};`,
    "",
    "/** The SHA-256 of the helper script, in hex: the one hash that the store trusts on a host. */",
    `export const POSIX_HELPER_SHA256 = ${JSON.stringify(await sha256(script))};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const made = await moduleOf(await fs.readTextFile(SCRIPT));
  if (process.argv.includes("--check")) {
    const have = (await fs.exists(MODULE)) ? await fs.readTextFile(MODULE) : "";
    if (have !== made) {
      process.stdout.write("src/helper/posix.ts is not what src/helper/posix.sh makes; run: bun tools/helper.ts\n");
      process.exitCode = 1;
    }
  } else {
    await fs.writeTextFile(MODULE, made);
    process.stdout.write("wrote src/helper/posix.ts\n");
  }
}
