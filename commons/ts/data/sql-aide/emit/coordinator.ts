/**
 * The coordinator: a model emitted as several files, in order, each saying where it came from, and scripts that carry typed variables
 * in their dialect's own way (commons 0006-sql-aide FR-015, FR-016). It writes nothing: what it returns is text, and a runtime module
 * keeps it.
 *
 * @module
 */
import { type Sha256, sha256 } from "../../../kernel/mod.ts";
import type { Domain } from "../algebra/domain.ts";
import { type EmitContext, emitted } from "./context.ts";
import type { Expr } from "./expr.ts";
import { type AnySql, byDialect, type Chunk, chunkOf, chunkText, renderUnchecked, sql, type Sql } from "./sql.ts";

/** The version of the library, written into what it emits. */
export const VERSION = "0.1.0";

/** One file of a model: where it goes, the module it is made from and what it holds. */
export interface FilePart {
  /** The path of the file, relative to where the model is kept. */
  readonly path: string;
  /** The TypeScript module the content comes from, as a person would find it. */
  readonly module: string;
  /** What the file holds. */
  readonly content: AnySql;
}

/** A file as emitted: its path, its text with the provenance header, and the hash of the text below the header. */
export interface EmittedFile {
  /** The path of the file. */
  readonly path: string;
  /** The whole text: header, then body. */
  readonly text: string;
  /** The SHA-256 of the body. */
  readonly sha256: Sha256;
}

/**
 * Emits the files of a model for a context, in the order given. Each begins with a comment that names the library and its version, the
 * dialect and execution context, the module it came from and the SHA-256 of its body, so that a file can be traced and a change seen.
 *
 * @param parts - the files, in the order they must be loaded
 * @param ctx - the context to render for
 */
export async function emitFiles(parts: readonly FilePart[], ctx: EmitContext): Promise<readonly EmittedFile[]> {
  const out: EmittedFile[] = [];
  for (const part of parts) {
    const body = `${renderUnchecked(part.content, ctx)}\n`;
    const hash = await sha256(body);
    const header = [
      `-- Generated by IFC SQL Aide ${VERSION} for ${ctx.dialect.name} (${ctx.execution}) from ${part.module}.`,
      `-- Body SHA-256 ${hash}. Do not edit this file: change the model and emit it again.`,
      "",
    ].join("\n");
    out.push({ path: part.path, text: `${header}\n${body}`, sha256: hash });
    emitted(ctx, { kind: "file", path: part.path, sha256: hash });
  }
  return out;
}

/** A variable of a script: an expression of its type whose value is set where the script is run. */
export interface Variable<T> extends Expr<T, never, "postgres" | "sqlite" | "duckdb"> {
  /** The variable's name. */
  readonly variable: string;
  /** The statement, or client command, that sets the variable to a value in a script. */
  readonly set: (value: AnySql) => Sql<"statement", unknown, never, "postgres" | "sqlite" | "duckdb">;
}

/**
 * A typed variable of a script, written as each dialect's own client does: `:'name'` for `psql`, `:name` for the `sqlite3` shell,
 * `getvariable('name')` for DuckDB.
 *
 * @param name - the variable's name, letters, digits and underscores
 * @param _domain - the type of its values
 */
export function variable<T>(name: string, _domain: Domain<T>): Variable<T> {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) throw new Error(`${name} is not a name a script variable can have`);
  const use = byDialect({
    postgres: sql("expression", () => [chunkText(`:'${name}'`)]),
    sqlite: sql("expression", () => [chunkText(`:${name}`)]),
    duckdb: sql("expression", () => [chunkText(`getvariable('${name}')`)]),
  });
  const line = (before: string, value: AnySql, after: string): AnySql =>
    sql("statement", (): Chunk[] => [chunkText(before), chunkOf(value), chunkText(after)]);
  return {
    sqlKind: "expression",
    chunks: use.chunks,
    variable: name,
    set: (value) =>
      byDialect(
        {
          postgres: line(`\\set ${name} `, value, ""),
          sqlite: line(`.parameter set :${name} `, value, ""),
          duckdb: line(`SET VARIABLE ${name} = `, value, ";"),
        },
        "statement",
      ),
  };
}
