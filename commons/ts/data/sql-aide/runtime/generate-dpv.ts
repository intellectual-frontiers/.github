/**
 * Writes `govern/dpv.auto.ts` from the Personal Data extension of the W3C Data Privacy Vocabulary, as its publishers give it in CSV
 * (commons 0006-sql-aide FR-026): the library names the vocabulary's own terms and invents none.
 *
 * Run it with the CSV downloaded from `https://w3c-cg.github.io/dpv/2.3/pd/pd.csv`:
 * `bun sql-aide/runtime/generate-dpv.ts pd.csv`.
 *
 * @module
 */
import { formatCsvError, parseCsvRecords, sha256 } from "../../../kernel/mod.ts";
import { fs, proc } from "../../../runtime/mod.ts";

const SOURCE = "https://w3c-cg.github.io/dpv/2.3/pd/pd.csv";
const VERSION = "2.3";

const path = proc.args[0];
if (path === undefined) {
  console.error("usage: generate-dpv.ts <pd.csv>");
  proc.exit(2);
}
const csv = await fs.readTextFile(path);
const parsed = parseCsvRecords(csv);
if (parsed.kind === "err") {
  console.error(formatCsvError(parsed.error));
  proc.exit(2);
}
const kindOf = (types: string): string =>
  types.includes("#SpecialCategoryPersonalData")
    ? "SpecialCategoryPersonalData"
    : types.includes("#SensitivePersonalData")
      ? "SensitivePersonalData"
      : "PersonalData";
const terms = parsed.value
  .filter((r) => r["type"] === "class" && (r["iri"] ?? "").startsWith("https://w3id.org/dpv/pd#"))
  .map((r) => ({ term: r["term"] ?? "", label: r["label"] ?? "", kind: kindOf(r["dpvtype"] ?? "") }))
  .filter((t) => /^[A-Za-z][A-Za-z0-9]*$/.test(t.term))
  .sort((a, b) => (a.term < b.term ? -1 : a.term > b.term ? 1 : 0));

const lines = [
  "/**",
  " * AUTO-GENERATED by sql-aide/runtime/generate-dpv.ts; do not edit: run the tool on the vocabulary's CSV.",
  " *",
  ` * The terms of the Personal Data extension of the W3C Data Privacy Vocabulary ${VERSION} (DPV-PD), a Final Community Group Report of the`,
  " * W3C Data Privacy Vocabularies and Controls Community Group, each with how DPV classes it: personal data, sensitive personal data or a",
  " * special category (commons 0006-sql-aide FR-026).",
  " *",
  ` * Source: ${SOURCE}`,
  ` * Source SHA-256: ${await sha256(csv)}`,
  " *",
  " * @module",
  " */",
  "",
  "/** The version of the vocabulary these terms are from. */",
  `export const DPV_VERSION = "${VERSION}";`,
  "",
  "/** The namespace of DPV, where the three classes of personal data are. */",
  'export const DPV_NAMESPACE = "https://w3id.org/dpv#";',
  "",
  "/** The namespace of DPV-PD, where the categories are. */",
  'export const PD_NAMESPACE = "https://w3id.org/dpv/pd#";',
  "",
  "/** Every category of DPV-PD by its term, with its label and its class in DPV. */",
  "export const pd = {",
  ...terms.map((t) => `  ${t.term}: { label: ${JSON.stringify(t.label)}, kind: "${t.kind}" },`),
  "} as const;",
  "",
];
const out = new URL("../govern/dpv.auto.ts", import.meta.url);
await fs.writeTextFile(out, lines.join("\n"));
console.log(`${terms.length} terms written`);
