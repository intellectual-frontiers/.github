proves(["0014-runner-github-actions FR-007"], "a finished run becomes one receipt with the plan hash, the address and the digest, the status says how it ended, and what is not a finished run of a plan is refused", () => {
  const ok = must(receiptFromRun(run(), { recordedBy: "person" }));
  assertEquals(ok.event, { kind: "receipt", plan: "a".repeat(64), ref: URL, status: 0, log: "b".repeat(64) });
  assertEquals(ok.refused, []);
  const status = (over: Partial<GithubRun>) => must(receiptFromRun(run(over), { recordedBy: "tool" })).event.status;
  assertEquals(status({ conclusion: "failure" }), 1);
  assertEquals(status({ conclusion: "timed_out" }), 124);
  assertEquals(status({ conclusion: "cancelled" }), 130);
  assertEquals(status({ jobs: { a: "success", b: "failure" } }), 1, "a job that failed in a run that says success");
  assertEquals(status({ jobs: { a: "success", b: "skipped", c: "neutral" } }), 0);
  assertEquals(status({ conclusion: "action_required" }), 1);
  const refused = (over: Partial<GithubRun>) => {
    const r = receiptFromRun(run(over), { recordedBy: "tool" });
    assert(r.kind === "err" && r.error.every((f) => f.code === "E-WL-RUNNER-RECEIPT-INVALID"), JSON.stringify(r));
  };
  refused({ conclusion: null });
  refused({ url: "https://github.com/synthetic-org-01/synthetic-repo-01" });
  refused({ url: "http://github.com/synthetic-org-01/synthetic-repo-01/actions/runs/1" });
  refused({ logDigest: "xyz" });
  refused({ plan: "A".repeat(64) });
  refused({ jobs: { a: null } });
  // matched to its hand-off by the plan hash, by the fold of the core
  const hand = must(makeRunner(1, { kind: "handoff", runner: "github-actions", plan: "a".repeat(64) }, PERSON));
  const rec = (k: number, plan: string) => must(makeRunner(k, must(receiptFromRun(run({ plan }), { recordedBy: "person" })).event, PERSON));
  assertEquals(foldHandoff("graph", ITEM, [hand, rec(2, "a".repeat(64))]).outcome, "completes");
  const wrong = foldHandoff("graph", ITEM, [hand, rec(3, "c".repeat(64))]);
  assertEquals(wrong.outcome, undefined);
  assert(wrong.refused[0]?.reason.includes("E-WL-RUNNER-RECEIPT-UNMATCHED"));
  assertEquals(handoffEvent({ runner: GH, hash: "a".repeat(64) }), { kind: "handoff", runner: "github-actions", plan: "a".repeat(64) });
});

const makeRunner = (k: number, e: RunnerEvent, actor: typeof PERSON | typeof AGENT) => makeRunnerEvent({ id: eventId(k), item: ITEM, at: NOW, actor }, "graph", e);

proves(["0014-runner-github-actions FR-008"], "an approval of an environment counts only where a person gave it and a person records the receipt, and an agent never approves", async () => {
  const approvals: GithubRun["approvals"] = [{ gate: "approve-publish", by: { login: "synthetic-person-01", kind: "user" }, state: "approved" }];
  const byPerson = must(receiptFromRun(run({ approvals }), { recordedBy: "person" }));
  assertEquals(byPerson.event.approvals, ["approve-publish"]);
  assertEquals(byPerson.refused, []);
  const byApp = must(receiptFromRun(run({ approvals: [{ gate: "approve-publish", by: { login: "synthetic-app-01", kind: "app" }, state: "approved" }] }), { recordedBy: "person" }));
  assertEquals(byApp.event.approvals, undefined);
  assert(byApp.refused.some((f) => f.code === "E-WL-RUNNER-APPROVAL-NOT-PERSON" && f.safety));
  for (const who of ["agent", "tool"] as const) {
    const r = must(receiptFromRun(run({ approvals }), { recordedBy: who }));
    assertEquals(r.event.approvals, undefined, `recorded by ${who}`);
    assert(r.refused.some((f) => f.code === "E-WL-RUNNER-APPROVAL-NOT-PERSON"));
  }
  assertEquals(must(receiptFromRun(run({ approvals: [{ gate: "approve-publish", by: { login: "synthetic-person-01", kind: "user" }, state: "rejected" }] }), { recordedBy: "person" })).event.approvals, undefined);
  // the fold of the core refuses the approvals of a receipt that an agent recorded, whatever the ingest did
  const hand = must(makeRunner(1, { kind: "handoff", runner: "github-actions", plan: "a".repeat(64) }, PERSON));
  const forced = must(makeRunner(2, { ...byPerson.event }, AGENT));
  const state = foldHandoff("graph", ITEM, [hand, forced]);
  assertEquals(state.approved, []);
  assert(state.refused.some((r) => r.reason.includes("E-WL-RUNNER-APPROVAL-NOT-PERSON")));
  assertEquals(foldHandoff("graph", ITEM, [hand, must(makeRunner(3, { ...byPerson.event }, PERSON))]).approved, ["approve-publish"]);
});

