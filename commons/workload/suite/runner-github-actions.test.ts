const SCHEMA = path.join(ROOT, "..", "libraries", "src", "workflows", "schema", "github-workflow.schema.json");
const CHECK = `
import json, sys, yaml
from jsonschema import Draft7Validator
schema = json.load(open(sys.argv[1]))
v = Draft7Validator(schema)
def doc(text):
    d = yaml.safe_load(text)
    return {("on" if k is True else k): x for k, x in d.items()}
out = {f.split("/")[-1]: [e.message for e in v.iter_errors(doc(open(f).read()))] for f in sys.argv[3:]}
broken = doc("name: x\\non:\\n  push:\\njobs:\\n  a:\\n    runs-on: ubuntu-latest\\n    steps:\\n      - run: x\\n        bogus: 1\\n")
out["broken"] = len(list(v.iter_errors(broken)))
print(json.dumps(out))
`;

proves(["0014-runner-github-actions FR-011"], "the emitted workflows are valid by the JSON Schema of GitHub workflows, read by a validator that is not this repository's", async () => {
  const python = have("python3") ? "python3" : undefined;
  const ready = python !== undefined && spawnSync(python, ["-c", "import jsonschema, yaml"]).status === 0;
  if (!ready) return skipped("the validation of the workflows by the JSON Schema", "python3 with jsonschema and PyYAML");
  const { outputs } = await import("../tools/runners.ts");
  const made = await outputs();
  const files = Object.keys(made).filter((f) => f.endsWith(".yml")).map((f) => path.join(ROOT, "..", "..", f));
  assertEquals(files.length, 3);
  const r = spawnSync("python3", ["-c", CHECK, SCHEMA, "x", ...files], { encoding: "utf8" });
  assertEquals(r.status, 0, r.stderr);
  const out: Record<string, readonly string[] | number> = JSON.parse(r.stdout);
  assert((out["broken"] as number) > 0, "a step with a key GitHub does not know is refused by the schema");
  for (const f of files) assertEquals(out[path.basename(f)], [], path.basename(f));
});

