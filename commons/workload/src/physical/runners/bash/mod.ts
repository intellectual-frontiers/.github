/**
 * The emitter of the runner `bash`: it renders a plan of calls as a script of modern Bash, version 5 or later, and nothing else. The script fails fast under an older Bash, sets `set -Eeuo pipefail` and
 * `shopt -s inherit_errexit`, and is only calls to the pinned verb command by verb id (through one function that takes an array, never a string), a loop over an array literal of a fixed list, and the order of the steps. Every
 * value is single-quoted, an input of the run is read from its environment variable with the unset check of `set -u`, a credential is a comment that names it, and an `EXIT` trap writes one receipt line to the standard
 * error. The script holds no `eval`, no command substitution and no secret. Pure; it imports no other emitter.
 *
 * @example
 * ```ts
 * import { emitter } from "@intellectual-frontiers/workload/runners/bash";
 * // emitter.render(plan, hash, { cli: "workload" })
 * ```
 *
 * @module
 */
import { type Call, type CallArg, type CallPlan, RUNNERS } from "@intellectual-frontiers/workload/governance";
import { type EmitterImpl, inputVariable, linuxSchedule } from "@intellectual-frontiers/workload/logical";

const runner = RUNNERS.get("bash");
if (runner === undefined) throw new Error("the runner bash is registered by the core");

/** A text as one single-quoted word: a single quote inside it ends the quote, is written escaped and opens the quote again. */
const q = (text: string): string => `'${text.replaceAll("'", "'\\''")}'`;

const arg = (a: CallArg): string => (a.value.kind === "literal" ? q(`${a.name}=${a.value.text}`) : `"${a.name}=\${${inputVariable(a.value.name)}}"`);

const call = (c: Call, indent: string, member: boolean): string => `${indent}run_verb ${q(c.step)} ${q(c.verb)}${c.args.map((a) => ` --in ${arg(a)}`).join("")}${member ? ' --member "${member}"' : ""}`;

/** The script of a plan of calls. */
const render = (plan: CallPlan, hash: string, options: { readonly cli: string }): string => {
  const lines: string[] = [
    "#!/usr/bin/env bash",
    `# Generated by commons/workload from the plan of ${plan.workload} ${plan.version} (the form ${plan.form}); do not edit it: regenerate it.`,
    "# It is only calls to the pinned verb command by verb id, loops over fixed lists and the order of the steps.",
    `# plan: ${hash}`,
    ...plan.credentials.map((c) => `# credential: ${c} (a name only: the verb command reads it from the environment)`),
    ...plan.inputs.map((i) => `# input: ${i} (read from ${inputVariable(i)})`),
    "",
    "if ((BASH_VERSINFO[0] < 5)); then",
    "  printf 'workload: this script needs bash 5 or later\\n' >&2",
    "  exit 70",
    "fi",
    "set -Eeuo pipefail",
    "shopt -s inherit_errexit",
    "",
    `readonly plan_hash=${q(hash)}`,
    `readonly workload_id=${q(plan.workload)}`,
    "readonly runner_id='bash'",
    `readonly cli=(${q(options.cli)})`,
    "current_step='none'",
    "",
    "on_exit() {",
    "  local status=\"$1\"",
    "  printf 'workload.receipt/1 plan=%s workload=%s runner=%s status=%d step=%s\\n' \"${plan_hash}\" \"${workload_id}\" \"${runner_id}\" \"${status}\" \"${current_step}\" >&2",
    "}",
    "trap 'on_exit \"$?\"' EXIT",
    "",
    "run_verb() {",
    "  current_step=\"$1\"",
    "  shift",
    "  \"${cli[@]}\" verb \"$@\"",
    "}",
    "",
  ];
  for (const s of plan.steps) {
    if (s.kind === "call") {
      lines.push(`# step ${s.step}: ${s.as}, ${s.autonomy}`, call(s, "", false));
    } else {
      lines.push(`# step ${s.step}: each over ${s.over}, ${s.autonomy}`, `members=(${s.members.map(q).join(" ")})`, 'for member in "${members[@]}"; do');
      for (const c of s.body) lines.push(`  # step ${c.step}: ${c.as}, ${c.autonomy}`, call(c, "  ", true));
      lines.push("done");
    }
  }
  lines.push("", "current_step='done'", "");
  return lines.join("\n");
};

/** The emitter. A schedule is a cron line and a systemd timer with its service, which only start the script by its path; Windows has none. */
export const emitter: EmitterImpl = { runner, extension: "sh", render, schedule: (plan, hash, trigger, options) => linuxSchedule("bash", "sh", (path) => ["/usr/bin/env", "bash", path], plan, hash, trigger, options.schedule ?? {}) };
