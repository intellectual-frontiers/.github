/**
 * The emitter of the runner `pwsh`: it renders a plan of calls as a script of modern PowerShell, version 7 or later, and nothing else. The script requires 7.0, sets strict mode and `$ErrorActionPreference = 'Stop'`, and is
 * only calls to the pinned verb command by verb id (through one function that gives the native command an array of arguments and checks `$LASTEXITCODE` after it), a `foreach` over an array literal of a fixed list and the
 * order of the steps. Every value is a single-quoted string, an input of the run is read from its environment variable and a missing one stops the script, a credential is a comment that names it, and a `finally` block
 * writes one receipt line to the error stream. The script holds no `Invoke-Expression` and no secret. Pure; it imports no other emitter.
 *
 * @example
 * ```ts
 * import { emitter } from "@intellectual-frontiers/workload/runners/pwsh";
 * // emitter.render(plan, hash, { cli: "workload" })
 * ```
 *
 * @module
 */
import { type Call, type CallArg, type CallPlan, RUNNERS } from "@intellectual-frontiers/workload/governance";
import { type EmitterImpl, inputVariable, linuxSchedule } from "@intellectual-frontiers/workload/logical";

const runner = RUNNERS.get("pwsh");
if (runner === undefined) throw new Error("the runner pwsh is registered by the core");

/** A text as one single-quoted string: a single quote inside it is doubled. */
const q = (text: string): string => `'${text.replaceAll("'", "''")}'`;

const arg = (a: CallArg): string => (a.value.kind === "literal" ? q(`${a.name}=${a.value.text}`) : `(${q(`${a.name}=`)} + (Get-Item -LiteralPath ${q(`Env:${inputVariable(a.value.name)}`)}).Value)`);

const call = (c: Call, indent: string, member: boolean): string => `${indent}Invoke-Verb -Step ${q(c.step)} -Verb ${q(c.verb)} -VerbArguments @(${[...c.args.flatMap((a) => ["'--in'", arg(a)]), ...(member ? ["'--member'", "$member"] : [])].join(", ")})`;

/** The script of a plan of calls. */
const render = (plan: CallPlan, hash: string, options: { readonly cli: string }): string => {
  const lines: string[] = [
    "#Requires -Version 7.0",
    `# Generated by commons/workload from the plan of ${plan.workload} ${plan.version} (the form ${plan.form}); do not edit it: regenerate it.`,
    "# It is only calls to the pinned verb command by verb id, loops over fixed lists and the order of the steps.",
    `# plan: ${hash}`,
    ...plan.credentials.map((c) => `# credential: ${c} (a name only: the verb command reads it from the environment)`),
    ...plan.inputs.map((i) => `# input: ${i} (read from ${inputVariable(i)})`),
    "",
    "Set-StrictMode -Version Latest",
    "$ErrorActionPreference = 'Stop'",
    "",
    `$PlanHash = ${q(hash)}`,
    `$WorkloadId = ${q(plan.workload)}`,
    "$RunnerId = 'pwsh'",
    `$Cli = ${q(options.cli)}`,
    "$script:CurrentStep = 'none'",
    "$script:Status = 0",
    "",
    "function Invoke-Verb {",
    "    param(",
    "        [Parameter(Mandatory)] [string] $Step,",
    "        [Parameter(Mandatory)] [string] $Verb,",
    "        [string[]] $VerbArguments = @()",
    "    )",
    "    $script:CurrentStep = $Step",
    "    & $Cli 'verb' $Verb @VerbArguments",
    "    if ($LASTEXITCODE -ne 0) {",
    "        $script:Status = $LASTEXITCODE",
    "        throw ('workload: the step {0} failed with status {1}' -f $Step, $LASTEXITCODE)",
    "    }",
    "}",
    "",
    "try {",
  ];
  for (const s of plan.steps) {
    if (s.kind === "call") {
      lines.push(`    # step ${s.step}: ${s.as}, ${s.autonomy}`, call(s, "    ", false));
    } else {
      lines.push(`    # step ${s.step}: each over ${s.over}, ${s.autonomy}`, `    foreach ($member in @(${s.members.map(q).join(", ")})) {`);
      for (const c of s.body) lines.push(`        # step ${c.step}: ${c.as}, ${c.autonomy}`, call(c, "        ", true));
      lines.push("    }");
    }
  }
  lines.push(
    "    $script:CurrentStep = 'done'",
    "}",
    "catch {",
    "    if ($script:Status -eq 0) { $script:Status = 1 }",
    "    [Console]::Error.WriteLine($_.Exception.Message)",
    "}",
    "finally {",
    "    [Console]::Error.WriteLine(('workload.receipt/1 plan={0} workload={1} runner={2} status={3} step={4}' -f $PlanHash, $WorkloadId, $RunnerId, $script:Status, $script:CurrentStep))",
    "}",
    "exit $script:Status",
    "",
  );
  return lines.join("\n");
};

/** The emitter. A schedule is a cron line and a systemd timer with its service on Linux only: PowerShell 7 has no Scheduled Job, and Windows Task Scheduler is not supported yet (`E-WL-RUNNER-EMIT-UNSUPPORTED`). */
export const emitter: EmitterImpl = { runner, extension: "ps1", render, schedule: (plan, hash, trigger, options) => linuxSchedule("pwsh", "ps1", (path) => ["/usr/bin/env", "pwsh", "-NoProfile", "-NonInteractive", "-File", path], plan, hash, trigger, options.schedule ?? {}) };
