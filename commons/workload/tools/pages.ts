// Spec: 0004-workload-projections FR-006
/**
 * The generated pages of the commons for the workloads: the forms, the catalogs of errors, each starter workload with everything made from it (its skill, checklist, implementation statement, rules and scenario) and the dialects
 * with what each writes. `bun commons/workload/tools/pages.ts` writes them, `--check` writes nothing and says which differ. They are made from the code, so a page cannot say what the code does not.
 *
 * @module
 */
import { type Catalog, type CatalogEntry, DIALECTS, FORM_IDS, FORMS, RUNNER_CAPABILITIES, RUNNERS, TRIGGER_KINDS } from "../src/governance/mod.ts";
import { checklist, lacksOf, projectAll, rulesOf, scenario, skillMd, statements } from "../src/logical/mod.ts";
import { bootstrapFleet, FIXTURES } from "../src/logical/forms/runbook/mod.ts";
import { CATALOGS, DIALECT_IMPLS, emitWorkload, runnerNeedsOfWorkload, STARTERS, viewOfWorkload } from "../src/physical/mod.ts";
import { fs, path, proc } from "@intellectual-frontiers/system";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..", "..", "..");
const GUIDES = "commons/docs/guides";
const NOTE = "Generated by `commons/workload/tools/pages.ts` from the code of the library `workload`; do not edit it.";

const row = (e: CatalogEntry): string => `| \`${e.code}\` | ${e.title} | ${e.fixer} | ${e.what} | ${e.fix} |`;
const fence = (lang: string, text: string): string[] => ["```" + lang, text.trimEnd(), "```", ""];
const cap = (c: string): string => `${c[0]?.toUpperCase() ?? ""}${c.slice(1)}`;

function section(c: Catalog): string {
  const parts = c.concepts.map((concept) => {
    const entries = Object.values(c.entries).filter((e) => e.concept === concept);
    return entries.length === 0 ? "" : `### ${cap(concept)}\n\n| Code | What happened | Who fixes it | What it says | The fix |\n|---|---|---|---|---|\n${entries.map(row).join("\n")}\n`;
  });
  return [`## The catalog of ${c.owner}, \`${c.prefix}\``, "", ...parts].join("\n");
}

function errors(): string {
  return [
    "# Errors of the workloads, and what to do",
    "",
    NOTE,
    "",
    "Every problem the static check of a workload finds has one code in a closed catalog: the core has `E-WL-<CONCEPT>-<KIND>` for what is true of every form, and each form has its own prefix. Every finding is an error: a workload with a finding is not planned and not run. **Who fixes it:** `agent` means the author of the workload can run the fix; `person` means a person must decide (an authority, the choice of a dialect); `environment` means the owner of the pinned packages; `ci` means a rebuild.",
    "",
    "**A failure that is in none of these** is `E-WL-UNKNOWN`: classify it by adding an entry, a check and a test, and documenting it, in one change.",
    "",
    ...CATALOGS.map(section),
  ].join("\n");
}

function forms(): string {
  return [
    "# Forms and triggers of a workload",
    "",
    NOTE,
    "",
    "A workload here is a unit of operated work, not running software. Two axes are orthogonal. The **form** says what kind of work it is and how it executes; the **dialect** says how a harness or a person receives it, and is never a form. What starts a workload is its **trigger**, a field of it and never a form.",
    "",
    "| Form | Status | What it is |",
    "|---|---|---|",
    ...FORM_IDS.map((id) => `| \`${id}\` | ${FORMS[id].status} | ${FORMS[id].summary} |`),
    "",
    "A form is built where a second concrete user needs it. A reserved form is a named slot with no code:",
    "",
    ...FORM_IDS.flatMap((id) => {
      const f = FORMS[id];
      return f.status === "reserved" ? [`- \`${id}\`: ${f.criteria}`] : [];
    }),
    "",
    `The triggers are ${TRIGGER_KINDS.map((t) => `\`${t}\``).join(", ")}. A drill or a game day is a runbook with a schedule trigger and an expected outcome.`,
    "",
  ].join("\n");
}

function starter(index: number): string {
  const w = STARTERS[index];
  if (w === undefined) return "";
  const view = viewOfWorkload(w);
  const rules = rulesOf([view]);
  const files = projectAll([view], DIALECT_IMPLS)["claude-code"] ?? [];
  const settings = files.find((f) => f.path === ".claude/workload.settings.json")?.text ?? "";
  return [
    `# The ${w.title.toLowerCase()}, and what is made from it`,
    "",
    NOTE,
    "",
    `\`${w.id}\` is a starter workload of the form \`${w.form}\`: ${w.summary} An agent or a person orchestrates; every effect is a deterministic verb of the pinned packages, a \`judge\` only proposes, and what a person must do is a gate. Everything below is made from the one typed workload, with synthetic names.`,
    "",
    "## The skill (Claude Code)",
    "",
    ...fence("markdown", skillMd(view)),
    "## The checklist (a person)",
    "",
    ...fence("markdown", checklist(view)),
    "## The implementation statements (an auditor)",
    "",
    ...fence("markdown", statements([view])),
    "## The rules derived from the effects",
    "",
    `Allowed: ${rules.allow.length}. Asked: ${rules.ask.length}. Denied: ${rules.deny.length}.`,
    "",
    ...fence("json", settings),
    "## The scenario",
    "",
    ...fence("gherkin", scenario(view)),
  ].join("\n");
}

function harness(): string {
  const views = STARTERS.map(viewOfWorkload);
  return [
    "# Harnesses and dialects",
    "",
    NOTE,
    "",
    "A workload never names a harness. A harness is a dialect, and the set of dialects is open: a harness added later is one entry registered with a renderer, with no change to any workload. A fleet owns a `HarnessPolicy` (a default, a choice by workload, a choice by form, a preference by operator); a run resolves its dialect as the explicit choice, then the operator's preference, then the choice for the workload, then the choice for its form, then the fleet's default, and a dialect that cannot carry the workload is refused with `E-WL-HARNESS-UNSUITABLE`.",
    "",
    "| Dialect | Held by | Reads a skill file | What it writes for the starter workloads |",
    "|---|---|---|---|",
    ...DIALECTS.list().map((d) => `| \`${d.id}\` | ${d.holder} | ${d.skillFiles ? "yes" : "no"} | ${(DIALECT_IMPLS.find((i) => i.info.id === d.id)?.render(views) ?? []).map((f) => `\`${f.path}\``).join(", ")} |`),
    "",
    "Switching the dialect changes only these files. The nodes, the effects and the autonomy derived for each node are the same for every dialect, and for every form.",
    "",
    "The format of each harness is the one its own documentation gives; where a format could not be verified, the dialect writes the conservative one and says so in the specification (0004-workload-projections FR-007).",
    "",
  ].join("\n");
}

const CAPABILITIES: Readonly<Record<(typeof RUNNER_CAPABILITIES)[number], string>> = {
  calls: "a call of a verb by its id, with typed inputs",
  "fan-out": "a loop over a fixed list",
  interactive: "a stop for a person",
  judge: "a bounded judgement of an agent",
  approval: "the approval of a gate by a person, ingested as evidence",
  logic: "a computation of typed TypeScript: a branch, a diff, a plan",
  compensate: "the undo of a step that succeeded",
  destroy: "a destroy of a durable, git or external store",
};

async function runners(): Promise<string> {
  const known = [...STARTERS, ...FIXTURES];
  const artifacts = await Promise.all(FIXTURES.flatMap((w) => RUNNERS.list().filter((r) => r.kind === "integration").map(async (r) => ({ w, r, made: await emitWorkload(w, r.id, { fleet: bootstrapFleet }) }))));
  return [
    "# Runners: how a plan is carried out",
    "",
    NOTE,
    "",
    "A **runner** is how a plan is carried out. The **form** says what the work is, the **dialect** says how a harness or a person receives it, and the **runner** says what carries it out. A **native** runner is the TypeScript of the library: it interprets the plan on Bun or Node, is interactive, is the default and records the events of a run directly. An **integration** runner compiles the plan into an artifact, a script, that a foreign system runs, and then hands it off: the library keeps the plan, the policy and the evidence, and not the run. (Where this documentation names the machines of GitHub it calls them **hosts**, so that they are not confused with runners.)",
    "",
    "A workload never names its runner. A fleet owns a `RunnerPolicy` (a default, which is `native`, a choice by workload, a choice by form and a preference by operator); a run resolves its runner as the explicit choice, then the operator's preference, then the choice for the workload, then the choice for its form, then the default. A runner that lacks something the workload needs is refused with `E-WL-RUNNER-UNSUITABLE`, and the run is never moved to another runner by itself. The autonomy derived for each node is the same under every runner.",
    "",
    "| Runner | Kind | What it is | What it can carry |",
    "|---|---|---|---|",
    ...RUNNERS.list().map((r) => `| \`${r.id}\` | ${r.kind} | ${r.title} | ${r.capabilities.map((c) => `\`${c}\``).join(", ")} |`),
    "",
    "## What a workload needs of a runner",
    "",
    "A form derives the needs of its workload from its nodes, and never has them declared:",
    "",
    ...RUNNER_CAPABILITIES.map((c) => `- \`${c}\`: ${CAPABILITIES[c]}.`),
    "",
    "A call of a verb or a check needs `calls`; an `each` needs `fan-out`; an `ask` needs `interactive`; a `judge` needs `judge`; a gate needs `approval`; a `branch`, a diff and a plan need `logic`; an `undo` needs `compensate`; a destroy of a durable, git or external store needs `destroy`, unless a gate guards it and then it needs `approval`; any other node that is `human-only` and that no gate guards needs `interactive`. Only the native runner has `interactive`, `judge`, `logic`, `compensate` and `destroy`, so a workload with an ask, a judge or an ungated destroy of a durable store is run by the native runner.",
    "",
    `| Workload | Form | ${RUNNERS.list().map((r) => `\`${r.id}\``).join(" | ")} |`,
    `|---|---|${RUNNERS.list().map(() => "---").join("|")}|`,
    ...known.map((w) => {
      const needs = runnerNeedsOfWorkload(w);
      return `| \`${w.id}\` | ${w.form} | ${RUNNERS.list().map((r) => (lacksOf(needs, r).length === 0 ? "can carry it" : `lacks ${[...new Set(lacksOf(needs, r).map((n) => n.capability))].join(", ")}`)).join(" | ")} |`;
    }),
    "",
    "## What an artifact is",
    "",
    "An artifact obeys the thin emit rule: it is only a sequence of calls to the pinned verb command by verb id, a loop over a fixed list and the order of the steps. It holds no expression, no inline logic, no `eval`, no command built from a string and no secret; a credential is only a name, and the verb command reads it from the environment. All meaning stays in typed TypeScript. The emitters target only Bash 5 or later and PowerShell 7 or later. The artifact carries the hash of its plan, the same for both emitters, and writes one receipt line when it ends; ingest pulls the receipt and the library records it as a `receipt` event beside the `handoff` event that carried the same plan hash. `bun commons/workload/tools/runners.ts --check` regenerates the artifacts and compares: a hand-edited artifact is `E-WL-RUNNER-DRIFT`.",
    "",
    ...artifacts.flatMap(({ w, r, made }) => (made.kind === "ok" ? [`## The artifact of \`${w.id}\` for \`${r.id}\``, "", ...fence(r.id === "bash" ? "bash" : "powershell", made.value.text)] : [])),
  ].join("\n");
}

/** Every file this writes, with its text. */
export async function outputs(): Promise<Readonly<Record<string, string>>> {
  return {
    [`${GUIDES}/workload-runners.auto.md`]: await runners(),
    [`${GUIDES}/workload-forms.auto.md`]: forms(),
    [`${GUIDES}/workload-errors.auto.md`]: errors(),
    ...Object.fromEntries(STARTERS.map((w, i) => [`${GUIDES}/workload-${w.id}.auto.md`, starter(i)])),
    [`${GUIDES}/workload-harness.auto.md`]: harness(),
  };
}

if (import.meta.main) {
  const check = proc.args.includes("--check");
  const stale: string[] = [];
  for (const [file, text] of Object.entries(await outputs())) {
    const full = path.join(ROOT, file);
    const have = (await fs.exists(full)) ? await fs.readTextFile(full) : undefined;
    if (have === text) continue;
    stale.push(file);
    if (!check) await fs.writeTextFile(full, text);
  }
  if (check && stale.length > 0) {
    console.error(`stale: ${stale.join(", ")}: run bun commons/workload/tools/pages.ts`);
    proc.exit(1);
  }
  console.log(check ? "the pages are current" : `wrote ${stale.length} files`);
}
