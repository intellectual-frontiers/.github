/**
 * The installers, written from the pins (commons ergonex 0004-onboarding FR-008, commons 0031-install-locations FR-006): `installerSh` for Linux and macOS and `installerPs1` for Windows. Each finds Bun (or Node 26
 * as the backup where a person asks for it), and where there is none installs it the way its platform installs programs: on Windows with `winget`, by package identifier (Git and GitHub CLI too, which ergonex needs), and on
 * Linux and macOS with Bun's own installer, which puts Bun where Bun keeps itself and adds it to the path as Bun says. Nothing is downloaded by an installer of ours and put in a folder of ours. Then it runs
 * `bunx @intellectual-frontiers/ergonex init` (or `npx --yes`) and says in plain words what it did. A Windows script is ASCII with a byte order mark, so that Windows PowerShell 5.1 reads it as it was written. Pure:
 * `tools/generate-installers.ts` writes the files.
 *
 * @module
 */
import { BUN_INSTALLER, BUN_VERSION, WINGET } from "./pins.ts";

const PACKAGE = "@intellectual-frontiers/ergonex";

/** A string as one word in a POSIX shell, in single quotes. */
const sh = (s: string): string => s.replaceAll("'", `'\\''`);

/** The installer for Linux and macOS: a POSIX `sh` script, run with `curl -fsSL <url> | sh` or as a file. */
export function installerSh(version: string): string {
  return `#!/bin/sh
# Generated by bun commons/ergonex/tools/generate-installers.ts; do not edit (commons ergonex 0004-onboarding FR-008).
#
# ergonex-install.sh: the one command that gets a person from nothing to a workspace on Linux and macOS. It uses the Bun that is there, or installs Bun ${BUN_VERSION} with
# Bun's own installer (${BUN_INSTALLER}), which puts Bun where Bun keeps itself and adds it to your path, then runs \`ergonex init\`, which makes the workspace folder
# and puts ergonex on your path.
#
#   curl -fsSL <this file's address> | sh
#
# ERGONEX_RUNTIME=node uses Node 26 instead of Bun. ERGONEX_VERSION=<version> installs another version of ergonex than ${version}. Anything after \`--\` is
# given to \`ergonex init\`.
set -eu

say() { printf '%s\\n' "$*"; }
stop() { printf 'ergonex install: %s\\n' "$1" >&2; if [ -n "\${2:-}" ]; then printf '  %s\\n' "$2" >&2; fi; exit 1; }

version="\${ERGONEX_VERSION:-${version}}"
runtime="\${ERGONEX_RUNTIME:-bun}"

case "$runtime" in
  node)
    command -v node >/dev/null 2>&1 || stop "Node is not installed" "install Node 26 (https://nodejs.org), then run this again"
    say "using Node $(node --version)"
    ;;
  bun)
    if ! command -v bun >/dev/null 2>&1; then
      say "installing Bun ${BUN_VERSION} with Bun's own installer (${BUN_INSTALLER})"
      if command -v curl >/dev/null 2>&1; then
        curl -fsSL ${BUN_INSTALLER} | bash -s "bun-v${BUN_VERSION}" || stop "Bun could not be installed" "check your connection and run this again, or install Bun yourself (https://bun.sh) and run this again"
      else
        stop "curl is not installed" "install curl with your package manager, or install Bun yourself (https://bun.sh), then run this again"
      fi
      BUN_INSTALL="\${BUN_INSTALL:-$HOME/.bun}"; export BUN_INSTALL
      PATH="$BUN_INSTALL/bin:$PATH"; export PATH
      command -v bun >/dev/null 2>&1 || stop "Bun was installed but is not where it should be ($BUN_INSTALL/bin)" "open a new terminal and run this again"
    else
      say "using Bun $(bun --version)"
    fi
    ;;
  *) stop "ERGONEX_RUNTIME is $runtime, which is not bun or node" ;;
esac

command -v git >/dev/null 2>&1 || say "note: Git is not installed; ergonex needs it (install it with your package manager, or from https://git-scm.com)"
command -v gh >/dev/null 2>&1 || say "note: GitHub CLI is not installed; ergonex uses it for your GitHub sign-in (https://cli.github.com)"

if [ "$runtime" = node ]; then
  exec npx --yes "${sh(PACKAGE)}@$version" init "$@"
fi
exec bunx "${sh(PACKAGE)}@$version" init "$@"
`;
}

/** The installer for Windows: ASCII, in one function so that `irm <address> | iex` runs it in the person's own session and never ends it, with a byte order mark added by `withBom`. */
export function installerPs1(version: string): string {
  const id = (name: keyof typeof WINGET): string => WINGET[name];
  return `#Requires -Version 5.1
# Generated by bun commons/ergonex/tools/generate-installers.ts; do not edit (commons ergonex 0004-onboarding FR-008).
#
# ergonex-install.ps1: the one command that gets a person from nothing to a workspace on Windows. It uses the Bun that is there, or installs it with winget (${id("bun")}), as it
# does Git (${id("git")}) and GitHub CLI (${id("gh")}), which ergonex needs, then runs \`ergonex init\`, which makes the workspace folder and puts ergonex on your path. In PowerShell:
#
#   irm <this file's address> | iex
#
# $env:ERGONEX_RUNTIME = 'node' uses Node 26 (${id("node")}) instead of Bun. $env:ERGONEX_VERSION = '<version>' installs another version of ergonex than ${version}.
# This file is ASCII with a byte order mark, so that Windows PowerShell 5.1 reads it as it is written. It never calls exit, which would close your window.

function Stop-ErgonexInstall([string] $What, [string] $Next) {
    [Console]::Error.WriteLine("ergonex install: $What")
    if ($Next) { [Console]::Error.WriteLine("  $Next") }
    throw [System.OperationCanceledException]::new($What)
}

# Installs a program with winget, by its package identifier, and says so; the path of this session is made again from Windows' own, so that the program is found at once.
function Install-WithWinget([string] $Id, [string] $Name) {
    if (-not (Get-Command winget -ErrorAction SilentlyContinue)) {
        Stop-ErgonexInstall "winget is not installed, and $Name has to be" 'install "App Installer" from the Microsoft Store (https://aka.ms/getwinget), then run this again'
    }
    Write-Host "installing $Name with winget ($Id)"
    & winget install --id $Id --exact --silent --accept-source-agreements --accept-package-agreements | Out-Host
    if ($LASTEXITCODE -ne 0) { Stop-ErgonexInstall "winget could not install $Name ($Id)" 'what it said above says why' }
    $env:PATH = [Environment]::GetEnvironmentVariable('Path', 'Machine') + ';' + [Environment]::GetEnvironmentVariable('Path', 'User')
}

function Install-Ergonex {
    $ErrorActionPreference = 'Stop'
    $version = if ($env:ERGONEX_VERSION) { $env:ERGONEX_VERSION } else { '${version}' }
    $runtime = if ($env:ERGONEX_RUNTIME) { $env:ERGONEX_RUNTIME } else { 'bun' }
    if ($runtime -ne 'bun' -and $runtime -ne 'node') { Stop-ErgonexInstall "ERGONEX_RUNTIME is $runtime, which is not bun or node" '' }

    if ($runtime -eq 'node') {
        if (-not (Get-Command node -ErrorAction SilentlyContinue)) { Install-WithWinget '${id("node")}' 'Node' }
        Write-Host "using Node $(& node --version)"
    } else {
        if (-not (Get-Command bun -ErrorAction SilentlyContinue)) { Install-WithWinget '${id("bun")}' 'Bun' }
        Write-Host "using Bun $(& bun --version)"
    }
    if (-not (Get-Command git -ErrorAction SilentlyContinue)) { Install-WithWinget '${id("git")}' 'Git' }
    if (-not (Get-Command gh -ErrorAction SilentlyContinue)) { Install-WithWinget '${id("gh")}' 'GitHub CLI' }

    if ($runtime -eq 'node') { & npx --yes "${PACKAGE}@$version" init @args }
    else { & bunx "${PACKAGE}@$version" init @args }
    if ($LASTEXITCODE -ne 0) { Stop-ErgonexInstall "ergonex init stopped (status $LASTEXITCODE)" 'what it said above says why' }
}

try { Install-Ergonex @args } catch [System.OperationCanceledException] { $global:LASTEXITCODE = 1 }
`;
}

/** The bytes of a Windows PowerShell script: a UTF-8 byte order mark and the text, whose line ends stay LF (PowerShell reads them, and this repository keeps generated files LF on every system). */
export function withBom(text: string): Uint8Array {
  const body = new TextEncoder().encode(text);
  const out = new Uint8Array(body.length + 3);
  out.set([0xef, 0xbb, 0xbf], 0);
  out.set(body, 3);
  return out;
}
