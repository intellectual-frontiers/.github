// Spec: 0004-onboarding FR-008
/**
 * The installers, written from the pins (commons ergonex 0004-onboarding FR-008): `installerSh` for Linux and macOS and `installerPs1` for Windows. Each finds Bun, or installs the pinned Bun checked by its
 * SHA-256 into `~/.bun/bin` and puts that folder on the path (Node 26 is the backup where a person asks for it or Bun has no build for the system), then runs `bunx @intellectual-frontiers/ergonex init` (or
 * `npx --yes`), and says in plain words what it did. A Windows script is ASCII with a byte order mark, so that Windows PowerShell 5.1 reads it as it was written (its line ends are LF, which PowerShell reads). Pure: `tools/generate-installers.ts`
 * writes the files.
 *
 * @module
 */
import { BUN_BASE_URL, BUN_RELEASES, BUN_VERSION } from "./pins.ts";

const PACKAGE = "@intellectual-frontiers/ergonex";

/** The first lines of a generated installer, which say what it is and how to run it. */
const sh = (s: string): string => s.replaceAll("'", `'\\''`);

/** The installer for Linux and macOS: a POSIX `sh` script, run with `curl -fsSL <url> | sh` or as a file. */
export function installerSh(version: string): string {
  const cases = Object.entries(BUN_RELEASES)
    .filter(([k]) => !k.startsWith("windows"))
    .map(([k, r]) => `    ${k}) bun_sum='${r.sha256}'; bun_target='${r.target}' ;;`)
    .join("\n");
  return `#!/bin/sh
# Generated by bun commons/ergonex/tools/generate-installers.ts; do not edit (commons ergonex 0004-onboarding FR-008).
#
# ergonex-install.sh: the one command that gets a person from nothing to a workspace on Linux and macOS. It uses the Bun that is there, or installs
# Bun ${BUN_VERSION} (checked against its SHA-256) into ~/.bun/bin, then runs \`ergonex init\`, which makes the workspace folder and puts ergonex on your path.
#
#   curl -fsSL <this file's address> | sh
#
# ERGONEX_RUNTIME=node uses Node 26 instead of Bun. ERGONEX_VERSION=<version> installs another version of ergonex than ${version}. Anything after \`--\` is
# given to \`ergonex init\`.
set -eu

say() { printf '%s\\n' "$*"; }
stop() { printf 'ergonex install: %s\\n' "$1" >&2; if [ -n "\${2:-}" ]; then printf '  %s\\n' "$2" >&2; fi; exit 1; }

version="\${ERGONEX_VERSION:-${version}}"
runtime="\${ERGONEX_RUNTIME:-bun}"

case "$runtime" in
  node)
    command -v node >/dev/null 2>&1 || stop "Node is not installed" "install Node 26 (https://nodejs.org), then run this again"
    say "using Node $(node --version)"
    ;;
  bun)
    if ! command -v bun >/dev/null 2>&1; then
      case "$(uname -s)/$(uname -m)" in
        Linux/x86_64) system=linux-x64 ;;
        Linux/aarch64|Linux/arm64) system=linux-aarch64 ;;
        Darwin/x86_64) system=darwin-x64 ;;
        Darwin/arm64|Darwin/aarch64) system=darwin-aarch64 ;;
        *) stop "Bun has no build for this computer ($(uname -s) $(uname -m))" "install Node 26 (https://nodejs.org) and run: ERGONEX_RUNTIME=node sh ergonex-install.sh" ;;
      esac
      case "$system" in
${cases}
      esac
      command -v unzip >/dev/null 2>&1 || stop "unzip is not installed, and Bun comes in a zip" "install it with your package manager (for example: sudo apt install unzip), then run this again"
      base="\${ERGONEX_BUN_BASE_URL:-${BUN_BASE_URL}}"
      work="$(mktemp -d)"
      trap 'rm -rf "$work"' EXIT
      say "installing Bun ${BUN_VERSION} for $system"
      if command -v curl >/dev/null 2>&1; then
        curl -fsSL --retry 3 -o "$work/bun.zip" "$base/bun-v${BUN_VERSION}/bun-$bun_target.zip" || stop "Bun could not be downloaded" "check your connection and run this again"
      elif command -v wget >/dev/null 2>&1; then
        wget -q -O "$work/bun.zip" "$base/bun-v${BUN_VERSION}/bun-$bun_target.zip" || stop "Bun could not be downloaded" "check your connection and run this again"
      else
        stop "neither curl nor wget is installed" "install one of them, then run this again"
      fi
      if command -v sha256sum >/dev/null 2>&1; then actual="$(sha256sum "$work/bun.zip" | cut -d ' ' -f 1)"; else actual="$(shasum -a 256 "$work/bun.zip" | cut -d ' ' -f 1)"; fi
      [ "$actual" = "$bun_sum" ] || stop "the Bun that was downloaded is not the one expected (its SHA-256 is $actual)" "nothing was installed; run this again, and if it happens again, tell the person who gave you this command"
      mkdir -p "$HOME/.bun/bin"
      unzip -q -o "$work/bun.zip" -d "$work/out"
      cp "$work/out/bun-$bun_target/bun" "$HOME/.bun/bin/bun"
      chmod 755 "$HOME/.bun/bin/bun"
      ln -sf bun "$HOME/.bun/bin/bunx"
      PATH="$HOME/.bun/bin:$PATH"; export PATH
      say "installed Bun ${BUN_VERSION} in $HOME/.bun/bin"
      case "\${SHELL:-}" in
        */zsh) rc="$HOME/.zshrc" ;;
        */fish) rc="" ;;
        *) rc="$HOME/.bashrc" ;;
      esac
      if [ -n "$rc" ] && ! grep -qs '.bun/bin' "$rc" 2>/dev/null; then
        printf '\\n# Bun (added by ergonex-install.sh)\\nexport PATH="$HOME/.bun/bin:$PATH"\\n' >>"$rc"
        say "added $HOME/.bun/bin to your path in $rc; open a new terminal to use it"
      elif [ -z "$rc" ]; then
        say "add $HOME/.bun/bin to your path (fish_add_path $HOME/.bun/bin) to use Bun in a new terminal"
      fi
    else
      say "using Bun $(bun --version)"
    fi
    ;;
  *) stop "ERGONEX_RUNTIME is $runtime, which is not bun or node" ;;
esac

if [ "$runtime" = node ]; then
  exec npx --yes "${sh(PACKAGE)}@$version" init "$@"
fi
exec bunx "${sh(PACKAGE)}@$version" init "$@"
`;
}

/** The installer for Windows: ASCII, in one function so that `irm <address> | iex` runs it in the person's own session and never ends it, with a byte order mark added by `withBom`. */
export function installerPs1(version: string): string {
  const win = BUN_RELEASES["windows-x64"];
  if (win === undefined) throw new Error("no Windows release of Bun is pinned");
  return `#Requires -Version 5.1
# Generated by bun commons/ergonex/tools/generate-installers.ts; do not edit (commons ergonex 0004-onboarding FR-008).
#
# ergonex-install.ps1: the one command that gets a person from nothing to a workspace on Windows. It uses the Bun that is there, or installs Bun ${BUN_VERSION}
# (checked against its SHA-256) into %USERPROFILE%\\.bun\\bin and adds that folder to your path (only yours), then runs \`ergonex init\`, which makes the
# workspace folder and puts ergonex on your path. In PowerShell:
#
#   irm <this file's address> | iex
#
# $env:ERGONEX_RUNTIME = 'node' uses Node 26 instead of Bun. $env:ERGONEX_VERSION = '<version>' installs another version of ergonex than ${version}.
# This file is ASCII with a byte order mark, so that Windows PowerShell 5.1 reads it as it is written. It never calls exit, which would close your window.

function Stop-ErgonexInstall([string] $What, [string] $Next) {
    [Console]::Error.WriteLine("ergonex install: $What")
    if ($Next) { [Console]::Error.WriteLine("  $Next") }
    throw [System.OperationCanceledException]::new($What)
}

function Install-Ergonex {
    $ErrorActionPreference = 'Stop'
    $version = if ($env:ERGONEX_VERSION) { $env:ERGONEX_VERSION } else { '${version}' }
    $runtime = if ($env:ERGONEX_RUNTIME) { $env:ERGONEX_RUNTIME } else { 'bun' }
    if ($runtime -ne 'bun' -and $runtime -ne 'node') { Stop-ErgonexInstall "ERGONEX_RUNTIME is $runtime, which is not bun or node" '' }

    if ($runtime -eq 'node') {
        if (-not (Get-Command node -ErrorAction SilentlyContinue)) { Stop-ErgonexInstall 'Node is not installed' 'install Node 26 (https://nodejs.org), then run this again' }
        Write-Host "using Node $(& node --version)"
    } elseif (Get-Command bun -ErrorAction SilentlyContinue) {
        Write-Host "using Bun $(& bun --version)"
    } else {
        if ($env:PROCESSOR_ARCHITECTURE -ne 'AMD64') {
            Stop-ErgonexInstall "Bun has no build for this computer ($env:PROCESSOR_ARCHITECTURE)" "install Node 26 (https://nodejs.org) and run: $env:ERGONEX_RUNTIME = 'node'; then this again"
        }
        $sum = '${win.sha256}'
        $base = if ($env:ERGONEX_BUN_BASE_URL) { $env:ERGONEX_BUN_BASE_URL } else { '${BUN_BASE_URL}' }
        $work = Join-Path ([IO.Path]::GetTempPath()) ('ergonex-' + [guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Path $work | Out-Null
        try {
            Write-Host 'installing Bun ${BUN_VERSION} for Windows'
            $zip = Join-Path $work 'bun.zip'
            $ProgressPreference = 'SilentlyContinue'
            try { Invoke-WebRequest -UseBasicParsing -Uri "$base/bun-v${BUN_VERSION}/bun-${win.target}.zip" -OutFile $zip }
            catch { Stop-ErgonexInstall 'Bun could not be downloaded' 'check your connection and run this again' }
            $actual = (Get-FileHash -Algorithm SHA256 -Path $zip).Hash.ToLowerInvariant()
            if ($actual -ne $sum) { Stop-ErgonexInstall "the Bun that was downloaded is not the one expected (its SHA-256 is $actual)" 'nothing was installed; run this again, and if it happens again, tell the person who gave you this command' }
            Expand-Archive -Path $zip -DestinationPath (Join-Path $work 'out') -Force
            $bin = Join-Path $env:USERPROFILE '.bun\\bin'
            New-Item -ItemType Directory -Path $bin -Force | Out-Null
            Copy-Item -Path (Join-Path $work 'out\\bun-${win.target}\\bun.exe') -Destination (Join-Path $bin 'bun.exe') -Force
            Copy-Item -Path (Join-Path $bin 'bun.exe') -Destination (Join-Path $bin 'bunx.exe') -Force
            $user = [Environment]::GetEnvironmentVariable('Path', 'User')
            $parts = @($user -split ';' | Where-Object { $_ })
            if ($parts -notcontains $bin) { [Environment]::SetEnvironmentVariable('Path', (($parts + $bin) -join ';'), 'User') }
            $env:PATH = $bin + ';' + $env:PATH
            Write-Host "installed Bun ${BUN_VERSION} in $bin and added it to your path (only yours); open a new terminal to use it"
        } finally {
            Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
        }
    }

    if ($runtime -eq 'node') { & npx --yes "${PACKAGE}@$version" init @args }
    else { & bunx "${PACKAGE}@$version" init @args }
    if ($LASTEXITCODE -ne 0) { Stop-ErgonexInstall "ergonex init stopped (status $LASTEXITCODE)" 'what it said above says why' }
}

try { Install-Ergonex @args } catch [System.OperationCanceledException] { $global:LASTEXITCODE = 1 }
`;
}

/** The bytes of a Windows PowerShell script: a UTF-8 byte order mark and the text, whose line ends stay LF (PowerShell reads them, and this repository keeps generated files LF on every system). */
export function withBom(text: string): Uint8Array {
  const body = new TextEncoder().encode(text);
  const out = new Uint8Array(body.length + 3);
  out.set([0xef, 0xbb, 0xbf], 0);
  out.set(body, 3);
  return out;
}
