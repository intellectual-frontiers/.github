// Spec: 0004-onboarding FR-002
/**
 * Putting `ergonex` on the person's path (commons ergonex 0004-onboarding FR-002): what the shims say, the command that installs the package globally for the runtime that ran `init`, the PowerShell
 * that adds the shim folder to the user's path on Windows, and how a run tells a copy installed from a registry from a checkout. All pure: `host/path.ts` runs it.
 *
 * @module
 */

/** How the command is started again: from the registry by its package and version (a copy that may be gone is never relied on), or from the files that are running now (a checkout). */
export type Launch =
  | {
      readonly kind: "registry";
      readonly runtime: "bun" | "node";
      readonly spec: string;
    }
  | {
      readonly kind: "local";
      readonly runtime: "bun" | "node";
      readonly entry: string;
    };

/** The package a person installs. */
export const PACKAGE = "@intellectual-frontiers/ergonex";

/** The first line of every file `init` writes into the shim folder, which marks it as ergonex's to rewrite and no other file as. */
export const SHIM_MARK = "generated by ergonex init";

/** Whether the files that run are a copy a package manager keeps (a registry install, `bunx` or `npx`) and not a checkout. */
export function isRegistryCopy(entry: string): boolean {
  return /(^|[\\/])(node_modules|_npx)([\\/]|$)|[\\/]\.bun[\\/]install[\\/]cache[\\/]/.test(entry);
}

/** How the shims start the command, from what runs now. */
export function launchFor(f: { readonly runtime: "bun" | "node"; readonly entry: string; readonly version: string }): Launch {
  return isRegistryCopy(f.entry)
    ? { kind: "registry", runtime: f.runtime, spec: `${PACKAGE}@${f.version}` }
    : { kind: "local", runtime: f.runtime, entry: f.entry };
}

/** The command that installs the package for every terminal: Bun's global install, or npm's where Node ran it. */
export function globalInstall(l: Extract<Launch, { kind: "registry" }>): readonly string[] {
  return l.runtime === "bun" ? ["bun", "add", "-g", l.spec] : ["npm", "install", "-g", l.spec];
}

const shQuote = (s: string): string => `'${s.replaceAll("'", `'\\''`)}'`;

/** The shim for `sh` (Linux, macOS, Git Bash): it runs the command and passes every argument on as one. */
export function shimSh(l: Launch): string {
  const run =
    l.kind === "registry"
      ? l.runtime === "bun"
        ? `exec bunx ${shQuote(l.spec)} "$@"`
        : `exec npx --yes ${shQuote(l.spec)} "$@"`
      : `exec ${l.runtime} ${shQuote(l.entry)} "$@"`;
  return `#!/bin/sh\n# ${SHIM_MARK}; run \`ergonex init\` again to rewrite it\n${run}\n`;
}

/** Why a path cannot be written into a `.cmd` file as it is: `%` and `"` mean more there than their letters. */
export function cmdUnsafe(path: string): boolean {
  return /[%"\r\n]/.test(path);
}

/** The shim for `cmd` and PowerShell on Windows, with the line ends `cmd` reads. */
export function shimCmd(l: Launch): string {
  const run =
    l.kind === "registry" ? (l.runtime === "bun" ? `bunx ${l.spec} %*` : `npx --yes ${l.spec} %*`) : `${l.runtime} "${l.entry}" %*`;
  return `@echo off\r\nrem ${SHIM_MARK}; run \`ergonex init\` again to rewrite it\r\n${run}\r\n`;
}

/** The PowerShell that adds a folder to the user's path (not the machine's) once, and says nothing where it is there. */
export function userPathScript(dir: string): string {
  const d = dir.replaceAll("'", "''");
  return [
    `$d = '${d}'`,
    "$p = [Environment]::GetEnvironmentVariable('Path', 'User')",
    "$parts = @($p -split ';' | Where-Object { $_ })",
    "if ($parts -notcontains $d) { [Environment]::SetEnvironmentVariable('Path', (($parts + $d) -join ';'), 'User'); 'added' } else { 'there' }",
  ].join("; ");
}

/** The shell a person most likely has, from `$SHELL`: the five ergonex knows by name, else bash. */
export function shellFrom(shellVar: string | undefined): "bash" | "zsh" | "fish" | "nu" {
  const name = (shellVar ?? "").split(/[\\/]/).pop() ?? "";
  return name === "zsh" || name === "fish" || name === "nu" ? name : "bash";
}
