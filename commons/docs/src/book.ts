// Spec: 0001-docs FR-008
/**
 * The volumes of a book (docs 0001-docs FR-008): the pages a volume's parts select, in the order of the site's navigation, written as the one AsciiDoc file a book of `erga` includes as a
 * generated chapter source (`<volume>/generated/<volume>.adoc`). A page is a chapter of its part, and a page whose parent is in the same part is a section of its parent's chapter. The file
 * says it is generated and is the same for the same pages, so that it can be proved current by writing it again and comparing.
 *
 * @module
 */
import type { Finding } from "./check.ts";
import type { BookPart, BookVolume, BooksConfig, PageSelector } from "./config.ts";
import { type AdocScope, anchorsOf, lead, pageAdoc, pageAnchor, textAdoc } from "./emit/asciidoc.ts";
import { navigation } from "./emit/html.ts";
import type { Page } from "./model.ts";

/** A file the book presentation writes: its path from the output folder, its text, and what it is. */
export interface BookFile {
  /** Where it is, from the output folder. */
  readonly path: string;
  /** Its text. */
  readonly text: string;
}

/** The first line of a generated file: what made it and how to make it again (no date and no revision, so that it is the same each time). */
export const GENERATED = (volume: string): string =>
  `// Generated by docs (@intellectual-frontiers/docs): volume ${volume}. Rewrite it with \`ifc-docs build --presentation book\`; do not edit it by hand.`;

const byOrder = (a: Page, b: Page): number => a.order - b.order || (a.title < b.title ? -1 : a.title > b.title ? 1 : 0);

const selects = (s: PageSelector, p: Page): boolean =>
  (s.section === undefined || p.section === s.section) &&
  (s.group === undefined || p.group === s.group) &&
  (s.prefix === undefined || p.path.startsWith(s.prefix)) &&
  !(s.exclude ?? []).some((e) => p.path.startsWith(e));

/** The pages a selector takes, in the order of the navigation of its section (by path where it names none). */
function take(pages: readonly Page[], s: PageSelector): Page[] {
  const hit = pages.filter((p) => selects(s, p));
  if (s.section !== undefined) return navigation(hit, s.section).flatMap((g) => g.pages);
  return [...hit].sort((a, b) => (a.path < b.path ? -1 : 1));
}

/** A part of a volume with the pages it takes. */
export interface PartPages {
  /** The part: as configured, or one a group made. */
  readonly part: BookPart;
  /** Its pages, in order. */
  readonly pages: Page[];
}

/** The pages each part of a volume takes (a page is in the first part that takes it), a part that is `perGroup` as a part of each group, in the order of the groups. */
export function selection(volume: BookVolume, pages: readonly Page[]): PartPages[] {
  const used = new Set<string>();
  return volume.parts.flatMap((part): PartPages[] => {
    const mine: Page[] = [];
    for (const s of part.select) {
      for (const p of take(pages, s)) {
        if (used.has(p.path)) continue;
        used.add(p.path);
        mine.push(p);
      }
    }
    if (part.perGroup !== true) return [{ part, pages: mine }];
    const groups: string[] = [];
    for (const p of mine) if (!groups.includes(p.group)) groups.push(p.group);
    return groups.map((g) => ({ part: { title: g, select: part.select }, pages: mine.filter((p) => p.group === g) }));
  });
}

/** The lines of a part: its heading, its line, and the chapter of each page that is not under another page of the part, with the pages under it as its sections. */
function partLines(volume: BookVolume, n: number, part: BookPart, mine: readonly Page[], scope: AdocScope): string[] {
  const inPart = new Map(mine.map((p) => [p.path, p] as const));
  const kids = new Map<string, Page[]>();
  for (const p of mine) if (p.parent !== undefined && inPart.has(p.parent)) kids.set(p.parent, [...(kids.get(p.parent) ?? []), p]);
  const out = ["", `[#${volume.id}-part-${n}]`, `= ${textAdoc(part.title)}`, ""];
  if (part.about !== undefined) out.push(lead(textAdoc(part.about)), "");
  const chapter = (p: Page, level: number): void => {
    out.push("", ...pageAdoc(p, scope, { anchor: scope.pages.get(p.path) ?? "", level: Math.min(6, level) }), "");
    for (const k of (kids.get(p.path) ?? []).sort(byOrder)) chapter(k, level + 1);
  };
  for (const p of mine) if (p.parent === undefined || !inPart.has(p.parent)) chapter(p, 2);
  return out;
}

/** The AsciiDoc of one volume, and what is found while it is made. */
export function volumeText(volume: BookVolume, pages: readonly Page[], site: string | undefined, found: Finding[]): string {
  const chosen = selection(volume, pages);
  const placed = new Map<string, string>();
  const anchors = new Set<string>();
  for (const p of chosen.flatMap((c) => c.pages)) {
    const a = pageAnchor(volume.id, p.path);
    placed.set(p.path, a);
    for (const x of anchorsOf(p, a)) anchors.add(x);
  }
  const scope: AdocScope = { pages: placed, anchors, site };
  const out = [GENERATED(volume.id), `// ${volume.title}: ${volume.about.replace(/\s+/g, " ")}`];
  chosen.forEach(({ part, pages: mine }, i) => {
    if (mine.length === 0) found.push({ where: `books.${volume.id}`, problem: { kind: "book-part-empty", volume: volume.id, part: part.title } });
    out.push(...partLines(volume, i + 1, part, mine, scope));
  });
  const lines: string[] = [];
  for (const l of out) if (!(l === "" && lines[lines.length - 1] === "")) lines.push(l);
  return `${lines.join("\n").trim()}\n`;
}

/**
 * The files of the book presentation: for each volume `<id>/generated/<id>.adoc`, and `books.json` that lists them (the volumes, their parts and how many pages each has).
 *
 * @param books - the configuration's volumes
 * @param pages - the pages of the site
 * @param found - where findings are added
 */
export function bookFiles(books: BooksConfig, pages: readonly Page[], found: Finding[]): BookFile[] {
  const files = books.volumes.map((v): BookFile => ({ path: `${v.id}/generated/${v.id}.adoc`, text: volumeText(v, pages, books.site, found) }));
  const manifest = books.volumes.map((v) => ({
    id: v.id,
    title: v.title,
    about: v.about,
    file: `${v.id}/generated/${v.id}.adoc`,
    parts: selection(v, pages).map((c) => ({ title: c.part.title, pages: c.pages.length })),
  }));
  return [...files, { path: "books.json", text: `${JSON.stringify(manifest, null, 2)}\n` }];
}
