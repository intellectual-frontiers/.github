// Spec: 0003-governance FR-013
/**
 * The terms of DPV-PD are the vocabulary's own (commons data 0003-governance FR-013): the generator refuses a CSV that is not the pinned one, and writes nothing then; the file it wrote says
 * where it came from and is the pinned CSV's digest; each term in it is the vocabulary's, with a class DPV gives. The generator's `--check` fetches the CSV, so the workflow runs it
 * (`data.yml`); the real fetch is not a test, which must not need a network.
 *
 * @module
 */
import { fs, path } from "@intellectual-frontiers/commons/ts/runtime";
import { assert, proves } from "@intellectual-frontiers/commons/ts/runtime/test";
import { vocabularies } from "@intellectual-frontiers/data/governance";
import { OUT, PINNED_SHA256, render, SOURCE, VERSION } from "../tools/generate-dpv.ts";
import { same } from "./governance-fixture.ts";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..");

proves(
  ["0003-governance FR-013"],
  "a CSV that is not the pinned one is refused with the digest it has, and nothing is made of it",
  async () => {
    const r = await render('"term","type"\n"Age","class"\n');
    assert(r.kind === "err");
    if (r.kind === "err") {
      same(r.error.kind, "digest");
      assert(r.error.kind === "digest" && r.error.pinned === PINNED_SHA256 && r.error.found !== PINNED_SHA256);
    }
  },
);

proves(
  ["0003-governance FR-013"],
  "the generated file says where it came from, at the pinned version and digest, and is not edited by hand",
  async () => {
    const text = await fs.readTextFile(path.join(ROOT, OUT));
    assert(text.includes("AUTO-GENERATED by tools/generate-dpv.ts; do not edit"));
    assert(text.includes(`Source: ${SOURCE}`) && text.includes(`Source SHA-256: ${PINNED_SHA256}`));
    assert(text.includes(`export const DPV_VERSION = "${VERSION}";`));
    assert(/^\/\/ Spec: 0003-governance FR-013\n/.test(text));
  },
);

proves(["0003-governance FR-013"], "every term is a term of DPV-PD with a class DPV gives, and the classes are DPV's three", () => {
  const terms = Object.entries(vocabularies.privacy.pd);
  assert(terms.length > 200, `${terms.length} terms`);
  const classes = new Set(terms.map(([, v]) => v.kind));
  same([...classes].sort(), ["PersonalData", "SensitivePersonalData", "SpecialCategoryPersonalData"]);
  assert(terms.every(([term, v]) => /^[A-Za-z][A-Za-z0-9]*$/.test(term) && v.label.length > 0));
  same([vocabularies.privacy.pd.Age.kind, vocabularies.privacy.pd.Biometric.kind], ["PersonalData", "SpecialCategoryPersonalData"]);
  same(
    terms.map(([t]) => t),
    [...terms.map(([t]) => t)].sort(),
    "the terms are in the CSV's alphabetical order",
  );
});
