// Spec: 0025-sql-target FR-001, FR-002, FR-003, FR-004, FR-005, FR-006
/**
 * Ephemeral targets (commons data 0025-sql-target), on real engines: one SQL file from governance and typed rows, the same bytes every time, tables in the order of their foreign keys and rows in the
 * order of their keys; a database made from it in one transaction; a committed file checked for staleness.
 *
 * @module
 */
import { assert, proves } from "@intellectual-frontiers/test";
import { materialize, type Rows, sizeFindings, staleness, targetBuild, type TargetBuild, type TargetOptions } from "@intellectual-frontiers/data/sql/extensions/target";
import { DIALECTS, openEngine } from "./engines-fixture.ts";
import { same } from "./governance-fixture.ts";
import { driverOf, libraryAt } from "./lifecycle-fixture.ts";

const schema = libraryAt(2);
const rows: Rows = {
  book: [
    { id: "b2", title: "Second", "genre code": "poetry", "author id": "a2" },
    { id: "b1", title: "First", "genre code": "fiction", "author id": "a1", pages: 120 },
  ],
  author: [
    { id: "a2", name: "Bo", born: null },
    { id: "a1", name: "Ann", born: "1990-01-02" },
    { id: "a3", name: "O'Neil" },
  ],
};
const made = (more: Partial<TargetOptions> = {}, dialect = DIALECTS[2].dialect): TargetBuild => {
  const r = targetBuild(schema, { dialect, rows, module: "catalog.ts", ...more });
  if (r.kind === "err") throw new Error(JSON.stringify(r.error));
  return r.value;
};

proves(
  ["0025-sql-target FR-001", "0025-sql-target FR-002", "0025-sql-target FR-003"],
  "the file is a header, the structure, then rows with tables after the tables they refer to, rows in the order of their key, a fixed number to an INSERT, and the same bytes every time whatever the order the rows were given in",
  () => {
    for (const { name, dialect } of DIALECTS) {
      const b = made({}, dialect);
      const lines = b.text.split("\n");
      same(lines.slice(0, 4).map((l) => l.split(":")[0]), ["-- Generated by @intellectual-frontiers/data from catalog.ts. Do not edit", "-- dialect", "-- schema", "-- rows"], name);
      assert(lines[1] === `-- dialect: ${dialect.name}` && /^-- schema: [0-9a-f]{64}$/.test(lines[2] ?? "") && /^-- rows: [0-9a-f]{64}$/.test(lines[3] ?? ""));
      const inserts = b.statements.filter((s) => s.startsWith("INSERT INTO") && /"author"|"book"/.test(s.slice(0, 40)));
      same(inserts.map((s) => (s.includes('"author"') ? "author" : "book")), ["author", "book"], `${name}: authors before the books that refer to them`);
      assert(inserts[0]!.indexOf("'a1'") < inserts[0]!.indexOf("'a2'") && inserts[0]!.indexOf("'a2'") < inserts[0]!.indexOf("'a3'"), `${name}: rows in the order of their key`);
      assert(inserts[0]!.includes("'O''Neil'"), `${name}: values written by the dialect`);
      same(b.counts, { author: 3, book: 2 });
      same(made({}, dialect).text, b.text, `${name}: the same bytes`);
      same(made({ rows: { author: [...(rows["author"] ?? [])].reverse(), book: [...(rows["book"] ?? [])].reverse() } }, dialect).text, b.text, `${name}: whatever order the rows were given in`);
      assert(!/20\d\d-\d\d-\d\dT/.test(b.text), `${name}: nothing of the clock`);
    }
    const five = { author: ["a1", "a2", "a3", "a4", "a5"].map((id) => ({ id, name: id })) };
    const batched = made({ rows: five, batch: 2 });
    same(batched.statements.filter((s) => s.startsWith('INSERT INTO "author"')).length, 3, "a fixed number to an INSERT");
    same(made({ rows: {} }).statements.some((s) => s.startsWith('INSERT INTO "author"')), false, "no rows, structure only");
    assert(made({ schema: "data" }).text.includes('"data"."author"'), "qualified as the schema is");
  },
);

proves(
  ["0025-sql-target FR-001"],
  "rows are checked when the file is made: an unknown table or column, a missing required column, a key twice, a column twice and a cycle among tables are errors as values",
  () => {
    const bad = (r: Rows): string[] => {
      const x = targetBuild(schema, { dialect: DIALECTS[2].dialect, rows: r });
      return x.kind === "err" ? x.error.map((e) => e.kind) : ["ok"];
    };
    same(bad({ nope: [{ a: 1 }] }), ["unknown-table"]);
    same(bad({ author: [{ id: "a", name: "x", shoe: 1 }] }), ["unknown-column"]);
    same(bad({ author: [{ id: "a" }] }), ["missing-required"]);
    same(bad({ author: [{ id: "a", name: "x" }, { id: "a", name: "y" }] }), ["duplicate-key"]);
    same(bad({ author: [{ id: "a", ID: "b", name: "x" }] }), ["duplicate-column"]);
    same(bad({ author: [{ id: "a", name: "x" }] }), ["ok"]);
    const cyclic = {
      ...schema,
      tables: schema.tables.map((t) => (t.name.join(".") === "author" ? { ...t, foreignKeys: [...t.foreignKeys, { id: "fk-cycle" as never, from: t.from, name: ["author", "book", "fk"], columns: [["id"]], references: { table: ["book"], columns: [["id"]] } }] } : t)),
    };
    const c = targetBuild(cyclic as never, { dialect: DIALECTS[2].dialect });
    assert(c.kind === "err" && c.error.some((e) => e.kind === "cycle"), JSON.stringify(c));
  },
);

proves(
  ["0025-sql-target FR-004"],
  "on three engines a database is made from the build in one transaction, with the rows as the source gives them, and a failure rolls everything back",
  async () => {
    for (const { name, dialect } of DIALECTS) {
      const e = await openEngine(name);
      try {
        const b = made({}, dialect);
        const r = await materialize(driverOf(e), b);
        assert(r.kind === "ok" && r.value === b.statements.length, `${name}: ${JSON.stringify(r)}`);
        same((await e.rows(`SELECT "id", "name" FROM "author" ORDER BY "id"`)).map((x) => [x["id"], x["name"]]), [["a1", "Ann"], ["a2", "Bo"], ["a3", "O'Neil"]], name);
        same(Number((await e.rows(`SELECT count(*) n FROM "book" WHERE "pages" = 120`))[0]?.["n"]), 1);
        // into a database that already has the rows: the first INSERT fails and nothing of this run stays
        const again = await materialize(driverOf(e), made({ rows: { author: [{ id: "z9", name: "New" }, { id: "a1", name: "Clash" }] } }, dialect));
        assert(again.kind === "err" && again.error.kind === "database", `${name}: a clash`);
        same(Number((await e.rows(`SELECT count(*) n FROM "author"`))[0]?.["n"]), 3, `${name}: and nothing of it stays`);
      } finally {
        await e.close();
      }
    }
  },
);

proves(
  ["0025-sql-target FR-005", "0025-sql-target FR-006"],
  "a committed file is current or it is stale at a line, and a table with more rows than a limit is reported",
  () => {
    const b = made();
    same(staleness(b.text, b), { stale: false });
    const edited = b.text.replace("'Ann'", "'Anne'");
    const s = staleness(edited, b);
    assert(s.stale && s.committed.includes("'Anne'") && s.made.includes("'Ann'") && s.line > 4, JSON.stringify(s));
    const changed = made({ rows: { ...rows, author: [...(rows["author"] ?? []), { id: "a4", name: "Di" }] } });
    assert(staleness(b.text, changed).stale, "a source that changed");
    same(sizeFindings(b, 2), [{ table: "author", rows: 3, limit: 2 }]);
    same(sizeFindings(b, 3), []);
  },
);
