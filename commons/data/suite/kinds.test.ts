// Spec: 0026-sql-kinds FR-001, FR-002, FR-003, FR-004
/**
 * Kinds (commons data 0026-sql-kinds): reference data kept as CSV read into typed rows, checked against a table, written as a TypeScript module that imports as the rows that were read, and given to
 * an ephemeral target as they are.
 *
 * @module
 */
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { assert, proves } from "@intellectual-frontiers/test";
import { checkKinds, kindsFromCsv, kindsModule, type Kinds, rowsOf } from "@intellectual-frontiers/data/sql/extensions/kinds";
import { materialize, targetBuild } from "@intellectual-frontiers/data/sql/extensions/target";
import { DIALECTS, openEngine } from "./engines-fixture.ts";
import { same } from "./governance-fixture.ts";
import { driverOf, libraryAt } from "./lifecycle-fixture.ts";

const csv = 'code,label,rank,active,note\nperson,Person,1,true,\norganization,"Organization, any body",2,1,"two\nlines"\n';
const must = (r: ReturnType<typeof kindsFromCsv>): Kinds => {
  if (r.kind === "err") throw new Error(JSON.stringify(r.error));
  return r.value;
};
const types = { rank: "integer", active: "boolean" } as const;

proves(
  ["0026-sql-kinds FR-001"],
  "CSV is read into typed rows in the order of the file, and a bad header, a ragged row, a value of the wrong type and a key twice are errors as values with their lines",
  () => {
    const k = must(kindsFromCsv(csv, { name: "kind", types }));
    same(k.rows, [
      { code: "person", label: "Person", rank: 1, active: true, note: null },
      { code: "organization", label: "Organization, any body", rank: 2, active: true, note: "two\nlines" },
    ]);
    same(k.columns.map((c) => [c.name, c.type, c.nullable]), [["code", "text", false], ["label", "text", false], ["rank", "integer", false], ["active", "boolean", false], ["note", "text", true]]);
    same(k.key, ["code"]);
    const bad = (text: string, o: Partial<Parameters<typeof kindsFromCsv>[1]> = {}): string[] => {
      const r = kindsFromCsv(text, { name: "k", types, ...o });
      return r.kind === "err" ? r.error.map((e) => (e.kind === "fields" || e.kind === "type" || e.kind === "duplicate-key" ? `${e.kind}@${e.line}` : e.kind)) : ["ok"];
    };
    same(bad(""), ["header"]);
    same(bad("a,a\n1,2"), ["header"]);
    same(bad("code,rank\nx,1,2"), ["fields@2"]);
    same(bad("code,rank\nx,one"), ["type@2"]);
    same(bad("code,rank\nx,1.5"), ["type@2"]);
    same(bad("code,active\nx,maybe"), ["type@2"]);
    same(bad("code,rank\nx,1\nx,2"), ["duplicate-key@3"]);
    same(bad("code,rank\nx,1\ny,1", { key: ["rank"] }), ["duplicate-key@3"]);
    same(bad("code,rank\nx,1", { key: ["nope"] }), ["unknown-key"]);
    same(bad("code,rank\n"), ["ok"], "a header and no rows");
    same(must(kindsFromCsv("a;b\n1;2", { name: "k", types: { b: "number" }, delimiter: ";" })).rows, [{ a: "1", b: 2 }]);
  },
);

proves(
  ["0026-sql-kinds FR-002"],
  "the rows are checked against a table by the words of the names: an unknown table or column, a required column the file lacks and an empty required value are errors as values",
  () => {
    const schema = libraryAt(2);
    const kinds = (text: string): Kinds => must(kindsFromCsv(text, { name: "author" }));
    same(checkKinds(kinds("id,name,born\na1,Ann,\n"), schema, "author"), []);
    same(checkKinds(kinds("id,name\na1,Ann\n"), schema, "Author").length, 0, "any case style");
    same(checkKinds(kinds("id,name\na1,Ann\n"), schema, "nope"), [{ kind: "unknown-table", table: "nope" }]);
    same(checkKinds(kinds("id,name,shoe\na1,Ann,9\n"), schema, "author"), [{ kind: "unknown-column", table: "author", column: "shoe" }]);
    same(checkKinds(kinds("id\na1\n"), schema, "author"), [{ kind: "missing-required", table: "author", columns: ["name"] }]);
    same(checkKinds(kinds("id,name\na1,\n"), schema, "author"), [{ kind: "empty-required", table: "author", column: "name", line: 2 }]);
  },
);

proves(
  ["0026-sql-kinds FR-003", "0026-sql-kinds FR-004"],
  "the module is the same text every time, marked not to be edited, imports as the rows that were read, and the rows go into an ephemeral target as they are",
  async () => {
    const k = must(kindsFromCsv(csv, { name: "kind", types }));
    const text = kindsModule(k, { source: "kinds.csv" });
    same(kindsModule(k, { source: "kinds.csv" }), text, "the same text");
    assert(text.includes("Do not edit this file") && text.includes("made from kinds.csv"));
    assert(text.includes("export interface KindRow {") && text.includes("readonly rank: number;") && text.includes("readonly active: boolean;") && text.includes("readonly note: string | null;"));
    assert(text.includes("export const kindRows: readonly KindRow[] = ["));
    const dir = mkdtempSync(join(tmpdir(), "kinds-"));
    const file = join(dir, "kinds.auto.ts");
    writeFileSync(file, text);
    const imported = (await import(file)) as { kindRows: readonly Record<string, unknown>[] };
    same(imported.kindRows, rowsOf(k), "imported, it is the rows that were read");
    const empty = kindsModule(must(kindsFromCsv("code\n", { name: "kind" })));
    assert(empty.includes("= [];"));
    // the same rows, a database
    const schema = libraryAt(2);
    const authors = must(kindsFromCsv("id,name,born\na2,Bo,\na1,Ann,1990-01-02\n", { name: "author" }));
    assert(checkKinds(authors, schema, "author").length === 0);
    for (const { name, dialect } of DIALECTS) {
      const b = targetBuild(schema, { dialect, rows: { author: rowsOf(authors) } });
      assert(b.kind === "ok", `${name}: ${JSON.stringify(b)}`);
      if (b.kind !== "ok") continue;
      const e = await openEngine(name);
      try {
        assert((await materialize(driverOf(e), b.value)).kind === "ok");
        same((await e.rows(`SELECT "id" FROM "author" ORDER BY "id"`)).map((r) => r["id"]), ["a1", "a2"], name);
      } finally {
        await e.close();
      }
    }
  },
);
