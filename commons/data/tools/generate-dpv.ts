// Spec: 0003-governance FR-013
/**
 * Writes `governance/vocabularies/dpv.auto.ts` from the Personal Data extension of the W3C Data Privacy Vocabulary (DPV-PD), as its publishers give it in CSV
 * (commons data 0003-governance FR-013): the library names the vocabulary's own terms and writes none by hand. The CSV is at the pinned version and its SHA-256 is pinned too;
 * a CSV that differs is refused and nothing is written.
 *
 * ```sh
 * bun tools/generate-dpv.ts            fetch the CSV, check it, write the file
 * bun tools/generate-dpv.ts pd.csv     the same from a CSV already downloaded
 * bun tools/generate-dpv.ts --check    fail where the file is not what the CSV makes (fetches the CSV)
 * ```
 *
 * @module
 */
import { formatCsvError, parseCsvRecords } from "@intellectual-frontiers/formats";
import { sha256 } from "@intellectual-frontiers/crypto";
import { fs, path } from "@intellectual-frontiers/system";

/** Where the CSV is, and which version. */
export const SOURCE = "https://w3c-cg.github.io/dpv/2.3/pd/pd.csv";
export const VERSION = "2.3";
/** The SHA-256 of the CSV at that version: a different CSV is refused. */
export const PINNED_SHA256 = "7f4391700aa88079c9f02526e0164c1c8d251c177c9c45c84cd76d4e4c09b4aa";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..");
/** The file this tool writes, from the library's root. */
export const OUT = "governance/vocabularies/dpv.auto.ts";

/** What can go wrong, as data. */
export type GenerateError =
  | { readonly kind: "digest"; readonly found: string; readonly pinned: string }
  | { readonly kind: "csv"; readonly message: string }
  | { readonly kind: "fetch"; readonly message: string };

type Kind = "PersonalData" | "SensitivePersonalData" | "SpecialCategoryPersonalData";

const kindOf = (types: string): Kind =>
  types.includes("#SpecialCategoryPersonalData")
    ? "SpecialCategoryPersonalData"
    : types.includes("#SensitivePersonalData")
      ? "SensitivePersonalData"
      : "PersonalData";

/** The text of `dpv.auto.ts` that a CSV makes, or why it makes none. */
export async function render(
  csv: string,
): Promise<{ readonly kind: "ok"; readonly text: string } | { readonly kind: "err"; readonly error: GenerateError }> {
  const found = await sha256(csv);
  if (found !== PINNED_SHA256) return { kind: "err", error: { kind: "digest", found, pinned: PINNED_SHA256 } };
  const parsed = parseCsvRecords(csv);
  if (parsed.kind === "err") return { kind: "err", error: { kind: "csv", message: formatCsvError(parsed.error) } };
  const terms = parsed.value
    .filter((r) => r["type"] === "class" && (r["iri"] ?? "").startsWith("https://w3id.org/dpv/pd#"))
    .map((r) => ({ term: r["term"] ?? "", label: r["label"] ?? "", kind: kindOf(r["dpvtype"] ?? "") }))
    .filter((t) => /^[A-Za-z][A-Za-z0-9]*$/.test(t.term))
    .sort((a, b) => (a.term < b.term ? -1 : a.term > b.term ? 1 : 0));
  const lines = [
    "// Spec: 0003-governance FR-013",
    "/**",
    " * AUTO-GENERATED by tools/generate-dpv.ts; do not edit: run the tool.",
    " *",
    ` * The terms of the Personal Data extension of the W3C Data Privacy Vocabulary ${VERSION} (DPV-PD), a Final Community Group Report of the W3C Data Privacy`,
    " * Vocabularies and Controls Community Group (CC BY 4.0), each with how DPV classes it: personal data, sensitive personal data or a special category",
    " * (commons data 0003-governance FR-013).",
    " *",
    ` * Source: ${SOURCE}`,
    ` * Source SHA-256: ${found}`,
    " *",
    " * @module",
    " */",
    "",
    "/** The version of the vocabulary these terms are from. */",
    `export const DPV_VERSION = "${VERSION}";`,
    "",
    "/** The namespace of DPV, where the three classes of personal data are. */",
    'export const DPV_NAMESPACE = "https://w3id.org/dpv#";',
    "",
    "/** The namespace of DPV-PD, where the categories are. */",
    'export const PD_NAMESPACE = "https://w3id.org/dpv/pd#";',
    "",
    "/** How DPV classes a category of personal data. */",
    'export type DpvClass = "PersonalData" | "SensitivePersonalData" | "SpecialCategoryPersonalData";',
    "",
    "/** Every category of DPV-PD by its term, with its label and its class in DPV. */",
    "export const pd = {",
    ...terms.map((t) => `  ${t.term}: { label: ${JSON.stringify(t.label)}, kind: "${t.kind}" },`),
    "} as const satisfies Readonly<Record<string, { readonly label: string; readonly kind: DpvClass }>>;",
    "",
    "/** A term of DPV-PD that names a category of personal data. */",
    "export type PdTerm = keyof typeof pd;",
    "",
  ];
  return { kind: "ok", text: lines.join("\n") };
}

async function csvText(
  arg: string | undefined,
): Promise<{ readonly kind: "ok"; readonly csv: string } | { readonly kind: "err"; readonly error: GenerateError }> {
  try {
    if (arg !== undefined) return { kind: "ok", csv: await fs.readTextFile(arg) };
    const r = await fetch(SOURCE);
    if (!r.ok) return { kind: "err", error: { kind: "fetch", message: `${SOURCE}: ${r.status}` } };
    return { kind: "ok", csv: await r.text() };
  } catch (e) {
    return { kind: "err", error: { kind: "fetch", message: e instanceof Error ? e.message : String(e) } };
  }
}

const say = (e: GenerateError): string => {
  switch (e.kind) {
    case "digest":
      return `the CSV's SHA-256 is ${e.found}, not the pinned ${e.pinned}: the vocabulary changed, so look at the change and pin it, or fix the source`;
    case "csv":
      return `the CSV does not parse: ${e.message}`;
    case "fetch":
      return `the CSV could not be read: ${e.message}`;
  }
};

if (import.meta.main) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const file = args.find((a) => !a.startsWith("--"));
  const got = await csvText(file);
  if (got.kind === "err") {
    console.error(`generate-dpv: ${say(got.error)}`);
    process.exit(2);
  }
  const made = await render(got.csv);
  if (made.kind === "err") {
    console.error(`generate-dpv: ${say(made.error)}`);
    process.exit(2);
  }
  const target = path.join(ROOT, OUT);
  if (check) {
    const now = await fs.readTextFile(target).catch(() => "");
    if (now !== made.text) {
      console.error(`generate-dpv: ${OUT} is not what the CSV makes; run: bun tools/generate-dpv.ts`);
      process.exit(1);
    }
    console.log(`generate-dpv: ${OUT} is what the CSV at DPV ${VERSION} makes`);
  } else {
    await fs.writeTextFile(target, made.text);
    console.log(`generate-dpv: wrote ${OUT} (${made.text.split("\n").length - 1} lines)`);
  }
}
