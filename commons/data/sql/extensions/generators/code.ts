// Spec: 0010-sql-generators FR-008, FR-009, FR-011, FR-012
/**
 * The row types (commons data 0010-sql-generators FR-008, FR-009, FR-011, FR-012): a struct of each table in Rust and a schema of each table in Zod, a field for each column, an `Option` or
 * `.nullable()` where it may be null, and an enum for each column that only a closed list of codes may fill. Every logical type has a form in each.
 *
 * @module
 */
import { ok } from "@intellectual-frontiers/commons/ts/kernel";
import type { LogicalType } from "@intellectual-frontiers/data/sql/logical";
import type { Generator } from "@intellectual-frontiers/data/sql/physical";
import { docOf, lines, oneLine, pascalOf, quoted } from "./model.ts";

const rustType = (t: LogicalType): string => {
  switch (t.kind) {
    case "text":
    case "decimal":
    case "date":
    case "timestamp":
    case "json":
      return "String";
    case "integer":
      return "i64";
    case "boolean":
      return "bool";
    case "bytes":
      return "Vec<u8>";
    case "vector":
      return "Vec<f32>";
  }
};

const rustDoc = (text: string, indent: string): string[] => (oneLine(text) === "" ? [] : [`${indent}/// ${oneLine(text)}`]);

/** The Rust row types: `<domain>.rs`. */
export const rust: Generator = {
  id: "sql.generate.rust",
  describe: "Rust structs of the rows of each table",
  generate: (context) => {
    const doc = docOf(context);
    const out = ["//! Rows of the tables, generated by IFC Data. Do not edit: change the model and generate again."];
    if (context.naming.names.name !== "snake") out.push("#![allow(non_snake_case)]");
    for (const t of doc.tables) {
      const struct = pascalOf(t.table.name.join(" ").replaceAll(" ", "_"));
      const enums = new Map<string, string>();
      for (const c of t.columns) {
        if (c.codes === undefined) continue;
        const name = `${struct}${pascalOf(c.column.name.join("_"))}`;
        enums.set(c.name, name);
        out.push("", `/// The values of ${t.name}.${c.name}.`, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]", `pub enum ${name} {`);
        for (const code of c.codes) out.push(`    /// \`${code}\``, `    ${pascalOf(code)},`);
        out.push("}");
      }
      out.push("", ...rustDoc(t.comment, ""), "#[derive(Debug, Clone, PartialEq)]", `pub struct ${struct} {`);
      for (const c of t.columns) {
        const base = enums.get(c.name) ?? rustType(c.type);
        out.push(...rustDoc(c.comment, "    "), `    pub ${c.name}: ${c.nullable ? `Option<${base}>` : base},`);
      }
      out.push("}");
    }
    return ok([{ path: `${doc.stem}.rs`, text: lines(out) }]);
  },
};

const zodType = (t: LogicalType): string => {
  switch (t.kind) {
    case "text":
    case "decimal":
      return "z.string()";
    case "integer":
      return "z.number().int()";
    case "boolean":
      return "z.boolean()";
    case "date":
      return "isoDate";
    case "timestamp":
      return "z.date()";
    case "json":
      return "z.unknown()";
    case "bytes":
      return "z.instanceof(Uint8Array)";
    case "vector":
      return `z.array(z.number()).length(${t.dimensions})`;
  }
};

/** The Zod schemas: `<domain>.zod.ts`. */
export const zod: Generator = {
  id: "sql.generate.zod",
  describe: "Zod schemas of the rows of each table",
  generate: (context) => {
    const doc = docOf(context);
    const out = [
      "/**",
      " * Zod schemas of the rows of the tables, generated by IFC Data. Do not edit: change the model and generate again.",
      " *",
      " * @module",
      " */",
      'import { z } from "zod";',
      "",
      "/** A calendar date, as a driver gives it. */",
      "const isoDate = z.string().regex(/^\\d{4}-\\d{2}-\\d{2}$/);",
    ];
    for (const t of doc.tables) {
      out.push("", ...(oneLine(t.comment) === "" ? [] : [`/** ${oneLine(t.comment).replaceAll("*/", "* /")} */`]));
      out.push(`export const ${pascalOf(t.table.name.join("_"))} = z.object({`);
      for (const c of t.columns) {
        const base = c.codes === undefined ? zodType(c.type) : `z.enum([${c.codes.map(quoted).join(", ")}])`;
        out.push(`  ${/^[A-Za-z_$][\w$]*$/.test(c.name) ? c.name : quoted(c.name)}: ${base}${c.nullable ? ".nullable()" : ""},`);
      }
      out.push("});");
    }
    return ok([{ path: `${doc.stem}.zod.ts`, text: lines(out) }]);
  },
};
