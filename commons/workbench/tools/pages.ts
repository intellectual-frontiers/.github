/**
 * The generated pages and block of the commons for the workbench: the catalog of errors, the three set-up pages (a person, Claude Code, Codex) made from what the dialects render for the contract of the commons, and the block of
 * `AGENTS.md`. `bun commons/workbench/tools/pages.ts` writes them, `--check` writes nothing and says which differ. They are made from the code, so a page cannot say what the code does not.
 *
 * @module
 */
import { CATALOG, CONCEPTS, type CatalogEntry } from "../src/governance/mod.ts";
import { agentsBlock, spliceBlock } from "../src/logical/mod.ts";
import { render as renderClaude } from "../src/physical/dialects/claude-code/mod.ts";
import { render as renderCodex } from "../src/physical/dialects/codex/mod.ts";
import { render as renderHuman } from "../src/physical/dialects/human/mod.ts";
import { fs, path, proc } from "@intellectual-frontiers/system";
import { contract } from "./commons.contract.ts";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..", "..", "..");
const GUIDES = "commons/docs/guides";
const NOTE = "Generated by `commons/workbench/tools/pages.ts` from the code of the library `workbench`; do not edit it.";
const cmd = contract.command ?? "workbench";

const row = (e: CatalogEntry): string => `| \`${e.code}\` | ${e.title} | ${e.fixer} | ${e.what} | ${e.fix} |`;

function errors(): string {
  const parts = CONCEPTS.map((c) => {
    const entries = Object.values(CATALOG).filter((e) => e.concept === c);
    return entries.length === 0 ? "" : `## ${c[0]?.toUpperCase()}${c.slice(1)}\n\n| Code | What happened | Who fixes it | What it says | The fix |\n|---|---|---|---|---|\n${entries.map(row).join("\n")}\n`;
  });
  return [
    "# Errors of the workbench, and what to do",
    "",
    NOTE,
    "",
    `Every failure the workbench reports has one code, \`E-WB-<CONCEPT>-<KIND>\`, belongs to one of the four words (workstation, workshop, workspace, workbench) and has one fix. \`${cmd} explain CODE\` says the same as this page. Until ${contract.enforceFrom} a finding is only a hint, except a safety rule, which is always an error.`,
    "",
    "**Who fixes it:** `agent` means the one working can run the fix; `person` means a person must do it (a credential, an approval); `environment` means the owner of the workshop; `ci` means a rebuild.",
    "",
    "**A failure that is in none of these** is `E-WB-UNKNOWN`: classify it by adding an entry, a check and a test, and documenting it, in one change.",
    "",
    ...parts,
  ].join("\n");
}

function human(): string {
  const run = renderHuman(contract)[0]?.text ?? "";
  return ["# Set up as a person", "", NOTE, "", `You are a person: you may work in your own checkout or in worktrees of your own, you review and approve what an agent proposes, and you hold the gates that only a person may pass. The runbook below is generated from the contract of the commons (\`${cmd} project runbook\` prints it).`, "", run.replace(/^# .*\n/u, "").replace(/^## /gmu, "## ")].join("\n");
}

function claudeCode(): string {
  const files = renderClaude(contract);
  return [
    "# Set up Claude Code",
    "",
    NOTE,
    "",
    "Claude Code reads `CLAUDE.md`, which sends it to `AGENTS.md`, and its settings. The dialect for Claude Code makes both from the contract: a hook that runs the check when a session starts, and a deny rule for each command that only a person may run (the commands of the gates). Put the settings in the settings of your own Claude Code (at the level you choose; this repository does not commit a folder of an agent's local settings).",
    "",
    ...files.flatMap((f) => [`## \`${f.path}\``, "", "```" + (f.path.endsWith(".json") ? "json" : "markdown"), f.text.trimEnd(), "```", ""]),
    "## Check it",
    "",
    "```",
    `${cmd} ready`,
    `${cmd} ready --for test --unit <library> --ensure`,
    "```",
    "",
    "The format of the settings is the one the harness documents; it is checked against its current documentation before a release of the library.",
    "",
  ].join("\n");
}

function codex(): string {
  const file = renderCodex(contract)[0];
  return [
    "# Set up Codex",
    "",
    NOTE,
    "",
    `Codex reads \`AGENTS.md\`. The dialect for Codex puts the contract there, between two marks, with \`${cmd} ready\` as the first command to run. It does not write the approval and sandbox settings of the harness: they are yours to set in its own configuration, to match the autonomy levels of the stages below, and the format is checked against its current documentation before this library writes it.`,
    "",
    "## The block of `AGENTS.md`",
    "",
    "```markdown",
    (file?.text ?? "").slice((file?.text ?? "").indexOf("<!-- workbench:begin -->")).trimEnd(),
    "```",
    "",
    "## Check it",
    "",
    "```",
    `${cmd} ready`,
    `${cmd} ready --for test --unit <library> --ensure`,
    "```",
    "",
  ].join("\n");
}

/** Every file this writes, with its text. */
export async function outputs(): Promise<Readonly<Record<string, string>>> {
  const agents = await fs.readTextFile(path.join(ROOT, "AGENTS.md"));
  return {
    [`${GUIDES}/workbench-errors.auto.md`]: errors(),
    [`${GUIDES}/workbench-setup-human.auto.md`]: human(),
    [`${GUIDES}/workbench-setup-claude-code.auto.md`]: claudeCode(),
    [`${GUIDES}/workbench-setup-codex.auto.md`]: codex(),
    "AGENTS.md": spliceBlock(agents, agentsBlock(contract)),
  };
}

if (import.meta.main) {
  const check = proc.args.includes("--check");
  const stale: string[] = [];
  for (const [file, text] of Object.entries(await outputs())) {
    const full = path.join(ROOT, file);
    const have = (await fs.exists(full)) ? await fs.readTextFile(full) : undefined;
    if (have === text) continue;
    stale.push(file);
    if (!check) await fs.writeTextFile(full, text);
  }
  if (check && stale.length > 0) {
    console.error(`stale: ${stale.join(", ")}: run bun commons/workbench/tools/pages.ts`);
    proc.exit(1);
  }
  console.log(check ? "the pages and the block of AGENTS.md are current" : `wrote ${stale.length} files`);
}
