/**
 * The renderers of the operate script for PowerShell 7 and of the public bootstrap that fetches a repository and runs its operate script, the same steps in the same order as the scripts for Bash 5. Pure functions of the plan and of
 * the digest the caller gives: the same bytes each time, printable ASCII, no value of a credential. The tools come from `winget`; the run stops at the first step that fails, and a script read from the web never ends the person's session.
 *
 * @example
 * ```ts
 * import { bootstrapPs1 } from "./operate-ps1.ts";
 * bootstrapPs1().includes("#requires -Version 7"); // true
 * ```
 *
 * @module
 */
import { type OperateSpec } from "@intellectual-frontiers/workbench/governance";
import { shq, text } from "./operate-text.ts";

const HEAD = (title: string, from: string): string => text`#requires -Version 7
# ${title}. Generated by ${from}: do not edit it, generate it again. It assumes PowerShell 7 or newer.
# Every step checks before it acts, so it can be run again at any time: a run in which every check holds changes nothing and says so.
`;

const COMMON = text`
$ErrorActionPreference = 'Stop'
$global:LASTEXITCODE = 0
$script:Changed = 0
$script:Fancy = ($Host.UI.SupportsVirtualTerminal -and -not [Console]::IsOutputRedirected -and -not $env:NO_COLOR -and $env:TERM -ne 'dumb')
$script:IOk = if ($script:Fancy) { [string][char]0x2705 } else { '[ok]' }
$script:IDo = if ($script:Fancy) { [string][char]0x23F3 } else { '[do]' }
$script:IBad = if ($script:Fancy) { [string][char]0x274C } else { '[!!]' }

function Write-Say([string]$Text) { $Host.UI.WriteLine($Text) }
function Write-Ok([string]$Text) { Write-Say "$($script:IOk) $Text" }
function Write-Did([string]$Text) { $script:Changed++; Write-Say "$($script:IDo) $Text" }
function Exit-Step([string]$Text, [string]$Hint = '') {
  $message = $Text
  if ($Hint) { $message = $Text + [Environment]::NewLine + '   ' + $Hint }
  throw [System.InvalidOperationException]::new($message)
}
function Test-Tool([string]$Name) { [bool](Get-Command $Name -ErrorAction SilentlyContinue) }
function Sync-SessionPath {
  $env:Path = (([Environment]::GetEnvironmentVariable('Path', 'Machine')), ([Environment]::GetEnvironmentVariable('Path', 'User')) -join ';')
  $bun = Join-Path $HOME '.bun/bin'
  if ((Test-Path $bun) -and ($env:Path -notlike "*$bun*")) { $env:Path = $bun + ';' + $env:Path }
}
function Install-WithWinget([string]$Id) {
  if (-not (Test-Tool 'winget')) { Exit-Step 'winget is not installed' 'install App Installer from the Microsoft Store and run this again' }
  & winget install --id $Id -e --silent --accept-source-agreements --accept-package-agreements
  if ($LASTEXITCODE -ne 0) { Exit-Step "winget could not install $Id" "run winget install --id $Id by hand and run this again" }
  Sync-SessionPath
}
function Initialize-Git {
  if (Test-Tool 'git') { Write-Ok ("git " + ((& git --version) -replace '^git version ', '')); return }
  Write-Did 'installing git'
  Install-WithWinget 'Git.Git'
  if (-not (Test-Tool 'git')) { Exit-Step 'git did not install' 'open a new PowerShell 7 window and run this again' }
}
function Initialize-GitHubCli {
  if (Test-Tool 'gh') { Write-Ok ("gh " + ((& gh --version | Select-Object -First 1) -split ' ')[2]); return }
  Write-Did 'installing the GitHub CLI (gh)'
  Install-WithWinget 'GitHub.cli'
  if (-not (Test-Tool 'gh')) { Exit-Step 'gh did not install' 'open a new PowerShell 7 window and run this again' }
}
function Connect-GitHub {
  if ($env:GH_TOKEN -or $env:GITHUB_TOKEN) { Write-Ok 'signed in to GitHub by the token of the environment'; return }
  $status = (& gh auth status --hostname github.com 2>&1 | Out-String)
  if ($LASTEXITCODE -eq 0) {
    if ($status -like '*read:packages*') { Write-Ok 'signed in to GitHub with read:packages' }
    else {
      Write-Did 'adding read:packages to the GitHub sign-in (a code and a browser)'
      & gh auth refresh --hostname github.com --scopes read:packages
      if ($LASTEXITCODE -ne 0) { Exit-Step 'the GitHub sign-in did not finish' 'run this again' }
    }
  } else {
    Write-Did 'signing in to GitHub (a code and a browser)'
    & gh auth login --hostname github.com --git-protocol https --web --scopes read:packages
    if ($LASTEXITCODE -ne 0) { Exit-Step 'the GitHub sign-in did not finish' 'run this again' }
  }
  & gh auth setup-git --hostname github.com *> $null
  $global:LASTEXITCODE = 0
}
function Test-Native([string[]]$Argv, [string]$Folder) {
  Push-Location $Folder
  try {
    $rest = @($Argv | Select-Object -Skip 1)
    & $Argv[0] @rest *> $null
    return ($LASTEXITCODE -eq 0)
  } catch { return $false } finally { Pop-Location }
}
function Invoke-Native([string[]]$Argv, [string]$Folder) {
  Push-Location $Folder
  try {
    $rest = @($Argv | Select-Object -Skip 1)
    & $Argv[0] @rest | Out-Host
    return ($LASTEXITCODE -eq 0)
  } finally { Pop-Location }
}
`;

const words = (argv: readonly string[]): string => `@(${argv.map(shq).join(", ")})`;

/** The operate script for PowerShell 7 of a plan, from the digest of the plan. */
export function operatePs1(spec: OperateSpec, digest: string): string {
  const converge = spec.converge
    .map(
      (s) => text`  # step ${s.id}
  Invoke-Converge -Id ${shq(s.id)} -Say ${shq(s.say)} -Check ${words(s.check)} -Run ${words(s.run)}
`,
    )
    .join("");
  const token = spec.registry.tokenEnv;
  const pinned = `bun ${spec.bun.minimum} or newer`;
  return (
    HEAD(`${spec.name} operate: sets this repository up so that it can be operated, and brings it up to date`, `${spec.slug} fleet write (plan ${digest})`) +
    COMMON +
    text`
function Initialize-Bun {
  if (Test-Tool 'bun') {
    $have = [version]((& bun --version) -replace '[^0-9.]', '')
    if ($have -ge [version]${shq(spec.bun.minimum)}) { Write-Ok "bun $have"; return }
  }
  Write-Did 'installing bun with winget'
  Install-WithWinget 'Oven-sh.Bun'
  if (-not (Test-Tool 'bun')) { Exit-Step 'bun did not install' 'install ${pinned} from https://bun.sh, open a new PowerShell 7 window and run this again' }
  Write-Ok ("bun " + (& bun --version))
}
function Initialize-RegistryToken {
  if (-not [Environment]::GetEnvironmentVariable(${shq(token)}, 'Process')) {
    $token = & gh auth token --hostname github.com
    if ($LASTEXITCODE -ne 0 -or -not $token) { Exit-Step 'the GitHub CLI has no token to give' 'sign in again: gh auth login --hostname github.com --scopes read:packages' }
    [Environment]::SetEnvironmentVariable(${shq(token)}, $token, 'Process')
  }
}
function Sync-Repository {
  & git -C $script:Root rev-parse --is-inside-work-tree *> $null
  if ($LASTEXITCODE -ne 0) { Exit-Step "$($script:Root) is not a Git clone" 'clone the repository and run bin/operate.ps1 in it' }
  if (-not (& git -C $script:Root remote)) { Write-Ok 'this clone has no remote: left as it is'; return }
  & git -C $script:Root symbolic-ref -q HEAD *> $null
  $onBranch = ($LASTEXITCODE -eq 0)
  & git -C $script:Root rev-parse --abbrev-ref '@{u}' *> $null
  if (-not $onBranch -or $LASTEXITCODE -ne 0) { Write-Ok 'this clone follows no branch: left as it is'; return }
  if (& git -C $script:Root status --porcelain) { Write-Ok 'this clone has changes that are not committed: left as it is'; return }
  $before = (& git -C $script:Root rev-parse HEAD)
  & git -C $script:Root pull --ff-only --quiet
  if ($LASTEXITCODE -ne 0) { Exit-Step 'the clone could not be brought up to date by a fast-forward' "look at it with: git -C $($script:Root) status" }
  if ((& git -C $script:Root rev-parse HEAD) -eq $before) { Write-Ok 'the clone is up to date' }
  else { Write-Did ("brought the clone up to date (" + (& git -C $script:Root rev-parse --short HEAD) + ")") }
}
function Get-Stamp {
  $bytes = [IO.File]::ReadAllBytes((Join-Path $script:Root 'package.json'))
  $lock = Join-Path $script:Root 'bun.lock'
  if (Test-Path $lock) { $bytes += [IO.File]::ReadAllBytes($lock) }
  return [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($bytes)).ToLowerInvariant()
}
function Install-DependencyTree {
  $want = Get-Stamp
  if ((Test-Path (Join-Path $script:Root 'node_modules')) -and (Test-Path $script:Stamp) -and ((Get-Content -Raw $script:Stamp).Trim() -eq $want)) {
    Write-Ok 'the dependencies are installed (nothing changed since the last run)'; return
  }
  Write-Did 'installing the dependencies (bun install)'
  $argv = @('bun', 'install')
  if (Test-Path (Join-Path $script:Root 'bun.lock')) { $argv += '--frozen-lockfile' }
  if (-not (Invoke-Native $argv $script:Root)) {
    Exit-Step 'bun install failed' 'its message is above; a 401 or 403 means the sign-in needs read:packages and access to the packages of ${spec.registry.scope}: run gh auth refresh --hostname github.com --scopes read:packages, then run this again'
  }
  New-Item -ItemType Directory -Force -Path (Split-Path $script:Stamp) | Out-Null
  Set-Content -Path $script:Stamp -Value $want
}
function Invoke-Converge([string]$Id, [string]$Say, [string[]]$Check, [string[]]$Run) {
  if (Test-Native $Check $script:Root) { Write-Ok $Say; return }
  Write-Did $Say
  if (-not (Invoke-Native $Run $script:Root)) { Exit-Step "the step $Id failed" ('run it by hand in the repository: ' + ($Run -join ' ')) }
  if (-not (Test-Native $Check $script:Root)) { Exit-Step "the step $Id ran but its check still fails" ('run it by hand in the repository: ' + ($Check -join ' ')) }
}
function Invoke-Main {
  $script:Root = Split-Path -Parent $PSScriptRoot
  $script:Stamp = Join-Path $script:Root '.${spec.slug}/operate.stamp'
  # step git
  Initialize-Git
  # step gh
  Initialize-GitHubCli
  # step bun
  Initialize-Bun
  # step sign-in
  Connect-GitHub
  Initialize-RegistryToken
  # step update
  Sync-Repository
  # step install
  Install-DependencyTree
${converge}  if ($script:Changed -eq 0) { Write-Say 'Nothing to do. ${spec.name} is ready.' } else { Write-Say "Done: $($script:Changed) change(s) made." }
  Write-Say ''
  Write-Say ${shq(`Next: ${spec.next.say}`)}
  Write-Say ("  cd '" + $script:Root + "'")
  Write-Say ${shq(`  ${spec.next.argv.join(" ")}`)}
}
try { Invoke-Main } catch { $Host.UI.WriteErrorLine("$($script:IBad) $($_.Exception.Message)"); exit 1 }
`
  );
}

/** The public bootstrap for PowerShell 7: given `-Repo OWNER/NAME` and optionally `-Dir`, it makes Git and GitHub CLI and the sign-in ready, clones the repository and runs that repository's own `bin/operate.ps1`. It names no product. */
export function bootstrapPs1(): string {
  return (
    HEAD("Bootstrap: makes git and the GitHub CLI ready, signs in to GitHub, clones a repository and runs its own bin/operate.ps1", "the workbench library of the commons (0007-workbench-operate)") +
    text`param(
  [Parameter(Mandatory = $true)][string]$Repo,
  [string]$Dir = ''
)
` +
    COMMON +
    text`
function Invoke-Main([string]$Repo, [string]$Dir) {
  if ($Repo -notmatch '^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$') { Exit-Step 'which repository? Give it as OWNER/NAME' '& ([scriptblock]::Create((Invoke-RestMethod URL))) -Repo OWNER/NAME' }
  $folder = $Dir
  if (-not $folder) { $folder = Join-Path $HOME ($Repo -split '/')[1] }
  Initialize-Git
  Initialize-GitHubCli
  Connect-GitHub
  if (Test-Path (Join-Path $folder '.git')) { Write-Ok "$folder is already a clone" }
  elseif ((Test-Path $folder) -and (Get-ChildItem -Force $folder | Select-Object -First 1)) { Exit-Step "$folder exists and is not a clone" 'give another folder with -Dir' }
  else {
    Write-Did "cloning $Repo to $folder"
    & gh repo clone $Repo $folder -- --quiet
    if ($LASTEXITCODE -ne 0) { Exit-Step 'the clone failed' "your GitHub account may not be able to read $@{Repo}: ask its owner for access, then run this again" }
  }
  $operate = Join-Path $folder 'bin/operate.ps1'
  if (-not (Test-Path $operate)) { Exit-Step "$Repo has no bin/operate.ps1" 'it is not set up to be operated by a script' }
  Write-Say ''
  & pwsh -NoProfile -File $operate
  if ($LASTEXITCODE -ne 0) { Exit-Step 'the operate script of the repository stopped' 'its own message is above' }
}
try { Invoke-Main -Repo $Repo -Dir $Dir } catch { $Host.UI.WriteErrorLine("$($script:IBad) $($_.Exception.Message)"); $global:LASTEXITCODE = 1; if ($PSCommandPath) { exit 1 } }
`
  );
}
