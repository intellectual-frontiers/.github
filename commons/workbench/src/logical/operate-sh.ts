/**
 * The renderers of the operate script for Bash 5 and of the public bootstrap that fetches a repository and runs its operate script. Pure functions of the plan and of the digest the caller gives: the same bytes each time, printable ASCII,
 * no value of a credential. Every step checks before it acts, the whole script is one function that is read before it runs (a script that updates its own repository is not changed under its feet), and the run stops at the first step
 * that fails.
 *
 * @example
 * ```ts
 * import { bootstrapSh } from "./operate-sh.ts";
 * bootstrapSh().startsWith("#!/usr/bin/env bash"); // true
 * ```
 *
 * @module
 */
import { type BunPin, type OperateSpec } from "@intellectual-frontiers/workbench/governance";
import { fnOf, shq, shWords, text } from "./operate-text.ts";

const HEAD = (title: string, from: string): string => text`#!/usr/bin/env bash
# ${title}. Generated by ${from}: do not edit it, generate it again. It assumes Bash 5 or newer.
# Every step checks before it acts, so it can be run again at any time: a run in which every check holds changes nothing and says so.
set -euo pipefail
if (( BASH_VERSINFO[0] < 5 )); then
  printf '%s\n' "This needs Bash 5 or newer (this is Bash $@{BASH_VERSION}). Install it (macOS: brew install bash), then run this again with it." >&2
  exit 1
fi
`;

/** What both scripts share: the words they say, the system's package manager and the steps that obtain Git, GitHub CLI and the sign-in. */
const COMMON = text`
if [[ -t 1 && -z "$@{NO_COLOR:-}" && "$@{TERM:-dumb}" != dumb && "$@{LC_ALL:-$@{LC_CTYPE:-$@{LANG:-}}}" == *[Uu][Tt][Ff]* ]]; then
  I_OK=$'\xe2\x9c\x85' I_DO=$'\xe2\x8f\xb3' I_BAD=$'\xe2\x9d\x8c'
else
  I_OK='[ok]' I_DO='[do]' I_BAD='[!!]'
fi
CHANGED=0
APT_UPDATED=0
say() { printf '%s\n' "$*"; }
st_ok() { say "$I_OK $*"; }
did() { CHANGED=$((CHANGED + 1)); say "$I_DO $*"; }
fail() { say "$I_BAD $1" >&2; if [[ -n "$@{2:-}" ]]; then say "   $2" >&2; fi; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }
as_root() { if [[ "$(id -u)" == 0 ]]; then "$@"; elif have sudo; then sudo "$@"; else fail "this needs administrator rights and sudo is not installed" "run this as root, or install sudo"; fi; }

detect_platform() {
  case "$(uname -s)" in
    Linux) OS=linux ;;
    Darwin) OS=macos ;;
    *) fail "this system ($(uname -s)) is not supported by this script" "Windows uses the PowerShell script" ;;
  esac
  # shellcheck disable=SC2034
  case "$(uname -m)" in
    x86_64 | amd64) ARCH=x64 ;;
    aarch64 | arm64) ARCH=arm64 ;;
    *) ARCH=$(uname -m) ;;
  esac
}

pkg() {
  if [[ "$OS" == macos ]]; then
    have brew || fail "Homebrew is not installed" "install it from https://brew.sh and run this again"
    brew install "$@"
  elif have apt-get; then
    local out
    if (( APT_UPDATED == 0 )); then
      out="$(as_root env DEBIAN_FRONTEND=noninteractive apt-get update -qq 2>&1)" || { printf '%s\n' "$out" >&2; return 1; }
      APT_UPDATED=1
    fi
    out="$(as_root env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "$@" 2>&1)" || { printf '%s\n' "$out" >&2; return 1; }
  elif have dnf; then
    as_root dnf install -y -q "$@"
  elif have pacman; then
    as_root pacman -S --needed --noconfirm "$@"
  else
    fail "no package manager is known here (apt-get, dnf, pacman, brew)" "install $* by hand and run this again"
  fi
}

ensure_git() {
  if have git; then st_ok "git $(git --version | cut -d' ' -f3)"; return; fi
  did "installing git"
  pkg git || fail "git could not be installed" "the message above says why; install git by hand and run this again"
  have git || fail "git did not install" "install it by hand and run this again"
}

ensure_gh() {
  if have gh; then st_ok "gh $(gh --version | head -n 1 | cut -d' ' -f3)"; return; fi
  did "installing the GitHub CLI (gh)"
  if [[ "$OS" == linux ]] && have pacman && ! have apt-get && ! have dnf; then pkg github-cli || fail "the GitHub CLI could not be installed" "the message above says why"; else pkg gh || fail "the GitHub CLI could not be installed" "the message above says why"; fi
  have gh || fail "gh did not install" "install the GitHub CLI from https://cli.github.com and run this again"
}

tty_run() { if { : </dev/tty; } 2>/dev/null; then "$@" </dev/tty; else "$@"; fi; }

sign_in() {
  if [[ -n "$@{GH_TOKEN:-}$@{GITHUB_TOKEN:-}" ]]; then st_ok "signed in to GitHub by the token of the environment"; return; fi
  local status
  if status="$(gh auth status --hostname github.com 2>&1)"; then
    if [[ "$status" == *read:packages* ]]; then
      st_ok "signed in to GitHub with read:packages"
    else
      did "adding read:packages to the GitHub sign-in (a code and a browser)"
      tty_run gh auth refresh --hostname github.com --scopes read:packages || fail "the GitHub sign-in did not finish" "run this again"
    fi
  else
    did "signing in to GitHub (a code and a browser)"
    tty_run gh auth login --hostname github.com --git-protocol https --web --scopes read:packages || fail "the GitHub sign-in did not finish" "run this again"
  fi
  gh auth setup-git --hostname github.com >/dev/null 2>&1 || true
}
`;

const pinArm = (p: BunPin): string => `    ${p.platform}) BUN_URL=${shq(p.url)} BUN_SHA=${shq(p.sha256)} BUN_ENTRY=${shq(p.entry)} ;;`;

/** The operate script for Bash 5 of a plan, from the digest of the plan. */
export function operateSh(spec: OperateSpec, digest: string): string {
  const pins = spec.bun.pins.map(pinArm).join("\n");
  const converge = spec.converge
    .map((s) =>
      text`
${fnOf(s.id)}() {
  if ( cd "$ROOT" && ${shWords(s.check)} ) >/dev/null 2>&1; then st_ok ${shq(s.say)}; return; fi
  did ${shq(s.say)}
  ( cd "$ROOT" && ${shWords(s.run)} ) || fail "the step ${s.id} failed" "run it by hand in the repository: ${shWords(s.run).replaceAll("'", "")}"
  ( cd "$ROOT" && ${shWords(s.check)} ) >/dev/null 2>&1 || fail "the step ${s.id} ran but its check still fails" "run it by hand in the repository: ${shWords(s.check).replaceAll("'", "")}"
}
`,
    )
    .join("");
  const calls = spec.converge.map((s) => `  # step ${s.id}\n  ${fnOf(s.id)}\n`).join("");
  const token = spec.registry.tokenEnv;
  return (
    HEAD(`${spec.name} operate: sets this repository up so that it can be operated, and brings it up to date`, `${spec.slug} fleet write (plan ${digest})`) +
    COMMON +
    text`
version_ge() { [[ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n 1)" == "$2" ]]; }
sha256_of() { if have sha256sum; then sha256sum; else shasum -a 256; fi | cut -d' ' -f1; }

BUN_BIN="$HOME/.bun/bin"
export PATH="$BUN_BIN:$PATH"

ensure_bun() {
  local have_version
  if have bun; then
    have_version="$(bun --version)"
    if version_ge "$have_version" ${shq(spec.bun.minimum)}; then st_ok "bun $have_version"; return; fi
  fi
  BUN_URL="" BUN_SHA="" BUN_ENTRY=""
  case "$OS-$ARCH" in
${pins}
  esac
  if [[ -n "$BUN_URL" ]]; then
    did "installing bun ${spec.bun.version} from its pinned download (SHA-256 checked)"
    have curl || pkg curl || fail "curl could not be installed" "the message above says why"
    have unzip || pkg unzip || fail "unzip could not be installed" "the message above says why"
    local tmp got
    tmp="$(mktemp -d)"
    curl -fsSL "$BUN_URL" -o "$tmp/bun.zip" || { rm -rf "$tmp"; fail "the download of bun failed" "check the network and run this again"; }
    got="$(sha256_of < "$tmp/bun.zip")"
    if [[ "$got" != "$BUN_SHA" ]]; then rm -rf "$tmp"; fail "the download of bun does not match its pinned SHA-256" "expected $BUN_SHA, got $got: nothing was installed"; fi
    unzip -q -o "$tmp/bun.zip" -d "$tmp"
    mkdir -p "$BUN_BIN"
    install -m 0755 "$tmp/$BUN_ENTRY/bun" "$BUN_BIN/bun"
    rm -rf "$tmp"
    if ! grep -qs '\.bun/bin' "$HOME/.bashrc"; then
      # shellcheck disable=SC2016
      printf '\n# bun (added by ${spec.name} operate)\nexport PATH="$HOME/.bun/bin:$PATH"\n' >> "$HOME/.bashrc"
      did "added ~/.bun/bin to the PATH of new shells (~/.bashrc)"
    fi
  elif [[ "$OS" == macos ]]; then
    did "installing bun with Homebrew"
    pkg oven-sh/bun/bun || fail "bun could not be installed" "the message above says why"
  else
    fail "there is no pinned download of bun for $OS-$ARCH" "install bun ${spec.bun.minimum} or newer from https://bun.sh and run this again"
  fi
  have bun || fail "bun did not install" "install bun ${spec.bun.minimum} or newer from https://bun.sh and run this again"
  st_ok "bun $(bun --version)"
}

export_token() {
  if [[ -z "$@{${token}:-}" ]]; then
    ${token}="$(gh auth token --hostname github.com)" || fail "the GitHub CLI has no token to give" "sign in again: gh auth login --hostname github.com --scopes read:packages"
    export ${token}
  fi
}

update_repo() {
  git -C "$ROOT" rev-parse --is-inside-work-tree >/dev/null 2>&1 || fail "$ROOT is not a Git clone" "clone the repository and run bin/operate.sh in it"
  if [[ -z "$(git -C "$ROOT" remote)" ]]; then st_ok "this clone has no remote: left as it is"; return; fi
  if ! git -C "$ROOT" symbolic-ref -q HEAD >/dev/null || ! git -C "$ROOT" rev-parse --abbrev-ref '@{u}' >/dev/null 2>&1; then st_ok "this clone follows no branch: left as it is"; return; fi
  if [[ -n "$(git -C "$ROOT" status --porcelain)" ]]; then st_ok "this clone has changes that are not committed: left as it is"; return; fi
  local before
  before="$(git -C "$ROOT" rev-parse HEAD)"
  git -C "$ROOT" pull --ff-only --quiet || fail "the clone could not be brought up to date by a fast-forward" "look at it with: git -C $ROOT status"
  if [[ "$(git -C "$ROOT" rev-parse HEAD)" == "$before" ]]; then st_ok "the clone is up to date"; else did "brought the clone up to date ($(git -C "$ROOT" rev-parse --short HEAD))"; fi
}

stamp_of() {
  { cat "$ROOT/package.json"; if [[ -f "$ROOT/bun.lock" ]]; then cat "$ROOT/bun.lock"; fi; } | sha256_of
}

install_deps() {
  local want flag=()
  want="$(stamp_of)"
  if [[ -d "$ROOT/node_modules" && -f "$STAMP" && "$(cat "$STAMP")" == "$want" ]]; then st_ok "the dependencies are installed (nothing changed since the last run)"; return; fi
  did "installing the dependencies (bun install)"
  if [[ -f "$ROOT/bun.lock" ]]; then flag=(--frozen-lockfile); fi
  ( cd "$ROOT" && bun install "$@{flag[@]}" ) || fail "bun install failed" "its message is above; a 401 or 403 means the sign-in needs read:packages and access to the packages of ${spec.registry.scope}: run gh auth refresh --hostname github.com --scopes read:packages, then run this again"
  mkdir -p "$(dirname "$STAMP")"
  printf '%s\n' "$want" > "$STAMP"
}
${converge}
main() {
  ROOT="$(cd "$(dirname "$@{BASH_SOURCE[0]}")/.." && pwd)"
  STAMP="$ROOT/.${spec.slug}/operate.stamp"
  detect_platform
  # step git
  ensure_git
  # step gh
  ensure_gh
  # step bun
  ensure_bun
  # step sign-in
  sign_in
  export_token
  # step update
  update_repo
  # step install
  install_deps
${calls}  if (( CHANGED == 0 )); then say "Nothing to do. ${spec.name} is ready."; else say "Done: $CHANGED change(s) made."; fi
  say ""
  say ${shq(`Next: ${spec.next.say}`)}
  printf '  cd %q\n' "$ROOT"
  say ${shq(`  ${spec.next.argv.join(" ")}`)}
}
main "$@"; exit
`
  );
}

/** The public bootstrap for Bash 5: given `OWNER/NAME` and optionally a folder, it makes Git and GitHub CLI and the sign-in ready, clones the repository and runs that repository's own `bin/operate.sh`. It names no product. */
export function bootstrapSh(): string {
  return (
    HEAD("Bootstrap: makes git and the GitHub CLI ready, signs in to GitHub, clones a repository and runs its own bin/operate.sh", "the workbench library of the commons (0007-workbench-operate)") +
    COMMON +
    text`
main() {
  local repo="$@{1:-}" dir="$@{2:-}"
  if [[ ! "$repo" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]]; then
    fail "which repository? Give it as OWNER/NAME" "curl -fsSL URL | bash -s -- OWNER/NAME [FOLDER]"
  fi
  if [[ -z "$dir" ]]; then dir="$HOME/$@{repo#*/}"; fi
  detect_platform
  ensure_git
  ensure_gh
  sign_in
  if [[ -d "$dir/.git" ]]; then
    st_ok "$dir is already a clone"
  elif [[ -e "$dir" && -n "$(ls -A "$dir" 2>/dev/null)" ]]; then
    fail "$dir exists and is not a clone" "give another folder as the second argument"
  else
    did "cloning $repo to $dir"
    gh repo clone "$repo" "$dir" -- --quiet || fail "the clone failed" "your GitHub account may not be able to read $repo: ask its owner for access, then run this again"
  fi
  [[ -f "$dir/bin/operate.sh" ]] || fail "$repo has no bin/operate.sh" "it is not set up to be operated by a script"
  say ""
  exec bash "$dir/bin/operate.sh"
}
main "$@"; exit
`
  );
}
