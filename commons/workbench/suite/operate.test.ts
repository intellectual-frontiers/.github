/**
 * Tests of the operate scripts (commons workbench 0007-workbench-operate FR-001 to FR-011): the plan is decoded with every reason, the two scripts are pure, ASCII and carry the same steps in the same order, every step checks before it
 * acts, the tools come only by the ways the specification names, the token is never printed or written, and the public bootstrap files of the commons are what the renderers write. The plan is made up.
 *
 * @module
 */
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { type OperateSpec, defineOperate, operateSteps } from "@intellectual-frontiers/workbench/governance";
import { bootstrapPs1, bootstrapSh, operatePs1, operateSh } from "@intellectual-frontiers/workbench/logical";
import { assert, assertEquals, proves } from "@intellectual-frontiers/test";

const SHA_X64 = "a".repeat(64);
const SHA_ARM = "b".repeat(64);
const SPEC: OperateSpec = {
  name: "Demo",
  slug: "demo",
  bun: {
    version: "1.4.4",
    minimum: "1.4.0",
    pins: [
      { platform: "linux-x64", url: "https://example.test/bun-linux-x64.zip", sha256: SHA_X64, entry: "bun-linux-x64" },
      { platform: "linux-arm64", url: "https://example.test/bun-linux-aarch64.zip", sha256: SHA_ARM, entry: "bun-linux-aarch64" },
    ],
  },
  registry: { scope: "@demo", tokenEnv: "DEMO_TOKEN" },
  converge: [{ id: "write", say: "the generated files are current", check: ["bun", "run", "demo", "check"], run: ["bun", "run", "demo", "write"] }],
  next: { say: "begin", argv: ["bun", "run", "demo", "next"] },
};
const DIGEST = "c".repeat(64);

function ok(spec: OperateSpec): OperateSpec {
  const made = defineOperate(spec);
  if (made.kind === "err") throw new Error(made.error.join("; "));
  return made.value;
}

const stepsOf = (script: string): readonly string[] => [...script.matchAll(/^\s*# step ([a-z-]+)$/gmu)].map((m) => m[1] ?? "");

proves(["0007-workbench-operate FR-001"], "a plan is refused with every reason, and a credential is only a name", () => {
  assertEquals(defineOperate(SPEC).kind, "ok");
  const bad = defineOperate({
    ...SPEC,
    name: "",
    slug: "Bad Slug",
    bun: { version: "1.4", minimum: "2.0.0", pins: [{ platform: "linux-x64", url: "http://example.test/x.zip", sha256: "xyz", entry: "a b" }, { platform: "linux-x64", url: "https://example.test/y.zip", sha256: SHA_X64, entry: "e" }] },
    registry: { scope: "demo", tokenEnv: "lowercase" },
    converge: [{ id: "git", say: "dup of a fixed step", check: ["bun; rm"], run: [] }],
    next: { say: "ok", argv: ["a|b"] },
  });
  assertEquals(bad.kind, "err");
  const reasons = bad.kind === "err" ? bad.error.join("\n") : "";
  for (const needle of ["name:", "slug:", "bun.version", "bun.pins", "twice", "sha256", "registry.scope", "registry.tokenEnv", "step of the library", "safe alphabet", "empty", "next.argv"]) assert(reasons.includes(needle), `a reason names ${needle}: ${reasons}`);
  const secret = defineOperate({ ...SPEC, next: { say: "begin", argv: ["echo", `ghp_${"a".repeat(30)}`] } });
  assert(secret.kind === "err" && secret.error.some((r) => r.includes("secret")));
});

proves(["0007-workbench-operate FR-002"], "the scripts are pure, printable ASCII, generated by a digest, without a value, and name the Bash and PowerShell they assume", () => {
  const spec = ok(SPEC);
  for (const script of [operateSh(spec, DIGEST), operatePs1(spec, DIGEST), bootstrapSh(), bootstrapPs1()]) {
    assert(/^[\x20-\x7e\n]*$/u.test(script), "printable ASCII only");
    assert(script.includes("Generated by"), "it says it is generated");
  }
  assertEquals(operateSh(spec, DIGEST), operateSh(spec, DIGEST));
  assertEquals(operatePs1(spec, DIGEST), operatePs1(spec, DIGEST));
  assert(operateSh(spec, DIGEST).includes(DIGEST) && operatePs1(spec, DIGEST).includes(DIGEST));
  assert(operateSh(spec, DIGEST).startsWith("#!/usr/bin/env bash") && operateSh(spec, DIGEST).includes("BASH_VERSINFO[0] < 5"));
  assert(operatePs1(spec, DIGEST).startsWith("#requires -Version 7"));
  assert(bootstrapPs1().startsWith("#requires -Version 7") && bootstrapSh().includes("BASH_VERSINFO[0] < 5"));
});

proves(["0007-workbench-operate FR-003"], "the two scripts have the same steps in the same order", () => {
  const spec = ok(SPEC);
  assertEquals(operateSteps(spec), ["git", "gh", "bun", "sign-in", "update", "install", "write"]);
  assertEquals(stepsOf(operateSh(spec, DIGEST)), operateSteps(spec));
  assertEquals(stepsOf(operatePs1(spec, DIGEST)), operateSteps(spec));
});

proves(["0007-workbench-operate FR-004"], "every step checks before it acts, the run stops at the first failure and a run with nothing to do says so", () => {
  const sh = operateSh(ok(SPEC), DIGEST);
  const ps = operatePs1(ok(SPEC), DIGEST);
  assert(sh.includes("set -euo pipefail") && sh.includes("Nothing to do. Demo is ready."));
  assert(ps.includes("Nothing to do. Demo is ready.") && ps.includes("$ErrorActionPreference = 'Stop'"));
  assert(sh.includes("if have git") || sh.includes("if have git; then"), "git is checked before it is installed");
  assert(/step_write\(\) \{\n  if \( cd "\$ROOT" && 'bun' 'run' 'demo' 'check' \)/u.test(sh), "a converge step checks first");
  assert(sh.includes("ran but its check still fails") && ps.includes("ran but its check still fails"), "the check must hold afterwards");
  assert(sh.includes("main \"$@\"; exit"), "the script is read whole before it runs");
});

proves(["0007-workbench-operate FR-005"], "tools come by the package manager or by a pinned download whose SHA-256 is checked, and never from a program fetched and run", () => {
  const sh = operateSh(ok(SPEC), DIGEST);
  assert(sh.includes(`BUN_SHA='${SHA_X64}'`) && sh.includes(`BUN_SHA='${SHA_ARM}'`));
  assert(sh.includes('"$got" != "$BUN_SHA"') && sh.includes("nothing was installed"));
  assert(sh.indexOf("sha256_of < \"$tmp/bun.zip\"") < sh.indexOf("unzip -q"), "the digest is checked before the archive is opened");
  assert(!/\|\s*(ba)?sh\b/u.test(sh.replaceAll("| sha256_of", "")), "no download is piped to a shell");
  assert(operatePs1(ok(SPEC), DIGEST).includes("winget install --id") && !operatePs1(ok(SPEC), DIGEST).includes("Invoke-Expression"));
  assert(sh.includes('version_ge "$have_version" \'1.4.0\''), "a bun at the minimum is left as it is");
});

proves(["0007-workbench-operate FR-006"], "the sign-in is the device flow with read:packages, run at the terminal, and an environment token needs none", () => {
  const sh = operateSh(ok(SPEC), DIGEST);
  const ps = operatePs1(ok(SPEC), DIGEST);
  assert(sh.includes("gh auth login --hostname github.com --git-protocol https --web --scopes read:packages") && sh.includes("tty_run()"));
  assert(sh.includes("GH_TOKEN:-") && ps.includes("$env:GH_TOKEN"));
  assert(ps.includes("gh auth login --hostname github.com --git-protocol https --web --scopes read:packages"));
  assert(sh.includes("gh auth refresh --hostname github.com --scopes read:packages"), "a sign-in without the scope is extended, not repeated");
});

proves(["0007-workbench-operate FR-007"], "the token is read from gh into the named variable for the programs the script runs, never printed, written or put in an argument", () => {
  const sh = operateSh(ok(SPEC), DIGEST);
  const ps = operatePs1(ok(SPEC), DIGEST);
  assert(sh.includes('DEMO_TOKEN="$(gh auth token --hostname github.com)"') && sh.includes("export DEMO_TOKEN"));
  assert(ps.includes("gh auth token --hostname github.com") && ps.includes("SetEnvironmentVariable('DEMO_TOKEN'"));
  for (const script of [sh, ps]) {
    assert(!/echo[^\n]*DEMO_TOKEN|printf[^\n]*DEMO_TOKEN|Write-[A-Za-z]+[^\n]*DEMO_TOKEN/u.test(script), "it is never printed");
    assert(!/>\s*[^\n]*\n[^\n]*DEMO_TOKEN/u.test(script) && !/--token|-t "\$/u.test(script), "it is in no argument");
  }
});

proves(["0007-workbench-operate FR-008"], "update fast-forwards only a clean clone with a branch and install runs only where the digest of the manifest and lockfile changed, keeping digests only", () => {
  const sh = operateSh(ok(SPEC), DIGEST);
  const ps = operatePs1(ok(SPEC), DIGEST);
  assert(sh.includes("pull --ff-only") && sh.includes("not committed: left as it is") && sh.includes("follows no branch"));
  assert(ps.includes("pull --ff-only") && ps.includes("not committed: left as it is"));
  assert(sh.includes("STAMP=\"$ROOT/.demo/operate.stamp\"") && sh.includes("--frozen-lockfile") && sh.includes("nothing changed since the last run"));
  assert(ps.includes(".demo/operate.stamp") && ps.includes("--frozen-lockfile"));
});

proves(["0007-workbench-operate FR-009"], "a converge step is two argument vectors run without a shell, and run only where check fails", () => {
  const sh = operateSh(ok(SPEC), DIGEST);
  assert(sh.includes("'bun' 'run' 'demo' 'write'") && sh.includes("'bun' 'run' 'demo' 'check'"));
  assert(operatePs1(ok(SPEC), DIGEST).includes("-Check @('bun', 'run', 'demo', 'check') -Run @('bun', 'run', 'demo', 'write')"));
  assertEquals(defineOperate({ ...SPEC, converge: [{ id: "x", say: "s", check: ["a"], run: ["b c"] }] }).kind, "err");
});

proves(["0007-workbench-operate FR-010"], "the bootstrap is generic: it takes a repository, installs git and gh, signs in, clones and runs the repository's own script, and names no product", () => {
  const sh = bootstrapSh();
  const ps = bootstrapPs1();
  assert(sh.includes("OWNER/NAME") && sh.includes('gh repo clone "$repo" "$dir"') && sh.includes('exec bash "$dir/bin/operate.sh"'));
  assert(ps.includes("[Parameter(Mandatory = $true)][string]$Repo") && ps.includes("gh repo clone $Repo $folder") && ps.includes("bin/operate.ps1"));
  for (const word of ["opsfolio", "Opsfolio", "erga", "intellectual-frontiers"]) assert(!sh.includes(word) && !ps.includes(word), `the bootstrap does not name ${word}`);
  assertEquals(stepsOf(sh), []);
});

proves(["0007-workbench-operate FR-002", "0007-workbench-operate FR-011"], "the script for Bash is valid Bash and the public bootstrap files are what the renderers write", () => {
  const spec = ok(SPEC);
  if (process.platform !== "win32") {
    for (const script of [operateSh(spec, DIGEST), bootstrapSh()]) {
      const r = spawnSync("bash", ["-n"], { input: script, encoding: "utf8" });
      assertEquals(r.status, 0, r.stderr);
    }
  }
  if (process.platform !== "win32" && spawnSync("shellcheck", ["--version"]).status === 0) {
    for (const script of [operateSh(spec, DIGEST), bootstrapSh()]) {
      const r = spawnSync("shellcheck", ["--shell=bash", "-"], { input: script, encoding: "utf8" });
      assertEquals(r.status, 0, r.stdout);
    }
  }
  const root = fileURLToPath(new URL("../../../", import.meta.url));
  assertEquals(readFileSync(`${root}bin/bootstrap.sh`, "utf8"), bootstrapSh());
  assertEquals(readFileSync(`${root}bin/bootstrap.ps1`, "utf8"), bootstrapPs1());
});
