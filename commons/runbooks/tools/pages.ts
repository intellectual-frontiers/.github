/**
 * The generated pages of the commons for the runbooks: the catalog of errors, the starter drill with everything made from it (its skill, checklist, implementation statement, rules and scenario) and the dialects with what each
 * writes. `bun commons/runbooks/tools/pages.ts` writes them, `--check` writes nothing and says which differ. They are made from the code, so a page cannot say what the code does not.
 *
 * @module
 */
import { CATALOG, DIALECTS, PROBLEM_CONCEPTS, RESTORE_DRILL, type CatalogEntry } from "../src/governance/mod.ts";
import { checklist, DIALECT_IMPLS, projectAll, rulesOf, scenario, skillMd, statements } from "../src/logical/mod.ts";
import { fs, path, proc } from "@intellectual-frontiers/system";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..", "..", "..");
const GUIDES = "commons/docs/guides";
const NOTE = "Generated by `commons/runbooks/tools/pages.ts` from the code of the library `runbooks`; do not edit it.";

const row = (e: CatalogEntry): string => `| \`${e.code}\` | ${e.title} | ${e.fixer} | ${e.what} | ${e.fix} |`;
const fence = (lang: string, text: string): string[] => ["```" + lang, text.trimEnd(), "```", ""];

function errors(): string {
  const parts = PROBLEM_CONCEPTS.map((c) => {
    const entries = Object.values(CATALOG).filter((e) => e.concept === c);
    return entries.length === 0 ? "" : `## ${c[0]?.toUpperCase()}${c.slice(1)}\n\n| Code | What happened | Who fixes it | What it says | The fix |\n|---|---|---|---|---|\n${entries.map(row).join("\n")}\n`;
  });
  return [
    "# Errors of the runbooks, and what to do",
    "",
    NOTE,
    "",
    "Every problem the static check of a runbook finds has one code, `E-RB-<CONCEPT>-<KIND>`, with one fix and one fixer. Every finding is an error: a runbook with a finding is not planned and not run. **Who fixes it:** `agent` means the author of the runbook can run the fix; `person` means a person must decide (an authority, the choice of a dialect); `environment` means the owner of the pinned packages; `ci` means a rebuild.",
    "",
    "**A failure that is in none of these** is `E-RB-UNKNOWN`: classify it by adding an entry, a check and a test, and documenting it, in one change.",
    "",
    ...parts,
  ].join("\n");
}

function drill(): string {
  const rules = rulesOf([RESTORE_DRILL]);
  const files = projectAll([RESTORE_DRILL])["claude-code"] ?? [];
  const settings = files.find((f) => f.path === ".claude/runbooks.settings.json")?.text ?? "";
  return [
    "# The restore drill, and what is made from it",
    "",
    NOTE,
    "",
    `\`${RESTORE_DRILL.id}\` is the starter runbook: ${RESTORE_DRILL.summary} An agent or a person orchestrates; every effect is a deterministic verb of the pinned packages, a \`judge\` step only proposes, and what a person must do is a \`gate\`. Everything below is made from the one typed runbook, with synthetic names.`,
    "",
    "## The skill (Claude Code)",
    "",
    ...fence("markdown", skillMd(RESTORE_DRILL)),
    "## The checklist (a person)",
    "",
    ...fence("markdown", checklist(RESTORE_DRILL)),
    "## The implementation statements (an auditor)",
    "",
    ...fence("markdown", statements([RESTORE_DRILL])),
    "## The rules derived from the effects",
    "",
    `Allowed: ${rules.allow.length}. Asked: ${rules.ask.length}. Denied: ${rules.deny.length}.`,
    "",
    ...fence("json", settings),
    "## The scenario",
    "",
    ...fence("gherkin", scenario(RESTORE_DRILL)),
  ].join("\n");
}

function harness(): string {
  return [
    "# Harnesses and dialects",
    "",
    NOTE,
    "",
    "A runbook never names a harness. A harness is a dialect, and the set of dialects is open: a harness added later is one entry registered with a renderer, with no change to any runbook. A fleet owns a `HarnessPolicy` (a default, a choice by skill, a preference by operator, a choice by workload); a run resolves its dialect as the explicit choice, then the operator's preference, then the skill's, then the workload's, then the fleet's default, and a dialect that cannot carry the runbook is refused with `E-RB-HARNESS-UNSUITABLE`.",
    "",
    "| Dialect | Held by | Reads a skill file | What it writes for the starter drill |",
    "|---|---|---|---|",
    ...DIALECTS.list().map((d) => `| \`${d.id}\` | ${d.holder} | ${d.skillFiles ? "yes" : "no"} | ${(DIALECT_IMPLS.find((i) => i.info.id === d.id)?.render([RESTORE_DRILL]) ?? []).map((f) => `\`${f.path}\``).join(", ")} |`),
    "",
    "Switching the dialect changes only these files. The steps, the effects and the autonomy derived for each step are the same for every dialect.",
    "",
    "The format of each harness is the one its own documentation gives; where a format could not be verified, the dialect writes the conservative one and says so in the specification (0004-runbooks-projections FR-007).",
    "",
  ].join("\n");
}

/** Every file this writes, with its text. */
export function outputs(): Readonly<Record<string, string>> {
  return {
    [`${GUIDES}/runbooks-errors.auto.md`]: errors(),
    [`${GUIDES}/runbooks-restore-drill.auto.md`]: drill(),
    [`${GUIDES}/runbooks-harness.auto.md`]: harness(),
  };
}

if (import.meta.main) {
  const check = proc.args.includes("--check");
  const stale: string[] = [];
  for (const [file, text] of Object.entries(outputs())) {
    const full = path.join(ROOT, file);
    const have = (await fs.exists(full)) ? await fs.readTextFile(full) : undefined;
    if (have === text) continue;
    stale.push(file);
    if (!check) await fs.writeTextFile(full, text);
  }
  if (check && stale.length > 0) {
    console.error(`stale: ${stale.join(", ")}: run bun commons/runbooks/tools/pages.ts`);
    proc.exit(1);
  }
  console.log(check ? "the pages are current" : `wrote ${stale.length} files`);
}
