/**
 * An HTML view of an ontology for people who read it in a browser and not in TypeScript (commons 0019-mizan-integrations FR-010, 0012-ontology): its classes, properties and code lists
 * with their definitions, and the basis of each term, so that the ontology can be read outside TypeScript without a tool. One self-contained page, written deterministically from the
 * data it is given, with its CSS embedded, readable in a light and a dark scheme and at a phone's width.
 *
 * @remarks
 * Every text is escaped. The page says it is generated and from what, and carries the ontology's IRI and version IRI where it has them.
 *
 * @example
 * ```ts
 * import { exportHtmlView } from "./export-html.ts";
 * exportHtmlView({ title: "Mizan", iri: "https://x/o", classes: [], properties: [], codeLists: [], terms: [] }, "generated by a tool").startsWith("<!doctype html>"); // true
 * ```
 *
 * @module
 */

/** What the page shows of a class or a property. */
export type ViewTerm = {
  readonly curie: string;
  readonly label: string;
  readonly definition?: string;
  readonly domain?: string;
  readonly range?: string;
};
/** What the page shows of a code list: its name and its members. */
export type ViewCodeList = {
  readonly name: string;
  readonly members: readonly { readonly code: string; readonly label: string; readonly definition?: string }[];
};
/** What the page shows of the basis of a term. */
export type ViewBasis = {
  readonly curie: string;
  readonly basis: string;
  readonly standardTerm?: string;
  readonly relation?: string;
  readonly justification?: string;
};

/** Everything the page is made from. */
export type OntologyView = {
  readonly title: string;
  readonly iri: string;
  readonly versionIri?: string;
  readonly classes: readonly ViewTerm[];
  readonly properties: readonly ViewTerm[];
  readonly codeLists: readonly ViewCodeList[];
  readonly terms: readonly ViewBasis[];
};

function esc(s: string): string {
  return s.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");
}

const CSS = `:root{--bg:#fbfaf7;--ink:#1d2230;--soft:#4a5368;--line:#e1ddd0;--card:#fff;--acc:#1f4f8f;--ok:#1e7a4f;--warn:#b07a1a}
@media(prefers-color-scheme:dark){:root{--bg:#0f1320;--ink:#e8ebf5;--soft:#a7b0c8;--line:#2a3150;--card:#181e32;--acc:#7fb0f0;--ok:#5fd09b;--warn:#e0b157}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--ink);font:16px/1.6 system-ui,sans-serif;padding:24px 16px;overflow-wrap:anywhere}
main{max-width:1000px;margin:0 auto}h1{font-family:Georgia,serif;margin:.2em 0}h2{margin-top:2em;border-bottom:1px solid var(--line);padding-bottom:.2em}
.meta{color:var(--soft);font-size:.9rem;word-break:break-all}.note{color:var(--soft);font-size:.85rem}
.scroll{overflow-x:auto}table{border-collapse:collapse;width:100%;background:var(--card);border:1px solid var(--line);margin:1em 0;min-width:560px}
th,td{text-align:left;padding:8px 12px;border-bottom:1px solid var(--line);vertical-align:top}th{font-size:.78rem;text-transform:uppercase;letter-spacing:.06em;color:var(--soft)}
code{font-family:ui-monospace,Menlo,monospace;font-size:.88em}.chip{display:inline-block;padding:1px 9px;border-radius:999px;border:1px solid var(--line);font-size:.8rem}
.adopts,.specializes,.maps{color:var(--ok)}.unaligned{color:var(--warn)}`;

function termRows(ts: readonly ViewTerm[], withTypes: boolean): string {
  return ts
    .map(
      (t) =>
        `<tr id="${esc(t.curie)}"><td><code>${esc(t.curie)}</code></td><td>${esc(t.label)}</td>${withTypes ? `<td>${t.domain === undefined ? "" : `<code>${esc(t.domain)}</code>`}</td><td>${t.range === undefined ? "" : `<code>${esc(t.range)}</code>`}</td>` : ""}<td>${esc(t.definition ?? "")}</td></tr>`,
    )
    .join("\n");
}

/** The ontology as one HTML page; `generated` says what generated it, as the page's own note. */
export function exportHtmlView(v: OntologyView, generated: string): string {
  const lists = v.codeLists
    .map(
      (l) =>
        `<h3 id="list-${esc(l.name)}">${esc(l.name)}</h3><div class="scroll"><table><tr><th>Code</th><th>Label</th><th>Definition</th></tr>\n${l.members.map((m) => `<tr><td><code>${esc(m.code)}</code></td><td>${esc(m.label)}</td><td>${esc(m.definition ?? "")}</td></tr>`).join("\n")}</table></div>`,
    )
    .join("\n");
  const basis = v.terms
    .map(
      (t) =>
        `<tr><td><code>${esc(t.curie)}</code></td><td><span class="chip ${esc(t.basis)}">${esc(t.basis)}</span></td><td>${t.standardTerm === undefined ? "" : `${esc(t.relation ?? "")} <code>${esc(t.standardTerm)}</code>`}</td><td>${esc(t.justification ?? "")}</td></tr>`,
    )
    .join("\n");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${esc(v.title)}</title><style>${CSS}</style></head>
<body><main>
<p class="note">${esc(generated)}</p>
<h1>${esc(v.title)}</h1>
<p class="meta">Ontology <code>${esc(v.iri)}</code>${v.versionIri === undefined ? "" : `<br>Version <code>${esc(v.versionIri)}</code>`}</p>
<h2>Classes</h2><div class="scroll"><table><tr><th>Term</th><th>Label</th><th>Definition</th></tr>
${termRows(v.classes, false)}</table></div>
<h2>Properties</h2><div class="scroll"><table><tr><th>Term</th><th>Label</th><th>Domain</th><th>Range</th><th>Definition</th></tr>
${termRows(v.properties, true)}</table></div>
<h2>Code lists</h2>
${lists}
<h2>Basis of each term</h2><p class="note">How a term relates to a standard: <code>adopts</code>, <code>specializes</code>, <code>maps</code> or <code>unaligned</code> (no standard names it: a justification and a decision are due).</p>
<div class="scroll"><table><tr><th>Term</th><th>Basis</th><th>Standard's term</th><th>Justification</th></tr>
${basis}</table></div>
</main></body></html>
`;
}
