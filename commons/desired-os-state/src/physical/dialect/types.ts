// Spec: 0004-desired-os-state-dialects FR-001, FR-002, FR-006
/**
 * The port of a dialect: the whole of what Desired OS State knows of a tool. A dialect says what it can guarantee, as data, renders an order and a plan to files, and gives the steps its tool needs to
 * carry the plan out. What it renders is generated, and the digest of what it rendered does not depend on the order the files were made in.
 *
 * @example
 * ```ts
 * import { GENERATED_MARK, isGenerated, renderHeader } from "./types.ts";
 * isGenerated(`${renderHeader("yaml")}\n- hosts: all`); // true
 * ```
 *
 * @module
 */
import { argvFindings, err, ok, type ArgvStep, type Result } from "@intellectual-frontiers/core";
import { sha256, type Sha256 } from "@intellectual-frontiers/crypto/sha256";
import { canonicalJson, type DialectId, type RequirementId, type ResourceKindId, type SubjectClass } from "@intellectual-frontiers/desired-os-state/governance";
import type { Order } from "@intellectual-frontiers/desired-os-state/logical";
import type { Plan } from "@intellectual-frontiers/desired-os-state/logical";

/** How faithful the plan of a tool is: `faithful` shows what would change, `partial` shows some of it and `none` shows nothing (the tool has no check mode). */
export type PlanGuarantee = "faithful" | "partial" | "none";

/** What a dialect says it can do, as data. */
export type Guarantees = {
  /** The kinds of resource it can carry out. */
  readonly kinds: readonly ResourceKindId[];
  /** The classes of subject it can reach. */
  readonly subjects: readonly SubjectClass[];
  readonly plan: PlanGuarantee;
  /** Whether applying twice changes nothing the second time has been shown by its conformance suite. */
  readonly idempotence: "proven" | "unproven";
  readonly destroy: boolean;
};

/** What a dialect rendered: files by path, and the digest of all of them. */
export type Rendered = { readonly files: ReadonlyMap<string, string>; readonly digest: Sha256 };

/** One step the tool needs, for the executor of headless. */
export type DialectStep = {
  /** The requirements it carries out. */
  readonly covers: readonly RequirementId[];
  readonly summary: string;
  /** The argument vector that does it: it names the digest of what was rendered. */
  readonly apply: readonly string[];
  /** The argument vector that looks and changes nothing; none where the tool has no check mode. */
  readonly check: readonly string[] | undefined;
  /** The exit status of the check that means something would change. */
  readonly changedExit?: number;
  /** Who runs it: `root` where the tool needs the administrator; `user` where it says nothing. */
  readonly as?: "user" | "root";
};

/** The step as two `ArgvStep`s of core, the apply and the check: words only, the identity it runs as and the exit codes that are a success (a check also succeeds with the exit code that says it would change). */
export function argvStepsOf(step: DialectStep): { readonly apply: ArgvStep; readonly check?: ArgvStep } {
  const as = step.as ?? "user";
  const apply: ArgvStep = { argv: step.apply, as, expect: [0] };
  if (step.check === undefined) return { apply };
  return { apply, check: { argv: step.check, as, expect: step.changedExit === undefined ? [0] : [0, step.changedExit] } };
}

/** Every reason a step of a dialect is not safe to run: a shell string, an empty vector, a bad exit code. */
export function stepFindings(step: DialectStep): readonly string[] {
  const { apply, check } = argvStepsOf(step);
  return [...argvFindings(apply), ...(check === undefined ? [] : argvFindings(check))];
}

/** A dialect. */
export type Dialect = {
  readonly id: DialectId;
  /** The tool, and the version the dialect pins. */
  readonly tool: { readonly name: string; readonly version: string };
  readonly guarantees: Guarantees;
  /** Renders an order and its plan to files, or says why it cannot. */
  readonly render: (order: Order, plan: Plan) => Promise<Result<Rendered, readonly string[]>>;
  /** The steps the tool needs to carry the plan out. */
  readonly steps: (plan: Plan, rendered: Rendered) => readonly DialectStep[];
};

/** The sentence every generated file carries. */
export const GENERATED_MARK = "GENERATED by desired-os-state; do not edit";

/** The kinds of file a dialect renders. */
export type FileKind = "yaml" | "shell" | "hcl" | "text" | "json";

/** The line that says a file is generated, for a kind of file: a comment where the kind has comments, and a member `_generated` for JSON. */
export function renderHeader(kind: FileKind): string {
  return kind === "json" ? `"_generated": ${JSON.stringify(GENERATED_MARK)}` : `# ${GENERATED_MARK}`;
}

/** Whether a file says it is generated: the mark is in its first lines. */
export function isGenerated(text: string): boolean {
  return text.slice(0, 400).includes(GENERATED_MARK);
}

/** What a set of files is, with the digest of them in the order of their paths. */
export async function renderedOf(files: ReadonlyMap<string, string>): Promise<Result<Rendered, readonly string[]>> {
  const problems: string[] = [];
  for (const [path, text] of files) {
    if (path === "" || path.startsWith("/") || path.split("/").includes("..")) problems.push(`${JSON.stringify(path)} is not a path inside the folder of the render`);
    if (!isGenerated(text)) problems.push(`${path} does not say it is generated`);
  }
  if (problems.length > 0) return err(problems);
  const sorted = [...files.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return ok({ files, digest: await sha256(canonicalJson(sorted)) });
}
