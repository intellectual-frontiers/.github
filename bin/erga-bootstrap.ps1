$DENO_VERSION = '2.9.8'
$DENO_SHA256_AARCH64 = 'd49596c20b9788cf8f5d8ddf644103d4bde56ed239753f0bdb92ba9361d51905'
$DENO_SHA256_MACOS_ARM64 = '9f0bf660393da2eaff044cdc7444cb08c73f235849b61d224d825a194ce7c98e'
$DENO_SHA256_MACOS_X64 = '4b2f5edd2639b7470f034238b321d7002d8dfb4726d8558f52c17afac370eb2c'
$DENO_SHA256_WINDOWS_X64 = 'cba84b26e0df5ae7f74fc66b86a95b866872a86292ebd84fa1e959927edd93bf'
$DENO_SHA256_X86_64 = 'e890975bc2549807bbcc0b584ffafda72cc7c93349dd99c80483dd784f6c4609'
# <<< pins.auto <<<

# throw, not exit: run with `irm | iex` an exit would close the person's window before they can read the message
function Stop-Here([string] $Text) { Write-Host "erga-bootstrap: $Text" -ForegroundColor Yellow; throw 'erga-bootstrap: stopped (see above)' }

$Base = ($(if ($env:BOOTSTRAP_URL) { $env:BOOTSTRAP_URL } else { 'https://raw.githubusercontent.com/intellectual-frontiers/.github/main' })).TrimEnd('/')
if ([Environment]::OSVersion.Platform -ne 'Win32NT') { Stop-Here 'this script is for Windows; on Linux or a Mac run erga-bootstrap.sh.' }
if (-not [Environment]::Is64BitOperatingSystem -or $env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { Stop-Here 'there is a Deno for Windows on x86-64 only.' }
$Url = "https://github.com/denoland/deno/releases/download/v$DENO_VERSION/deno-x86_64-pc-windows-msvc.zip"
$Sum = $DENO_SHA256_WINDOWS_X64
if ($env:BOOTSTRAP_DENO_URL) { $Url = $env:BOOTSTRAP_DENO_URL; $Sum = $env:BOOTSTRAP_DENO_SHA256 }

$DataHome = if ($env:LOCALAPPDATA) { $env:LOCALAPPDATA } else { Join-Path $HOME 'AppData\Local' }
$Final = Join-Path $DataHome "erga\toolchain\deno\$DENO_VERSION\windows-x64"
$Deno = Join-Path $Final 'deno.exe'
if (-not (Test-Path $Deno)) {
    [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
    $Parent = Split-Path -Parent $Final
    New-Item -ItemType Directory -Force -Path $Parent | Out-Null
    $Tmp = Join-Path $Parent ".windows-x64.$([System.IO.Path]::GetRandomFileName())"
    New-Item -ItemType Directory -Path $Tmp | Out-Null
    try {
        Write-Host "erga-bootstrap: getting Deno $DENO_VERSION for windows-x64 ($Url)"
        $Zip = Join-Path $Tmp 'deno.zip'
        $Tries = if ($env:ERGA_RETRIES -match '^[1-9][0-9]*$') { [int] $env:ERGA_RETRIES } else { 8 }
        $Wait = 3
        for ($n = 1; ; $n++) {
            try { Invoke-WebRequest -Uri $Url -OutFile $Zip -UseBasicParsing; break }
            catch {
                if ($n -ge $Tries) { Stop-Here "Deno could not be fetched from $Url ($n tries): $($_.Exception.Message)" }
                Write-Host "erga-bootstrap: could not fetch Deno; trying again in ${Wait}s (attempt $($n + 1) of $Tries)"
                Start-Sleep -Seconds $Wait; $Wait = [Math]::Min($Wait * 2, 60)
            }
        }
        $Got = (Get-FileHash -Algorithm SHA256 -Path $Zip).Hash.ToLowerInvariant()
        if ($Got -ne $Sum) { Stop-Here "the file at $Url is not the Deno pinned (its SHA-256 is $Got, not $Sum); nothing was unpacked." }
        $Unpacked = Join-Path $Tmp 'unpacked'
        Expand-Archive -Path $Zip -DestinationPath $Unpacked
        if (-not (Test-Path (Join-Path $Unpacked 'deno.exe'))) { Stop-Here "the Deno zip holds no deno.exe." }
        try { Move-Item -Path $Unpacked -Destination $Final } catch { if (-not (Test-Path $Deno)) { Stop-Here "Deno could not be put in $Final." } }
    } finally { Remove-Item -Recurse -Force -Path $Tmp -ErrorAction SilentlyContinue }
}

# The setup: given, beside this file in a checkout, or fetched by Deno from where this came from (and fetched again each run).
$Setup = $env:BOOTSTRAP_SETUP; $Reload = @()
if (-not $Setup -and $PSScriptRoot -and (Test-Path (Join-Path $PSScriptRoot 'setup\main.ts'))) { $Setup = Join-Path $PSScriptRoot 'setup\main.ts' }
if (-not $Setup) { $Setup = "$Base/bin/setup/main.ts"; $Reload = @("--reload=$Base/") }
$env:BOOTSTRAP_URL = $Base; $env:ERGA_BOOTSTRAP_DENO = $Deno
& $Deno run -q --no-config --no-prompt --allow-env --allow-read --allow-write --allow-net --allow-run --allow-sys @Reload $Setup @args
$Status = $LASTEXITCODE
if ($PSCommandPath) { exit $Status }   # run as a file: the setup's exit status is this script's
if ($Status -ne 0) { throw "erga-bootstrap: the setup stopped (exit $Status); its last lines say why" }
