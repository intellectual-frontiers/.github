# erga-bootstrap.ps1: set up Windows for erga (erga's 009-machine-bootstrap). It only gets Deno: the pinned Deno for Windows, checked by SHA-256, kept in erga's
# toolchain store (%LOCALAPPDATA%\erga\toolchain\deno\<version>\windows-x64, where erga's bin\setup.ps1 keeps it), then the setup, which is TypeScript
# (bin/setup/main.ts), does the rest: WSL 2 with Debian, your Linux user, and erga's bootstrap inside it (erga itself runs in WSL, not natively on Windows yet).
# Run it from PowerShell (not as administrator; Windows asks if it needs that):
#   irm https://raw.githubusercontent.com/intellectual-frontiers/.github/main/bin/erga-bootstrap.ps1 | iex
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/intellectual-frontiers/.github/main/bin/erga-bootstrap.ps1))) --dry-run
# Settings (set before running, e.g. $env:ERGA_WSL_DISTRO = 'Ubuntu'): ERGA_WSL_DISTRO, ERGA_WSL_USER and the others the setup's --help names; BOOTSTRAP_URL (where this
# repository is served from), BOOTSTRAP_SETUP (the setup's main.ts to run instead), BOOTSTRAP_DENO_URL with BOOTSTRAP_DENO_SHA256 (another copy of the Deno zip).
# Trust: as with any `irm | iex`, you trust this repository's main branch; Deno is checked against the SHA-256 pinned below before it is unpacked.

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'   # Windows PowerShell draws a progress bar so slowly that it slows the download itself

# >>> pins.auto >>>
