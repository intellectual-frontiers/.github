proves(["0002-packaging FR-002"], "Generated: every manager and every os row of upt is here", () => {
  const t = table();
  const managers = doc(t.managers);
  const prohibitions = list(t.prohibitions).map((p) => doc(p));
  for (const r of rows("tools.tsv")) {
    if (r.tool === "upt") continue;
    const tool = r.tool ?? "";
    const mid = MANAGER_OF_TOOL[tool] ?? tool;
    assert(mid in managers, `upt's manager ${tool} is missing`);
    const commands = doc(doc(managers[mid]).commands ?? {});
    for (const [col, op] of Object.entries(OP_OF_COLUMN)) {
      const cell = r[col] ?? "";
      if (cell.trim() === "-") continue;
      const template = cell.replaceAll("$pkg", "{packages}").replace(/(-\S+)\/(--\S+)/g, "$2");
      if (prohibitions.some((p) => p.manager === mid && JSON.stringify(p.argv) === JSON.stringify(split(template)))) {
        assert(!(op in commands), `${mid} ${op} is forbidden and must not be a usable command`);
        continue;
      }
      assert(op in commands, `upt's ${tool} ${op} is missing`);
      assertEquals(texts(doc(commands[op]).argv), split(template), `${mid} ${op}`);
    }
  }
  assert("port" in managers, "upt names MacPorts for macOS");
  const families = entries(t.families);
  for (const r of rows("os.tsv")) {
    const ids = (r.os_ids ?? "").split(/\s+/).filter((i) => i !== "" && i !== "oubes");
    const family = families.find(([, v]) => texts(v.detect).length > 0 && ids.every((i) => texts(v.detect).includes(i)));
    assert(family !== undefined, `upt's row ${r.family} is missing`);
    for (const tool of (r.tools ?? "").split(","))
      assert(texts(family[1].managers).includes(MANAGER_OF_TOOL[tool] ?? tool), `${tool} for ${r.family}`);
  }
});

