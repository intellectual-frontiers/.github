// ---- the generator, run on copies of commons ---------------------------------------------------------------------------------------------------------------------

type Ran = { readonly code: number; readonly stdout: string; readonly stderr: string };

/** What of commons the generator and the type checker need: the ontology, the tools, the generated files and the kernel the ontology is typed by. */
const COPIED = ["about.ts", "generated", "ontology", "tools", "ts/kernel"];
/** The libraries lifted out of the kernel, which it and the ontology import (a copy of each, linked by package name). */
const LIFTED = ["core", "rdf", "terminal"];

class Copy {
  readonly root: string;
  readonly tmp: string;
  private constructor(tmp: string) {
    this.tmp = tmp;
    this.root = `${tmp}/commons`;
    fs.writeTextFileSync(`${tmp}/package.json`, '{ "type": "module" }\n');
    for (const rel of COPIED)
      cpSync(`${COMMONS}/${rel}`, `${this.root}/${rel}`, { recursive: true, filter: (src) => basename(src) !== "node_modules" });
    // the kernel imports the foundation by package name (commons 0032-lifting-libraries FR-003): a link to a copy of it is where Node and the compiler look for it (Node does not strip the types of a file under node_modules, and a link's real path is not)
    fs.mkdirSync(`${tmp}/node_modules/@intellectual-frontiers`, { recursive: true });
    for (const lib of LIFTED) {
      cpSync(`${COMMONS}/${lib}`, `${this.root}/${lib}`, {
        recursive: true,
        filter: (src) => basename(src) !== "node_modules" && basename(src) !== "dist",
      });
      fs.symlinkSync(`${this.root}/${lib}`, `${tmp}/node_modules/@intellectual-frontiers/${lib}`, { type: "dir" });
    }
  }
  static make(): Copy {
    return new Copy(fs.makeTempDirSync({ prefix: "commons-generator-" }));
  }
  [Symbol.dispose](): void {
    fs.removeSync(this.tmp, { recursive: true });
  }
  file(rel: string): string {
    return `${this.root}/${rel}`;
  }
  /** Replaces the first `old` in the ontology's module `name`. */
  edit(name: string, old: string | RegExp, now: string): void {
    const f = this.file(`${ONTOLOGY}/${name}`);
    const t = fs.readTextFileSync(f);
    const changed = t.replace(old, () => now);
    assertNotEquals(changed, t, `${name}: ${old}`);
    fs.writeTextFileSync(f, changed);
  }
  /** The copy's own generator, as a person runs it: a program on the runtime this test runs on, with nothing configured. */
  async run(...args: string[]): Promise<Ran> {
    const o = await proc.run([proc.execPath(), this.file("tools/generate-packaging.ts"), ...args]);
    return { code: o.code, stdout: o.stdout, stderr: o.stderr };
  }
  /** TypeScript 7's type checker (the one commons/ts installs) on the copy's generator, and so on the ontology it imports, with the strictness of commons/ts/tsconfig.json. */
  async check(): Promise<Ran> {
    const tsc = path.join(COMMONS, "ts", "node_modules", ".bin", "tsc");
    const o = await proc.run([
      tsc,
      "--ignoreConfig",
      "--noEmit",
      "--pretty",
      "false",
      "--strict",
      "--target",
      "es2024",
      "--module",
      "nodenext",
      "--allowImportingTsExtensions",
      "--erasableSyntaxOnly",
      "--verbatimModuleSyntax",
      "--types",
      "node",
      "--typeRoots",
      path.join(COMMONS, "ts", "node_modules", "@types"),
      "--noUncheckedIndexedAccess",
      "--exactOptionalPropertyTypes",
      "--noPropertyAccessFromIndexSignature",
      this.file("tools/generate-packaging.ts"),
    ]);
    return { code: o.code, stdout: o.stdout, stderr: o.stderr };
  }
  generated(): Map<string, string> {
    return new Map(fs.readDirSync(this.file("generated")).map((e) => [e.name, fs.readTextFileSync(this.file(`generated/${e.name}`))]));
  }
}

/** The copy, broken by `edits`, is refused (exit 2), every `said` is named, and nothing is written. */
async function refused(edits: (c: Copy) => void, ...said: string[]): Promise<void> {
  using c = Copy.make();
  const before = c.generated();
  edits(c);
  const p = await c.run();
  assertEquals(p.code, 2, p.stdout + p.stderr);
  assertStringIncludes(p.stderr, "the packaging ontology breaks its own rules:\n");
  for (const s of said) assertStringIncludes(p.stderr, s);
  assertEquals(c.generated(), before, "nothing is written");
}

