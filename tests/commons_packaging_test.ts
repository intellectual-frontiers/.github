// ---- the generator, run on copies of commons ---------------------------------------------------------------------------------------------------------------------

type Ran = { readonly code: number; readonly stdout: string; readonly stderr: string };

class Copy {
  readonly root: string;
  private constructor(readonly tmp: string) {
    this.root = `${tmp}/commons`;
    copyTree(COMMONS, this.root, ["spec-kit", "__pycache__", "node_modules", "docs", "data", "dist", "test-results"]);
  }
  static make(): Copy {
    return new Copy(Deno.makeTempDirSync({ prefix: "commons-generator-" }));
  }
  [Symbol.dispose](): void {
    Deno.removeSync(this.tmp, { recursive: true });
  }
  file(rel: string): string {
    return `${this.root}/${rel}`;
  }
  /** Replaces the first `old` in the ontology's module `name`. */
  edit(name: string, old: string | RegExp, now: string): void {
    const f = this.file(`${ONTOLOGY}/${name}`);
    const t = Deno.readTextFileSync(f);
    const changed = t.replace(old, () => now);
    assertNotEquals(changed, t, `${name}: ${old}`);
    Deno.writeTextFileSync(f, changed);
  }
  /** The copy's own generator, as a person runs it: with no configuration, reading and writing files alone. */
  async run(...args: string[]): Promise<Ran> {
    const o = await new Deno.Command(Deno.execPath(), {
      args: ["run", "--no-config", "--allow-read", "--allow-write", this.file("tools/generate-packaging.ts"), ...args],
      stdout: "piped",
      stderr: "piped",
    }).output();
    const dec = new TextDecoder();
    return { code: o.code, stdout: dec.decode(o.stdout), stderr: dec.decode(o.stderr) };
  }
  /** Deno's type checker on the copy's generator, and so on the ontology it imports, as CI runs it. */
  async check(): Promise<Ran> {
    const o = await new Deno.Command(Deno.execPath(), { args: ["check", "--no-config", "--quiet", this.file("tools/generate-packaging.ts")], stdout: "piped", stderr: "piped" })
      .output();
    const dec = new TextDecoder();
    return { code: o.code, stdout: dec.decode(o.stdout), stderr: dec.decode(o.stderr) };
  }
  generated(): Map<string, string> {
    return new Map([...Deno.readDirSync(this.file("generated"))].map((e) => [e.name, Deno.readTextFileSync(this.file(`generated/${e.name}`))]));
  }
}

/** The copy, broken by `edits`, is refused (exit 2), every `said` is named, and nothing is written. */
async function refused(edits: (c: Copy) => void, ...said: string[]): Promise<void> {
  using c = Copy.make();
  const before = c.generated();
  edits(c);
  const p = await c.run();
  assertEquals(p.code, 2, p.stdout + p.stderr);
  assertStringIncludes(p.stderr, "the packaging ontology breaks its own rules:\n");
  for (const s of said) assertStringIncludes(p.stderr, s);
  assertEquals(c.generated(), before, "nothing is written");
}

