// ---- reading TOML as a consumer does: the values checked where they are used, with no cast ----------------------------------------------------------------

type Doc = Readonly<Record<string, unknown>>;
const isDoc = (x: unknown): x is Doc => typeof x === "object" && x !== null && !Array.isArray(x);
function doc(x: unknown, what = "a table"): Doc {
  assert(isDoc(x), `${what} is not a table`);
  return x;
}
function list(x: unknown, what = "a list"): readonly unknown[] {
  assert(Array.isArray(x), `${what} is not a list`);
  return x;
}
function text(x: unknown, what = "a value"): string {
  assert(typeof x === "string", `${what} is not a string`);
  return x;
}
const texts = (x: unknown, what = "a list"): string[] => list(x, what).map((v) => text(v, what));
const entries = (x: unknown, what = "a table"): [string, Doc][] => Object.entries(doc(x, what)).map(([k, v]) => [k, doc(v, `${what}.${k}`)]);
const table = (): Doc => parse(Deno.readTextFileSync(TOML_PATH));

const MANAGER_OF_TOOL: Readonly<Record<string, string>> = { "pkg": "freebsd-pkg", "pkg(termux)": "termux-pkg" };
const OP_OF_COLUMN: Readonly<Record<string, string>> = {
  install: "install",
  uninstall: "remove",
  upgrade: "upgrade",
  search: "search",
  info: "info",
  update_index: "refresh",
  upgrade_all: "upgrade-all",
  list_installed: "list-installed",
};

function rows(name: string): Record<string, string>[] {
  const [head, ...lines] = Deno.readTextFileSync(`${FIXTURES}/${name}`).split("\n").filter((l) => l !== "");
  const cols = (head ?? "").split("\t");
  return lines.map((l) => Object.fromEntries(l.split("\t").map((v, i) => [cols[i] ?? "", v])));
}
function split(t: string): string[] {
  const w = words(t);
  assert(w.ok, t);
  return w.value;
}

