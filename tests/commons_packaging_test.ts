async function call(code: string): Promise<string> {
  const o = await new Deno.Command("sh", { args: ["-c", `. "${SH_FRAGMENT}"\n${code}`], stdout: "piped", stderr: "null" }).output();
  return new TextDecoder().decode(o.stdout);
}

