/** Every file under a folder, by its path from that folder. */
function walk(dir: string, rel = ""): string[] {
  return [...Deno.readDirSync(`${dir}/${rel}`)].flatMap((e) => (e.isDirectory ? walk(dir, `${rel}${e.name}/`) : [`${rel}${e.name}`]));
}

