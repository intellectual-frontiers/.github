proves(
  ["0016-ladder FR-003", "0016-ladder FR-009"],
  "a rung relies only on rungs below it, and nothing relies on the lifecycle rung",
  () => {
    const number = new Map(rungs.map((r) => [r.iri, r.values.rungNumber]));
    for (const r of rungs) {
      for (const lower of r.values.mayRelyOn ?? []) {
        const n = number.get(lower.iri);
        assert(n !== undefined && n < r.values.rungNumber, `${r.iri} relies on ${lower.iri}`);
        assert(n !== 8 && n !== 9 && n !== 10, "no rung relies on rung 8, 9 or 10");
      }
    }
    assertEquals(
      (rungs[3].values.mayRelyOn ?? []).map((r) => number.get(r.iri)),
      [0, 1, 2],
    );
    assertEquals(
      (rungs[4].values.mayRelyOn ?? []).map((r) => number.get(r.iri)),
      [0, 1, 3],
    );
  },
);

proves(["0018-standards-first FR-003"], "every class of Mizan's vocabulary has an individual saying its basis", () => {
  const classIris = classes.map((c) => c.iri).sort();
  const termIris = terms.map((t) => t.values.termIri).sort();
  assertEquals(termIris, classIris);
  const known = new Set(Object.values(bases).map((b) => b.iri));
  for (const t of terms) assert(known.has(t.values.basis.iri), `${t.iri} has a basis`);
});

proves(
  ["0018-standards-first FR-004"],
  "an unaligned term carries a justification and its date, and a term with a standard names it",
  () => {
    for (const t of terms) {
      if (t.values.basis.iri === bases.Unaligned.iri) {
        assert((t.values.justification ?? "") !== "", `${t.iri} says why no standard names it`);
        assert((t.values.addedOn ?? "") !== "", `${t.iri} says the day it was added, from which its decision is due`);
      } else assert((t.values.standardTerm ?? "") !== "", `${t.iri} names its standard's term`);
    }
  },
);

