proves(
  ["0019-mizan-integrations FR-019"],
  "the catalog lists a distribution of every file the generator writes for the Mizan ontology, with its media type, and an exporter's refusal is a sentence",
  async () => {
    const made = await wanted();
    const catalog = made.get("generated/mizan-catalog.auto.ttl") ?? "";
    const listed = [...catalog.matchAll(/dcat:downloadURL <[^>]*\/commons\/(generated\/[^>]+)>/g)].map((m) => m[1]).sort();
    const written = [...made.keys()]
      .filter((k) => k !== "generated/mizan-audit-packaging.auto.ttl" && k !== "generated/mizan-catalog.auto.ttl")
      .sort();
    assertEquals(listed, written);
    assertStringIncludes(catalog, "dcat:mediaType <https://www.iana.org/assignments/media-types/application/rdf+xml>");
    assertEquals(textOf({ kind: "ok", value: "text" }, "X"), "text");
    const refused = assertThrows(() => textOf({ kind: "err", error: ["one", "two"] }, "X"), ExportRefused);
    assertEquals(refused.message, "the Mizan ontology cannot be written as X: one; two");
  },
);

