/**
 * Mizan's shared ontology and the generator of its Turtle (commons 0003-mizan FR-018, 0016-ladder, 0018-standards-first): the generator runs as a program on the runtime
 * this test runs on, on a copy of commons in a temporary folder; the ladder is read from the typed individuals; and every class of the vocabulary says its basis.
 * An independent RDF parser (rdflib) read the generated Turtle while this was written (423 triples, nine rungs), but is not a dependency of the suite, so no test here
 * runs it.
 *
 * @module
 */
import { cpSync } from "node:fs";
import { fs, path, proc } from "../commons/ts/runtime/mod.ts";
import { assert, assertEquals, assertStringIncludes, assertThrows, proves } from "../commons/ts/runtime/test.ts";
import { classes, rungs, terms, authorities, cfr820, bases } from "../commons/ontology/mizan/mod.ts";
import { files } from "../commons/ontology/mizan/mod.ts";
import { digestOf, ExportRefused, findingsOf, main, textOf, TURTLE_PATH, turtleOf, wanted } from "../commons/ts/mizan/generate-ontology.ts";

const ROOT = path.resolve(path.dirname(path.fromFileUrl(import.meta.url)), "..");
const TOOL = `${ROOT}/commons/ts/mizan/generate-ontology.ts`;

/** The generator as a program, from the checkout's folder. */
async function run(args: readonly string[]): Promise<{ code: number; stdout: string; stderr: string }> {
  const o = await proc.run([proc.execPath(), TOOL, ...args], { cwd: ROOT });
  return { code: o.code, stdout: o.stdout, stderr: o.stderr };
}

proves(
  ["0003-mizan FR-018"],
  "the generated Turtle is what the ontology makes, from the command line, and says it is generated",
  async () => {
    const p = await run(["--check"]);
    assertEquals([p.code, p.stdout, p.stderr], [0, "", ""]);
    const text = fs.readTextFileSync(`${ROOT}/commons/${TURTLE_PATH}`);
    assert(text.startsWith("# AUTO-GENERATED by bun commons/ts/mizan/generate-ontology.ts"));
    assertStringIncludes(text, `source_sha256=${await digestOf(files)}`);
    assertEquals(text, turtleOf(files, await digestOf(files)));
  },
);

proves(
  ["0003-mizan FR-018"],
  "an export edited by hand is named as stale, with exit 1, and writing it again makes it current",
  async () => {
    const tmp = fs.makeTempDirSync({ prefix: "commons-mizan-ontology-" });
    try {
      cpSync(`${ROOT}/commons/generated`, `${tmp}/generated`, { recursive: true });
      const file = `${tmp}/${TURTLE_PATH}`;
      fs.writeTextFileSync(file, `${fs.readTextFileSync(file)}mzid:rung-9 a mz:Rung .\n`);
      assertEquals(await main(["--check"], tmp), 1);
      assertEquals(await main([], tmp), 0);
      assertEquals(await main(["--check"], tmp), 0);
      assertEquals(fs.readTextFileSync(file), fs.readTextFileSync(`${ROOT}/commons/${TURTLE_PATH}`));
    } finally {
      fs.removeSync(tmp, { recursive: true });
    }
  },
);

