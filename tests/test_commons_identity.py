"""commons: the identity ontology and the table made from it (commons 0004-identity-and-roles).

What runs here with the standard library alone: the generated TOML is read as a consumer reads it and checked against the rules of the specification. What needs `uv` (the generator,
which reads Turtle with rdflib) is skipped where `uv` is not installed: that it makes the committed file, and that it refuses an ontology that breaks a rule."""
import re
import shutil
import subprocess
import tempfile
import tomllib
import unittest
from pathlib import Path

HOME = Path(__file__).resolve().parents[1]
COMMONS = HOME / "commons"
TOML = COMMONS / "generated" / "identity.auto.toml"
UV = shutil.which("uv")
ROLE_ID = re.compile(r"^[a-z]+(-[a-z]+)*$")
SLUG = re.compile(r"^[a-z0-9][a-z0-9:.-]*$")
DEPTHS = ["answer", "reader", "own", "connect", "team"]


def table() -> dict:
    return tomllib.loads(TOML.read_text())


class Generated(unittest.TestCase):
    """The TOML a harness reads."""

    def test_it_says_it_is_generated_and_is_the_schema_a_reader_expects(self):
        """0004-identity-and-roles FR-023"""
        text = TOML.read_text()
        self.assertTrue(text.startswith("# AUTO-GENERATED by commons/tools/generate-identity.py"))
        t = table()
        self.assertEqual(t["schema"], 1)
        self.assertRegex(t["source_sha256"], r"^[0-9a-f]{64}$")
        for key in ("roles", "permissions", "depth"):
            self.assertIn(key, t)
        self.assertIn(".auto.", TOML.name)

    def test_every_role_is_well_formed(self):
        """0004-identity-and-roles FR-004"""
        for rid, r in table()["roles"].items():
            self.assertRegex(rid, ROLE_ID)
            self.assertLessEqual(len(rid), 32, rid)
            self.assertIn(r["kind"], ("visitor", "member", "staff"), rid)
            self.assertTrue(r["label"] and r["definition"], rid)
            self.assertTrue(r["grants"], f"{rid} grants nothing")

    def test_every_permission_is_well_formed_and_granted(self):
        """0004-identity-and-roles FR-005, SC-003"""
        t = table()
        granted = {g for r in t["roles"].values() for g in r["grants"]}
        for slug, p in t["permissions"].items():
            self.assertRegex(slug, SLUG)
            self.assertLessEqual(len(slug), 40, slug)
            self.assertTrue(p["label"] and p["definition"], slug)
            self.assertIn(slug, granted, f"{slug} is granted by no role")
        for rid, r in t["roles"].items():
            for g in r["grants"]:
                self.assertIn(g, t["permissions"], f"{rid} grants an undefined {g}")

    def test_the_depth_levels_are_the_five_in_order(self):
        """0004-identity-and-roles FR-018"""
        d = table()["depth"]
        self.assertEqual(sorted(d, key=lambda n: d[n]["order"]), DEPTHS)
        self.assertEqual([d[n]["order"] for n in DEPTHS], [1, 2, 3, 4, 5])
        self.assertTrue(all(d[n]["definition"] for n in DEPTHS))

    def test_the_catalog_serves_both_a_book_imprint_and_a_think_tank(self):
        """0004-identity-and-roles FR-022"""
        roles = table()["roles"]
        for rid in ("guest", "reader", "reviewer", "author", "editor", "producer", "designer", "communications", "rights", "operations", "advisor", "director", "owner"):
            self.assertIn(rid, roles)
        for rid, r in roles.items():
            if r["kind"] != "visitor":
                self.assertTrue(r.get("publishing") and r.get("research"), f"{rid} says what neither a book imprint nor a think tank calls it")

    def test_no_role_reads_the_unreleased_work_without_its_permission(self):
        """0004-identity-and-roles FR-006: the table carries permissions to act and never a visibility of a fact"""
        for rid, r in table()["roles"].items():
            for g in r["grants"]:
                self.assertFalse(g.startswith(("audience", "visible", "see:")), f"{rid} grants {g}")

    def test_the_table_holds_no_person_company_layer_price_or_secret(self):
        """0004-identity-and-roles FR-022, SC-004"""
        text = TOML.read_text().lower()
        for needle in ("@", "http://", "https://", "$", "usd", "price", "password", "secret", "token", "api_key", "workos", "stripe", "posthog", "netspective", "shahid"):
            body = "\n".join(line for line in text.splitlines() if not line.startswith("#"))
            self.assertNotIn(needle, body, f"the table mentions {needle}")


@unittest.skipUnless(UV, "uv is not installed")
class Generator(unittest.TestCase):
    """The generator, which needs uv to read Turtle."""

    def run_generator(self, root: Path, *args: str) -> subprocess.CompletedProcess:
        return subprocess.run(["uv", "run", str(root / "tools" / "generate-identity.py"), *args], capture_output=True, text=True, cwd=root.parent)

    def test_the_committed_table_is_what_the_ontology_makes(self):
        """0004-identity-and-roles FR-023, SC-001"""
        r = self.run_generator(COMMONS, "--check")
        self.assertEqual(r.returncode, 0, r.stderr)

    def copy_with(self, old: str, new: str) -> Path:
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, True)
        root = tmp / "commons"
        shutil.copytree(COMMONS / "ontology", root / "ontology")
        shutil.copytree(COMMONS / "tools", root / "tools")
        roles = root / "ontology" / "identity" / "roles.ttl"
        text = roles.read_text()
        self.assertIn(old, text)
        roles.write_text(text.replace(old, new, 1))
        return root

    def test_a_slug_that_is_too_long_or_has_a_capital_is_refused(self):
        """0004-identity-and-roles FR-005, FR-023, SC-002"""
        for new in ('idn:slug "Work:Edit"', 'idn:slug "' + "a" * 41 + '"'):
            r = self.run_generator(self.copy_with('idn:slug "work:edit"', new))
            self.assertEqual(r.returncode, 2, new)
            self.assertIn("permission slug", r.stderr)

    def test_a_role_with_a_bad_identifier_or_no_kind_is_refused(self):
        """0004-identity-and-roles FR-004, FR-023, SC-002"""
        r = self.run_generator(self.copy_with('dcterms:identifier "guest"', 'dcterms:identifier "Guest_1"'))
        self.assertEqual(r.returncode, 2)
        self.assertIn("role identifier", r.stderr)
        r = self.run_generator(self.copy_with('rdfs:label "Guest"@en ; idn:roleKind idnid:visitor ;', 'rdfs:label "Guest"@en ;'))
        self.assertEqual(r.returncode, 2)
        self.assertIn("exactly one kind", r.stderr)

    def test_a_permission_no_role_grants_is_refused(self):
        """0004-identity-and-roles FR-005, SC-003"""
        r = self.run_generator(self.copy_with("idnid:p-answer-read, idnid:p-news-edit, idnid:p-rendition-read-published .", "idnid:p-answer-read, idnid:p-rendition-read-published ."))
        self.assertEqual(r.returncode, 2)
        self.assertIn("news:edit is granted by no role", r.stderr)

    def test_a_missing_depth_level_is_refused(self):
        """0004-identity-and-roles FR-018"""
        r = self.run_generator(self.copy_with("skos:notation \"connect\" ; idn:depthOrder 4", "skos:notation \"connected\" ; idn:depthOrder 4"))
        self.assertEqual(r.returncode, 2)
        self.assertIn("depth levels must be", r.stderr)

    def test_the_check_names_a_stale_file_and_writes_nothing(self):
        """0004-identity-and-roles FR-023"""
        root = self.copy_with('rdfs:label "Guest"@en', 'rdfs:label "Visitor"@en')
        out = root / "generated" / "identity.auto.toml"
        out.parent.mkdir(parents=True)
        out.write_text(TOML.read_text())
        before = out.read_text()
        r = self.run_generator(root, "--check")
        self.assertEqual(r.returncode, 1)
        self.assertIn("is not what the ontology makes", r.stderr)
        self.assertEqual(out.read_text(), before)


if __name__ == "__main__":
    unittest.main()
