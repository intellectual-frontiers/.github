"""commons: the packaging ontology and the tables made from it (commons 0001-software-supply-chain, 0002-packaging).

What runs here with the standard library alone: the generated TOML and shell fragment are read as a consumer reads them, checked against the tables of `upt` they were seeded from,
against the rules of 0002-packaging, and the commons specifications are checked for shape and for a row in the register for every requirement. What needs `uv` (the generator, which reads
Turtle with rdflib) is skipped where `uv` is not installed: that it makes the committed files, and that it refuses an ontology that breaks a rule."""
import csv
import re
import shlex
import shutil
import subprocess
import tempfile
import tomllib
import unittest
from pathlib import Path

HOME = Path(__file__).resolve().parents[1]
COMMONS = HOME / "commons"
TOML = COMMONS / "generated" / "packaging.auto.toml"
SH_FRAGMENT = COMMONS / "generated" / "packaging.auto.sh"
FIXTURES = HOME / "tests" / "fixtures" / "upt"
SPECS = COMMONS / "spec-kit" / "specs"
UV = shutil.which("uv")
SH = shutil.which("sh")

MANAGER_OF_TOOL = {"pkg": "freebsd-pkg", "pkg(termux)": "termux-pkg"}
OP_OF_COLUMN = {"install": "install", "uninstall": "remove", "upgrade": "upgrade", "search": "search", "info": "info", "update_index": "refresh", "upgrade_all": "upgrade-all", "list_installed": "list-installed"}


def table() -> dict:
    return tomllib.loads(TOML.read_text())


def rows(name: str) -> list[dict]:
    with open(FIXTURES / name) as f:
        return list(csv.DictReader(f, delimiter="\t"))


class Generated(unittest.TestCase):
    """The TOML a harness reads."""

    def test_it_says_it_is_generated_and_is_the_schema_a_reader_expects(self):
        """0002-packaging FR-011, 0001-software-supply-chain FR-002"""
        text = TOML.read_text()
        self.assertTrue(text.startswith("# AUTO-GENERATED by commons/tools/generate-packaging.py"))
        t = table()
        self.assertEqual(t["schema"], 1)
        self.assertRegex(t["source_sha256"], r"^[0-9a-f]{64}$")
        for key in ("families", "managers", "programs", "prohibitions"):
            self.assertIn(key, t)
        self.assertIn(".auto.", TOML.name)
        self.assertIn(".auto.", SH_FRAGMENT.name)

    def test_every_manager_and_every_os_row_of_upt_is_here(self):
        """0002-packaging FR-002: a future harness is not limited to the families archon runs on"""
        t = table()
        for r in rows("tools.tsv"):
            if r["tool"] == "upt":
                continue
            mid = MANAGER_OF_TOOL.get(r["tool"], r["tool"])
            self.assertIn(mid, t["managers"], f"upt's manager {r['tool']} is missing")
            forbidden = {tuple(shlex.split(p["argv"][0])) for p in t["prohibitions"] if p["manager"] == mid}
            for col, op in OP_OF_COLUMN.items():
                if r[col].strip() == "-":
                    continue
                template = r[col].replace("$pkg", "{packages}")
                template = re.sub(r"(-\S+)/(--\S+)", r"\2", template)
                if any(shlex.split(template) == p["argv"] for p in t["prohibitions"] if p["manager"] == mid):
                    self.assertNotIn(op, t["managers"][mid]["commands"], f"{mid} {op} is forbidden and must not be a usable command")
                    continue
                self.assertIn(op, t["managers"][mid]["commands"], f"upt's {r['tool']} {op} is missing")
                self.assertEqual(t["managers"][mid]["commands"][op]["argv"], shlex.split(template), f"{mid} {op}")
        self.assertIn("port", t["managers"], "upt names MacPorts for macOS")
        for r in rows("os.tsv"):
            ids = [i for i in r["os_ids"].split() if i != "oubes"]
            family = next((f for f, v in t["families"].items() if set(ids) <= set(v["detect"]) and v["detect"]), None)
            self.assertIsNotNone(family, f"upt's row {r['family']} is missing")
            for tool in r["tools"].split(","):
                self.assertIn(MANAGER_OF_TOOL.get(tool, tool), t["families"][family]["managers"], f"{tool} for {r['family']}")

    def test_upt_is_credited_with_its_licence_and_the_id_it_leaves_out_is_said(self):
        """0002-packaging FR-003"""
        for f in (COMMONS / "ontology" / "supply-chain" / "packaging").glob("*.ttl"):
            if f.name in ("managers.ttl", "families.ttl"):
                text = f.read_text()
                self.assertIn("sigoden/upt", text, f.name)
                self.assertIn("MIT or Apache-2.0", text, f.name)
        self.assertIn("oubes", (COMMONS / "ontology" / "supply-chain" / "packaging" / "families.ttl").read_text())
        self.assertNotIn("oubes", {d for f in table()["families"].values() for d in f["detect"]})

    def test_a_supported_family_is_complete_and_says_how_far_it_has_been_tried(self):
        """0002-packaging FR-004"""
        t = table()
        supported = {k: v for k, v in t["families"].items() if v["status"] == "supported"}
        self.assertEqual(sorted(supported), ["arch", "debian", "macos"])
        self.assertEqual((supported["debian"]["assurance"], supported["arch"]["assurance"], supported["macos"]["assurance"]), ("verified", "stand-in", "untested"))
        self.assertTrue(supported["debian"]["verified_on"])
        for fid, f in supported.items():
            self.assertTrue(f["removal_hint"], fid)
            if not f["installs_packages"]:
                self.assertEqual(fid, "macos")
                continue
            m = t["managers"][f["preferred"]]
            inst = m["commands"]["install"]
            self.assertIn("noninteractive", inst, fid)
            self.assertEqual(inst["origin"], "archon", f"{fid}: a harness must have run it")
            self.assertIn("query-installed", m["commands"], fid)
            self.assertTrue(f["admin_install"], fid)
        for fid, f in t["families"].items():
            if f["status"] == "catalogued":
                self.assertEqual(f["assurance"], "none", fid)
        verified = [f for f in t["families"].values() if f["assurance"] == "verified"]
        self.assertTrue(all(f["verified_on"] for f in verified), "verified says where and when")

    def test_what_must_never_be_run_is_a_prohibition_with_a_reason_and_nothing_usable_is_it(self):
        """0002-packaging FR-005"""
        t = table()
        pro = {(p["manager"], " ".join(p["argv"])): p for p in t["prohibitions"]}
        self.assertIn(("pacman", "pacman -Sy"), pro)
        self.assertIn("partly upgraded", pro[("pacman", "pacman -Sy")]["reason"])
        self.assertTrue(any(m == "yay" for m, _ in pro), "an AUR helper is never driven")
        self.assertEqual(t["managers"]["yay"]["harness_use"], "never")
        for p in t["prohibitions"]:
            self.assertTrue(p["reason"])
            for op, c in t["managers"][p["manager"]].get("commands", {}).items():
                self.assertNotEqual(c["argv"], p["argv"], f"{p['manager']} {op}")
                self.assertNotEqual(c.get("noninteractive"), p["argv"], f"{p['manager']} {op}")
        self.assertNotIn("refresh", t["managers"]["pacman"]["commands"], "upt's `pacman -Sy` is not recorded as a refresh")

    def test_a_command_is_a_list_of_words_with_no_shell_syntax(self):
        """0002-packaging FR-006: a harness runs it without a shell"""
        t = table()
        bad = re.compile(r"[;|&<>`()\n]")
        for mid, m in t["managers"].items():
            for op, c in m.get("commands", {}).items():
                for key in ("argv", "noninteractive"):
                    for w in c.get(key, []):
                        self.assertIsNone(bad.search(w), f"{mid} {op} {key}: {w}")
                        self.assertTrue(w, f"{mid} {op} {key} has an empty word")
                if "noninteractive" in c:
                    self.assertTrue(c["argv"][0] == c["noninteractive"][0] or mid in ("apt",), f"{mid} {op} changes the program")

    def test_every_detecting_id_detects_one_family_and_omarchy_is_arch_by_id_like(self):
        """0002-packaging FR-007"""
        seen = {}
        for fid, f in table()["families"].items():
            for d in f["detect"]:
                if d != "*":
                    self.assertNotIn(d, seen, f"{d} detects both {seen.get(d)} and {fid}")
                    seen[d] = fid
        self.assertEqual(seen["arch"], "arch")
        self.assertEqual(seen["ubuntu"], "debian")
        self.assertNotIn("omarchy", seen, "Omarchy is detected by its ID_LIKE, not by a name of its own")

    def test_programs_are_named_once_and_required_ones_are_named_for_every_supported_family(self):
        """0002-packaging FR-008"""
        t = table()
        supported = [k for k, v in t["families"].items() if v["status"] == "supported" and v["installs_packages"]]
        required = {k: v for k, v in t["programs"].items() if v["tier"] == "required"}
        self.assertTrue({"git", "curl", "jq", "gh", "xz"} <= set(required))
        for name, p in required.items():
            for fid in supported:
                self.assertIn(fid, p["names"], f"{name} has no package for {fid}")
        self.assertEqual(t["programs"]["xz"]["names"], {"arch": "xz", "debian": "xz-utils"})
        self.assertEqual(t["programs"]["gh"]["names"], {"arch": "github-cli", "debian": "gh"})
        for name, p in t["programs"].items():
            for fid in p["names"]:
                self.assertIn(fid, supported, f"{name} names a package for {fid}, which is not supported")


@unittest.skipUnless(SH, "sh is not installed")
class Pins(unittest.TestCase):
    """The platforms and the pinned downloads (0002-packaging FR-014)."""

    def env(self):
        return dict(l.split("=", 1) for l in (COMMONS / "generated" / "pins.auto.env").read_text().splitlines() if l and not l.startswith("#"))

    def test_the_env_file_the_toml_and_the_script_agree(self):
        """0002-packaging FR-014"""
        t = tomllib.loads(TOML.read_text())
        env = self.env()
        script = (COMMONS.parent / "bin" / "archon-setup.sh").read_text()
        self.assertTrue(t["pins"] and t["platforms"])
        for name, pin in t["pins"].items():
            self.assertEqual(env[f"{pin['key']}_VERSION"], pin["version"], name)
            self.assertIn(f"{pin['key']}_VERSION={pin['version']}\n", script)
            for plat, digest in pin.get("sha256", {}).items():
                var = f"{pin['key']}_SHA256_{t['platforms'][plat]['pin_suffix']}"
                self.assertEqual(env[var], digest, var)
                self.assertRegex(digest, r"^[0-9a-f]{64}$")
                self.assertIn(f"{var}={digest}\n", script)

    def test_every_platform_names_an_os_and_a_processor(self):
        """0002-packaging FR-014"""
        for name, pl in tomllib.loads(TOML.read_text())["platforms"].items():
            self.assertRegex(name, r"^(linux|macos)-(x64|arm64)$")
            self.assertIn(pl["os"], ("linux", "macos"))
            self.assertIn(pl["processor"], ("x86_64", "aarch64"))


class ShellFragment(unittest.TestCase):
    """The shell fragment a script carries."""

    def call(self, code):
        return subprocess.run([SH, "-c", f'. "{SH_FRAGMENT}"\n{code}'], capture_output=True, text=True)

    def test_it_is_between_marks_posix_sh_and_free_of_shellcheck_warnings(self):
        """0002-packaging FR-012"""
        text = SH_FRAGMENT.read_text()
        self.assertTrue(text.startswith("# >>> packaging.auto >>>"))
        self.assertIn("# <<< packaging.auto <<<", text)
        self.assertIn("AUTO-GENERATED", text)
        self.assertEqual(subprocess.run([SH, "-n", str(SH_FRAGMENT)], capture_output=True, text=True).returncode, 0)
        if shutil.which("shellcheck"):
            p = subprocess.run(["shellcheck", "-s", "sh", "-S", "warning", str(SH_FRAGMENT)], capture_output=True, text=True)
            self.assertEqual(p.returncode, 0, p.stdout)

    def test_it_answers_what_a_script_asks_by_family(self):
        """0002-packaging FR-012"""
        out = self.call('echo "$(pm_family_of "omarchy arch")|$(pm_family_of "ubuntu debian")|$(pm_family_of fedora)|$(pm_family_of_uname Darwin)|$(pm_family_of nothing-known)"').stdout.strip()
        self.assertEqual(out, "arch|debian|redhat|macos|")
        facts = {
            "pm_manager debian": "apt", "pm_manager arch": "pacman", "pm_manager macos": "", "pm_manager redhat": "dnf",
            "pm_status debian": "supported", "pm_status redhat": "catalogued", "pm_assurance debian": "verified", "pm_assurance macos": "untested",
            "pm_install_words debian": "apt-get install -y", "pm_install_words arch": "pacman -S --needed --noconfirm", "pm_install_words redhat": "",
            "pm_environment debian": "DEBIAN_FRONTEND=noninteractive", "pm_admin_install arch": "pacman -S --needed {packages}", "pm_admin_install redhat": "dnf install {packages}",
            "pm_removal_hint debian": "sudo deluser --remove-home NAME", "pm_removal_hint arch": "sudo userdel -r NAME", "pm_installs_packages macos": "no",
            "pm_package debian xz": "xz-utils", "pm_package arch xz": "xz", "pm_package arch gh": "github-cli", "pm_package debian gh": "gh", "pm_package macos git": "",
            "pm_query_installed_words arch": "pacman -Qi", "pm_refresh_words debian": "apt-get update", "pm_refresh_words arch": "",
        }
        for call, want in facts.items():
            self.assertEqual(self.call(f"{call}").stdout, want, call)
        required = self.call("pm_programs required").stdout.split()
        self.assertTrue({"git", "curl", "jq", "gh", "xz", "ca-certificates", "tar", "unzip", "wget"} <= set(required), required)
        self.assertIn("ripgrep", self.call("pm_programs comfort").stdout.split())

    def test_the_fragment_and_the_toml_say_the_same(self):
        t = table()
        for fid in ("debian", "arch"):
            m = t["managers"][t["families"][fid]["preferred"]]
            self.assertEqual(self.call(f"pm_install_words {fid}").stdout, " ".join(w for w in m["commands"]["install"]["noninteractive"] if not w.startswith("{")))
            for name, p in t["programs"].items():
                self.assertEqual(self.call(f"pm_package {fid} {name}").stdout, p["names"].get(fid, ""), f"{fid} {name}")


@unittest.skipUnless(UV, "uv is not installed (it runs the generator)")
class Generator(unittest.TestCase):
    """The tool that reads the ontology."""

    def run_tool(self, root: Path, *args):
        return subprocess.run(["uv", "run", "--quiet", str(root / "tools" / "generate-packaging.py"), *args], capture_output=True, text=True)

    def test_a_term_with_no_definition_is_refused(self):
        """0002-packaging FR-001"""
        root = self.copy()
        voc = root / "ontology" / "supply-chain" / "packaging" / "packaging.ttl"
        voc.write_text(voc.read_text().replace('skos:definition "The program the package gives."@en', "", 1))
        p = self.run_tool(root)
        self.assertEqual(p.returncode, 2)
        self.assertIn("the term forProgram has no definition", p.stderr)

    def test_the_committed_files_are_what_the_ontology_makes(self):
        """0002-packaging FR-009, 0001-software-supply-chain FR-002"""
        p = self.run_tool(COMMONS, "--check")
        self.assertEqual(p.returncode, 0, p.stderr)

    def pins(self, root: Path) -> Path:
        return root / "ontology" / "supply-chain" / "packaging" / "pins.ttl"

    def test_a_bad_checksum_is_refused(self):
        """0002-packaging FR-014"""
        root = self.copy()
        f = self.pins(root)
        f.write_text(re.sub(r'pm:sha256 "[0-9a-f]{64}"', 'pm:sha256 "abc"', f.read_text(), count=1))
        p = self.run_tool(root)
        self.assertEqual(p.returncode, 2)
        self.assertIn("is not 64 lower-case hexadecimal digits", p.stderr)

    def test_a_pin_with_no_version_and_a_repeated_key_are_refused(self):
        """0002-packaging FR-014"""
        root = self.copy()
        f = self.pins(root)
        text = f.read_text().replace('pm:pinKey "FISH"', 'pm:pinKey "GH"', 1)
        text = re.sub(r'\n    pm:version "[^"]*"', "", text, count=1)
        f.write_text(text)
        p = self.run_tool(root)
        self.assertEqual(p.returncode, 2)
        self.assertIn("needs a name, a key and a version", p.stderr)

    def test_a_repeated_key_is_refused(self):
        """0002-packaging FR-014"""
        root = self.copy()
        f = self.pins(root)
        f.write_text(f.read_text().replace('pm:pinKey "FISH"', 'pm:pinKey "GH"', 1))
        p = self.run_tool(root)
        self.assertEqual(p.returncode, 2)
        self.assertIn("share the key GH", p.stderr)

    def test_a_checksum_for_nothing_is_refused(self):
        """0002-packaging FR-014"""
        root = self.copy()
        f = self.pins(root)
        f.write_text(f.read_text().replace("pm:forPlatform pmid:platform-linux-x64", "pm:forPlatform pmid:platform-nowhere", 1))
        self.assertIn("needs a pinned download, a platform and a SHA-256", self.run_tool(root).stderr)

    def copy(self) -> Path:
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, True)
        root = tmp / "commons"
        shutil.copytree(COMMONS, root, ignore=shutil.ignore_patterns("spec-kit", "__pycache__"))
        return root

    def test_it_makes_the_same_bytes_twice(self):
        """0002-packaging FR-009"""
        root = self.copy()
        self.assertEqual(self.run_tool(root).returncode, 0)
        first = (root / "generated" / "packaging.auto.toml").read_bytes(), (root / "generated" / "packaging.auto.sh").read_bytes()
        self.assertEqual(self.run_tool(root).returncode, 0)
        self.assertEqual(first, ((root / "generated" / "packaging.auto.toml").read_bytes(), (root / "generated" / "packaging.auto.sh").read_bytes()))
        self.assertEqual(first, (TOML.read_bytes(), SH_FRAGMENT.read_bytes()))

    def test_check_fails_where_a_generated_file_was_edited_by_hand(self):
        root = self.copy()
        f = root / "generated" / "packaging.auto.toml"
        f.write_text(f.read_text() + "# edited\n")
        p = self.run_tool(root, "--check")
        self.assertEqual(p.returncode, 1)
        self.assertIn("not what the ontology makes", p.stderr)

    def test_it_names_every_rule_the_ontology_breaks_and_writes_nothing(self):
        """0002-packaging FR-010"""
        root = self.copy()
        before = {p: p.read_bytes() for p in (root / "generated").iterdir()}
        fam = root / "ontology" / "supply-chain" / "packaging" / "families.ttl"
        text = fam.read_text()
        # a verified family with no where or when; two families claiming one ID; a supported family with no removal hint
        text = text.replace('    pm:verifiedOn "Debian 13 under WSL 2, by archon-bootstrap.sh and archon update, 2026-10-16" ;\n', "", 1)
        text = text.replace('pm:detectedBy "ubuntu" ;', 'pm:detectedBy "ubuntu" ;\n    pm:detectedBy "fedora" ;', 1)
        text = text.replace('    pm:removalHint "sudo userdel -r NAME" ;\n', "", 1)
        fam.write_text(text)
        p = self.run_tool(root)
        self.assertEqual(p.returncode, 2, p.stdout + p.stderr)
        for finding in ("is verified but says no where or when", "detects both", "has no removal hint"):
            self.assertIn(finding, p.stderr)
        self.assertEqual(before, {p: p.read_bytes() for p in (root / "generated").iterdir()}, "nothing is written")

    def test_a_forbidden_command_and_shell_syntax_are_refused(self):
        """0002-packaging FR-005, FR-006"""
        root = self.copy()
        man = root / "ontology" / "supply-chain" / "packaging" / "managers.ttl"
        text = man.read_text().replace('pm:template "apt install {packages}"', 'pm:template "apt install {packages}; rm -rf /"', 1)
        text = text.replace('pm:template "pacman -S {packages}"', 'pm:template "pacman -Sy"', 1)
        man.write_text(text)
        p = self.run_tool(root)
        self.assertEqual(p.returncode, 2)
        self.assertIn("holds shell syntax", p.stderr)
        self.assertIn("a command the ontology forbids", p.stderr)


