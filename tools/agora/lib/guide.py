def site_links(out: Path) -> list[str]:
    pages = sorted(str(p.relative_to(out)) for p in (out / "guide").glob("*.html")) if (out / "guide").is_dir() else []
    if (out / "index.html").is_file():
        pages.append("index.html")
    return link_findings(out, pages)
