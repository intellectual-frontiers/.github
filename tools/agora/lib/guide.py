def header(name: str = GENERATOR, rewrite: str = REWRITE) -> str:
    return (f"// Generated by the {name} generator from agora's code. Do not edit it by hand: run `agora {rewrite}` to rewrite it, "
            "`agora fresh` to prove it current.\n")


def _cell(s: Any) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def _block(text: str) -> list[str]:
    """A help topic's text as AsciiDoc: paragraphs as they are, and lines indented four spaces as listing blocks."""
    out: list[str] = []
    code: list[str] = []
    for line in text.split("\n"):
        if line.startswith("    "):
            code.append(line[4:])
            continue
        if code:
            out += ["----", *code, "----", ""]
            code = []
        out.append(line)
    if code:
        out += ["----", *code, "----"]
    return out


