def commands_chapter(reg: Registry) -> str:
    name = reg.name
    lines = [header(), "[#reference-commands]", "== Command reference", "",
             f"Every command, taken from the registry. `{name} command list` and `{name} command show COMMAND` say the same, and "
             f"`{name} help` is where the daily work is explained, step by step. A command is `{name} NOUN VERB [ID] [options]`; "
             "every command takes `--json`, and one that writes takes `--dry-run`.", "",
             "[cols=\"1,4\"]", "|===", "|Category |What it may do", ""]
    for c in CATEGORIES:
        lines += [f"|`{c}`", f"|{_cell(CATEGORY_HELP[c])}", ""]
    lines += ["|===", ""]
    by_noun: dict[str, list] = {}
    for c in sorted(reg.commands.values(), key=lambda c: c.id):
        by_noun.setdefault(c.noun or "", []).append(c)
    order = [""] + sorted(n for n in by_noun if n)
    for noun in order:
        cmds = by_noun.get(noun)
        if not cmds:
            continue
        if noun:
            lines += [f"=== {noun}", "", _cell(reg.nouns.get(noun, "")), ""]
        else:
            lines += ["=== Repository-wide commands", "", "These take no noun.", ""]
        lines += ['[cols="4,2,2,4"]', "|===", "|Usage |Category |Where it runs |What it does", ""]
        for c in cmds:
            d = command_data(reg, c)
            lines += [f"|`{_cell(d['usage'])}`", f"|{c.category}", f"|{_cell(', '.join(d['surfaces']))}", f"|{_cell(c.help)}", ""]
        lines += ["|===", ""]
    lines += ["=== Typed arguments", "",
              "A value that fails its type is an error that names the type and gives examples.", "",
              '[cols="1,3,3"]', "|===", "|Type |Is |Examples", ""]
    for t in sorted(reg.types.values(), key=lambda t: t.name):
        n, doc, eg = _type_row(t)
        lines += [f"|`{n}`", f"|{_cell(doc)}", f"|{_cell(eg)}", ""]
    lines += ["|===", ""]
    return "\n".join(lines)


def _type_row(t: ArgType) -> tuple[str, str, str]:
    if isinstance(t, Choice):
        eg = ", ".join(t.choices(None))
    elif isinstance(t, Pattern):
        eg = ", ".join(t.examples(None))
    else:
        eg = "a value `LIST` offers"
    return t.name, t.doc, eg.replace("LIST", "the noun's list command")


def checks_chapter(reg: Registry) -> str:
    name = reg.name
    suites = {s: v["sections"] for s, v in sorted(reg.suites.items())}
    lines = [header(), "[#reference-checks]", "== Checks, suites and generators", "",
             f"Every check runs through `{name} check [SECTION...]`. With nothing named it runs every section; `--suite` runs a named set, "
             f"`--scope` limits a section to one resource, and `--changed` runs only the sections whose watched files changed. A section "
             f"that cannot run says why and is skipped, never passed, and the run exits 3. `{name} help check` says which to run before "
             "you push.", "", "=== Sections", "", '[cols="1,5,1,2"]', "|===", "|Section |What it checks |Scope |Suites", ""]
    for s in sorted(reg.sections.values(), key=lambda s: s.name):
        in_suites = ", ".join(f"`{k}`" for k, v in suites.items() if any(n.split(" ")[0] == s.name for n in v)) or "none"
        lines += [f"|`{s.name}`", f"|{_cell(s.help)}", f"|{s.scope or 'none'}", f"|{in_suites}", ""]
    lines += ["|===", "", "=== Suites", "", '[cols="1,4"]', "|===", "|Suite |Sections", ""]
    for k, v in suites.items():
        opts = reg.suites[k].get("options", {})
        tail = "".join(f" (with --{o} {val})" for o, val in opts.items())
        lines += [f"|`{k}`", f"|{', '.join(f'`{n}`' for n in v)}{tail}", ""]
    lines += ["|===", "", "=== Generators", "",
              f"A generator writes tracked files from their sources. `{name} fresh` proves each current and writes nothing; when one is "
              "stale it names the command that rewrites it.", "", '[cols="1,3,2,2"]', "|===", "|Generator |What it writes |Rewritten by |Files", ""]
    for g in sorted(reg.generators.values(), key=lambda g: g.name):
        outs = ", ".join(f"`{o}`" for o in g.outputs)
        lines += [f"|`{g.name}`", f"|{_cell(g.help)}", f"|`{name} {g.command}`" if g.command else "|", f"|{outs}", ""]
    lines += ["|===", ""]
    return "\n".join(lines)


def help_chapter(reg: Registry) -> str:
    name = reg.name
    lines = [header(), "[#reference-help]", "== Help topics", "",
             f"The daily work is explained by `{name} help`. This chapter is the same text, taken from the same code, so that it cannot "
             "drift. In VS Code, the Learn command shows these pages with a button for each step.", ""]
    from agora.core.resource import Call
    for t in sorted(reg.topics.values(), key=lambda t: t.name):
        body = t.body()
        lines += [f"[#help-{t.name}]", f"=== {t.name}", "", f"_{t.summary}_", "", body["plain"], ""]
        for heading, text in body["sections"]:
            lines += [f"==== {heading}", "", *_block(text), ""]
        if body["steps"]:
            lines += ["==== Steps", ""]
            for s in body["steps"]:
                line = Call(s.command, dict(s.fields)).cli(reg, name)
                lines.append(f"* {s.label}: `{line}`" + (f" ({s.note})" if s.note else ""))
            lines.append("")
    return "\n".join(lines)


